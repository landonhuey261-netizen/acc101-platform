      "html": "<p>Most drugs work by fitting into <strong>receptors</strong> — protein shapes on or inside cells that act like locks. The body's own chemical messengers are the keys that normally fit those locks. A drug is a copy of a key: it fits the lock and either turns it or jams it. A drug that fits a receptor and <em>turns it on</em> is called an <strong>agonist</strong>. A drug that fits a receptor and <em>blocks it</em> is called an <strong>antagonist</strong>.</p>\n<p>Epinephrine is an agonist: it fits the receptors on blood vessels and airways and switches them on, so vessels tighten and airways open — exactly what anaphylaxis needs. Naloxone is an antagonist: it fits the opioid receptors in the brain and blocks them, so opioids cannot act there — which is why it reverses an opioid overdose. Aspirin works differently: it permanently switches off an enzyme (COX-1) inside platelets, so the platelets cannot make the chemical that makes them clump. Because platelets cannot make new enzyme, the effect lasts for the life of the platelet, about 7 to 10 days.</p>\n<p>One more idea matters for the field: <strong>dose-response</strong>. A tiny dose may do nothing, a normal dose does the job, and a large dose causes harm. There is no drug that is safe at every dose. The therapeutic window is the gap between the dose that helps and the dose that harms — and for some drugs that gap is wide, while for others it is narrow. EMT medications are chosen, in part, because their doses are fixed and their windows are forgiving at those doses.</p>"
