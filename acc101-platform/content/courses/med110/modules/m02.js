      "html": "<p>The journey has four stages, remembered by the letters <strong>ADME</strong>. <strong>Absorption</strong> is how the drug gets from where you put it into the bloodstream. A tablet swallowed whole must dissolve in the stomach and pass through the gut wall; a tablet dissolved under the tongue is absorbed through the rich blood vessels of the mouth and skips the stomach entirely. That is why nitroglycerin goes under the tongue and aspirin is chewed — both need to work in minutes, not in half an hour.</p>\n<p><strong>Distribution</strong> is how the drug travels in the blood to the tissues where it works. Blood carries the drug everywhere, but not every tissue gets the same amount: some drugs bind to proteins in the blood, some dissolve into fat, and some cannot cross into the brain. <strong>Metabolism</strong> is how the body breaks the drug down, mostly in the liver, turning it into pieces that are easier to get rid of. <strong>Excretion</strong> is how those pieces leave the body, mostly in the urine through the kidneys. A patient with a weak liver or weak kidneys clears drugs more slowly, which is one reason the same dose can be safe for one person and too much for another.</p>\n<p>Route decides speed. From fastest to slowest, the routes an EMT meets are: intravenous (straight into a vein — paramedic and hospital territory, not EMT), inhaled or under the tongue (minutes), intramuscular injection into the thigh (minutes, as with an epinephrine auto-injector), and swallowed (slowest, because of the stomach and liver). When a patient is crashing, minutes matter, and the route is part of the drug's design.</p>"
