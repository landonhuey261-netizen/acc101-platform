      "heading": "Albuterol: The Rescue Inhaler",
      "html": "<p>Albuterol is a <strong>bronchodilator</strong> — a drug that opens the airways in the lungs. It is used for asthma and other conditions that cause wheezing: the airways tighten, air cannot get out easily, and the patient wheezes and struggles to breathe. Albuterol relaxes the smooth muscle around the airways, so they open and the patient can breathe more easily. It is given through a <strong>metered-dose inhaler (MDI)</strong> — a small canister that delivers one measured puff of drug at a time.</p>\n<p>An EMT usually <strong>assists</strong> the patient with their <em>own</em> prescribed inhaler. The steps are: confirm it is the patient's own inhaler and not expired, shake the inhaler, have the patient sit upright and breathe out fully, place the mouthpiece in the mouth with a good seal, and have the patient breathe in slowly and deeply while you (or the patient) press the canister once to release one puff. The patient then holds their breath for about 10 seconds if they can, then breathes out slowly. A <strong>spacer</strong> (a holding chamber) makes this much easier: the puff goes into the chamber first, and the patient breathes it in at their own pace — more of the drug reaches the lungs instead of hitting the back of the throat.</p>\n<p>The usual assist is one to two puffs, with about 30 to 60 seconds between puffs, as the protocol allows — and only for a patient whose wheezing is from a condition albuterol treats. Albuterol must not be given to a patient with chest pain of cardiac origin as a substitute for cardiac care, and it does not help a patient whose airway is blocked by something else. Side effects include a fast heartbeat, shaking hands, and nervousness — the patient may feel jittery after a puff, and that is expected. If the patient is getting worse despite the inhaler, or cannot speak in full sentences, or is becoming drowsy, call for advanced help immediately: a rescue inhaler is not a substitute for a hospital.</p>"
