      "heading": "Oral Glucose: Low Blood Sugar",
      "html": "<p>Glucose is sugar, and the brain runs on it. When blood sugar falls too low — a condition called <strong>hypoglycemia</strong> — the brain is starved, and the patient becomes confused, shaky, sweaty, weak, or aggressive, and may eventually lose consciousness or have a seizure. Low blood sugar is most common in people with diabetes who take insulin or certain diabetes medicines, especially if they skipped a meal, exercised hard, or took too much medicine. It can also happen in people who have not eaten for a long time or who have been drinking alcohol.</p>\n<p><strong>Oral glucose</strong> is a sugary gel or liquid carried on many ambulances. It is given by mouth to a patient with low blood sugar who is <em>conscious and able to swallow safely</em>. The gel is squeezed between the cheek and the gum, or the patient drinks the liquid, and the sugar is absorbed quickly — the patient often improves within minutes. It is a simple drug with a simple job: put sugar back into a brain that is running out of it.</p>\n<p>The rule that matters most: <strong>oral glucose is only for a patient who is awake and can swallow.</strong> A patient who is unconscious, confused to the point of not being able to swallow, or having a seizure must never be given anything by mouth — they can choke, and the gel can go into the lungs instead of the stomach. For those patients, the answer is rapid transport and advanced care (in the hospital, glucose can be given intravenously). If you are not sure the patient can swallow safely, do not give it — call for help and transport fast.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Oral glucose is for the awake patient who can swallow. An unconscious patient, a seizing patient, or a patient who cannot swallow safely gets nothing by mouth — they get rapid transport and advanced care.</div>"
