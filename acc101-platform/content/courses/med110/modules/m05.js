      "html": "<p>Epinephrine is the body's own fight-or-flight chemical, made by the adrenal glands, and as a drug it is an <strong>agonist</strong> — it switches on receptors throughout the body. In anaphylaxis it does three things at once, which is why it is the only drug that treats the whole reaction. First, it constricts blood vessels, which raises blood pressure back up. Second, it relaxes the smooth muscle around the airways, which opens the breathing passages. Third, it reduces the leaking of fluid from blood vessels, which slows the swelling.</p>\n<p>No other drug does all three. Antihistamines such as diphenhydramine can help with itching and hives, but they do not open airways or raise blood pressure — and they act far too slowly to save a patient in anaphylaxis. That is why the rule is simple: <strong>epinephrine first</strong>. An antihistamine is never a substitute, and giving one first while waiting is a dangerous delay.</p>\n<p>Epinephrine's effect is fast but short: it starts working in minutes and fades within tens of minutes. That is why a patient who received epinephrine still needs a hospital urgently — the reaction can come back (a second wave, called a biphasic reaction) hours later, and only a hospital can watch for it and treat it.</p>"
