      "heading": "The Delivery Devices",
      "html": "<p>There are four devices you will meet most often. The <strong>nasal cannula</strong> is two soft prongs that sit in the nostrils, held by tubing looped over the ears. It is used at low flow rates, usually 1 to 6 liters per minute, and delivers a modest increase in oxygen. Patients can eat, drink, and talk with it in place, which makes it the most comfortable device — and the right choice for a patient who needs a little help, not a lot.</p>\n<p>The <strong>simple face mask</strong> covers the nose and mouth and is used at 6 to 10 liters per minute, delivering more oxygen than a cannula. The <strong>non-rebreather mask</strong> is the high-oxygen device: it has a reservoir bag that fills with oxygen and one-way valves that keep exhaled air out. It is used at 10 to 15 liters per minute, with the bag kept inflated, and it can deliver the highest oxygen concentration of any mask an EMT uses. It is the device for the patient who is seriously short of oxygen. A <strong>bag-valve mask</strong> (BVM) is different: it is used to breathe <em>for</em> a patient who is not breathing adequately, and it can be connected to oxygen. That skill belongs to hands-on training, and this module only introduces it — you must learn it in person, with an instructor, before ever using it on a patient.</p>\n<p>Choosing the device is a judgment call guided by protocol: a mildly short-of-breath patient gets a cannula; a patient with very low oxygen or severe distress gets a non-rebreather. The device is not a trophy — the highest-oxygen device is not automatically the best choice, and the protocol and the patient's numbers tell you what to use.</p>"
