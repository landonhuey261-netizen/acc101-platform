      "html": "<p>Aspirin (acetylsalicylic acid) is an <strong>antiplatelet</strong> drug. Inside each platelet there is an enzyme called COX-1, which makes a chemical called thromboxane A2 — the signal that tells platelets to clump together. Aspirin permanently switches off COX-1. With no thromboxane, the platelets cannot clump properly, and the clot grows more slowly.</p>\n<p>The word \"permanently\" matters. Platelets have no nucleus, so they cannot make new COX-1 enzyme. Once aspirin switches it off, that platelet is disabled for the rest of its life — about 7 to 10 days. That is why a single dose of aspirin has an effect that lasts for days, and why a patient who takes aspirin every day has platelets that are always partly disabled. It is also why aspirin increases bleeding risk: the same mechanism that slows a bad clot also slows the good clotting that stops bleeding from a cut.</p>\n<p>Aspirin does <em>not</em> dissolve a clot that is already there. It only slows the growth of a new one. Dissolving a clot requires hospital drugs or a procedure. Aspirin is a holding action, not a cure — but in a heart attack, a holding action that starts in the first minutes can save heart muscle and save a life. Studies of early aspirin in suspected heart attacks show it reduces deaths, which is why it is given as early as possible.</p>"
