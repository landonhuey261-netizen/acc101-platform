      "html": "<p>Before any drug is given, a trained provider runs a checklist called the <strong>five rights</strong> of medication administration. They are simple, they are old, and they still catch most errors before they happen. <strong>Right patient:</strong> is this the right person? Check their name and a second identifier — never guess, and never give a drug to a patient you have not identified. <strong>Right drug:</strong> is this the right medication? Read the label, and watch out for look-alike, sound-alike names — drugs whose names are nearly identical but do completely different things.</p>\n<p><strong>Right dose:</strong> is this the right amount? Check the number and the unit — milligrams are not micrograms, and a misplaced decimal point can turn a safe dose into a dangerous one. <strong>Right route:</strong> is this the right way in? A drug meant to be chewed must not be swallowed whole; a drug meant to go under the tongue must not be swallowed; a drug meant for the thigh must not go anywhere else. <strong>Right time:</strong> is this the right moment? Some drugs are given once, some are repeated at set intervals, and some must not be repeated too soon.</p>\n<div class=\"callout\"><strong>Memory hook:</strong> Patient, Drug, Dose, Route, Time — five checks, every drug, every time. If any one of them is wrong or unclear, stop. A drug that is not given can be given later; a drug that is given wrong cannot be taken back.</div>"
