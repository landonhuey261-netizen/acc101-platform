      "html": "<p>Chest pain from the heart happens when the heart muscle is not getting enough blood. The heart is a muscle, and like any muscle it needs oxygen. The coronary arteries carry blood to the heart muscle itself. When one of those arteries narrows — usually because of a fatty buildup called plaque — or when a clot blocks it, part of the heart muscle is starved of oxygen. That starvation causes pain: a pressure, squeezing, or heaviness in the center of the chest, which may spread to the jaw, the left arm, or the back. It may come with sweating, nausea, or shortness of breath.</p>\n<p>There are two situations you will meet. <strong>Angina</strong> is chest pain that comes when the heart works harder (such as climbing stairs) and eases with rest — the artery is narrowed but not fully blocked. A <strong>heart attack</strong> (myocardial infarction) is when the artery is blocked and heart muscle starts to die. The pain is often more severe and does not ease with rest. As an EMT you do not diagnose which one it is — that takes a hospital, blood tests, and an ECG. Your job is to recognize chest pain that could be cardiac, treat it by protocol, and get the patient to a hospital fast. Every minute of delay means more heart muscle lost.</p>\n<div class=\"callout\"><strong>Key idea:</strong> You do not need to diagnose angina versus heart attack in the field. If the chest pain could be cardiac, treat it as cardiac: oxygen if indicated, aspirin and nitroglycerin where protocol allows, and rapid transport. Time is heart muscle.</div>"
