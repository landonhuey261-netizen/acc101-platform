      "heading": "How Nitroglycerin Works",
      "html": "<p>Nitroglycerin is a <strong>nitrate</strong> — a drug that widens blood vessels. It works in two ways that both help a starving heart. First, it widens the veins, so less blood returns to the heart — the heart has less work to do, so it needs less oxygen. Second, it widens the coronary arteries themselves, so more blood can reach the heart muscle. Together, less work plus more blood flow usually eases the pain within minutes.</p>\n<p>Nitroglycerin does not dissolve a clot. That is aspirin's job (slowing clot growth) and the hospital's job (dissolving or removing the clot). Nitroglycerin buys time and relieves pain; it does not fix the blockage. That is why a patient whose pain does not ease after nitroglycerin is still an emergency — and why you keep reassessing.</p>\n<p>The dose is <strong>0.4 mg</strong>, given as one tablet or one spray <strong>under the tongue (sublingual)</strong>. Under the tongue it is absorbed straight into the bloodstream and starts working in 1 to 3 minutes. It must not be swallowed or chewed — swallowed, it goes to the stomach and liver first and works far too slowly. The patient should be sitting or lying down, because nitroglycerin lowers blood pressure and can make a standing patient dizzy or faint.</p>"
