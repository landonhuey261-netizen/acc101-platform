      "heading": "How Insurance Works: Pooling Risk",
      "html": "\n<p>Insurance works by <strong>pooling</strong>: many people pay a <strong>premium</strong>, and the pool pays the few who suffer a loss. The insurer's skill is pricing the premium — it must cover the expected losses, the cost of running the pool, and a profit — and the customer's skill is buying the right amount of coverage for the risks that would actually hurt. A <strong>deductible</strong> is the amount the customer pays first on each claim; a higher deductible lowers the premium, because the customer bears the small losses and the insurer only bears the large ones. <strong>Coverage limits</strong> cap what the insurer will pay; a limit below the true value of what is insured leaves the firm underinsured when the loss is large.</p>\n<p>Insurance does not remove risk; it changes who pays for it, and at what price. A firm that insures every small risk pays more in premiums than it would have paid in losses, because the insurer adds its costs and profit. A firm that insures nothing saves the premiums and risks everything on one bad event. The discipline is to insure the losses that would end the business, and to retain or reduce the rest.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Insurance pools risk: many pay premiums so the few who suffer a loss are paid. Insure the losses that would end the business; retain or reduce the rest.</div>\n"
