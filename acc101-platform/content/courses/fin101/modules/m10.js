      "html": "\n<p>The main kinds of business insurance are: <strong>property insurance</strong> (buildings, equipment, and inventory against fire, theft, and storm); <strong>general liability insurance</strong> (injury or damage the business causes to others — a customer slipping in the shop, a product that harms someone); <strong>professional liability insurance</strong> (claims that the firm's advice or service caused a loss); <strong>workers' compensation insurance</strong> (injuries to employees at work, required in most states); <strong>business interruption insurance</strong> (lost income while the business cannot operate after a covered loss); and <strong>commercial auto insurance</strong> (vehicles used for the business). A home-based business is not covered by a homeowner's policy for its business activities — a gap that surprises many new owners.</p>\n<p>The coverage must match the real risk. A shop with $200,000 of equipment needs a property limit of at least $200,000, not $100,000; a business with delivery vans needs commercial auto, not personal auto. The cheapest policy is often the one with the lowest limit and the highest deductible — and the most expensive policy is the one that does not pay when the loss happens.</p>\n<div class=\"formula\">Worked example: a shop faces a 1-in-100 chance of a $50,000 fire loss each year. Expected loss = $50,000 × 0.01 = $500 a year. A policy costing $800 a year with a $1,000 deductible transfers the risk for $300 more than the expected loss — the price of certainty.</div>\n"
