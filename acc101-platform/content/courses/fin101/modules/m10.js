      "heading": "Risk Management: Four Ways to Handle a Risk",
      "html": "\n<strong>Risk management</strong> is identifying what could go wrong, judging how likely it is and how bad it would be, and choosing what to do about it. There are four responses. <strong>Avoid</strong> the risk: do not do the risky thing at all — a shop that refuses to deliver in a storm avoids the accident risk, and also loses the delivery sales. <strong>Reduce</strong> the risk: make it less likely or less bad — training, maintenance, safety checks, backups. <strong>Retain</strong> the risk: accept it and pay for it when it happens, usually by setting aside cash — sensible for small, frequent losses. <strong>Transfer</strong> the risk: pay someone else to bear it, usually through insurance — sensible for rare, large losses the firm could not survive.\n<p>The choice follows two questions: how likely is the loss, and how big would it be? Small, likely losses are best retained or reduced (insurance would cost more than the losses). Large, unlikely losses are best transferred (one fire could end the business). The worst error is to retain a large, unlikely loss because it has not happened yet — that is not risk management, it is gambling with the firm's existence.</p>\n<ul>\n<li><strong>Avoid:</strong> do not do the risky thing.</li>\n<li><strong>Reduce:</strong> make it less likely or less bad.</li>\n<li><strong>Retain:</strong> accept it and pay when it happens.</li>\n<li><strong>Transfer:</strong> pay someone else (insurance) to bear it.</li>\n</ul>\n"
