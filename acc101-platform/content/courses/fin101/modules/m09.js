      "html": "\n<p>Debt and equity trade risk against control. <strong>Debt</strong> is cheaper — interest is tax-deductible and lenders accept a lower return than shareholders — and the owners keep full control, because lenders get no vote. But debt must be repaid on schedule, with interest, in good years and bad; too much of it, and a bad year becomes a bankruptcy. <strong>Equity</strong> is more expensive — shareholders demand a higher return for bearing the most risk — and it dilutes control, because new owners get a say. But equity never has to be repaid on a schedule, and dividends can be cut in a bad year without defaulting. The <strong>optimal capital structure</strong> is the mix that balances the cheapness of debt against the risk of having to repay it.</p>\n<p>The tax shield is debt's hidden advantage: interest is deductible, so a firm borrowing at 6% with a 25% tax rate really pays 4.5% (Module 6). Equity has no equivalent shield — dividends are paid from after-tax profit. That is why firms borrow at all, even though equity is safer. But the shield is worthless if the firm has no profit to shield, and the interest is due whether or not there is profit — which is why the trade-off is real and not just arithmetic.</p>\n<ul>\n<li><strong>Debt:</strong> cheaper, tax-deductible, owners keep control — but must be repaid on schedule, in good years and bad.</li>\n<li><strong>Equity:</strong> no repayment schedule, dividends can be cut — but more expensive and dilutes control.</li>\n<li><strong>Optimal mix:</strong> the cheapest blend that the firm can still repay in a bad year.</li>\n</ul>\n"
