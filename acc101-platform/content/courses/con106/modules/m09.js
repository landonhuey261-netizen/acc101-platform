      "html": "<p>Sheathing is the structural skin over the frame — panels nailed to the outside of the walls and to the floors — and it does three jobs at once. It braces the frame against racking, the sideways force of wind and earthquakes that would push a wall over like a folding card table. It gives the siding and the roofing a solid base to nail to. And it closes the building, keeping the weather out while the rest of the work goes on inside.</p>\n<p>Without sheathing, a framed wall is a rectangle of sticks held by nails, and it can fold sideways under a modest push. With sheathing nailed to it, the same wall is a rigid panel that cannot rack. That is why sheathing is structural, not decorative, and why the nailing pattern is specified — the nails are what transfer the wind load from the panel into the frame.</p>\n<p>On floors, the subfloor is the sheathing, and it braces the floor the same way: it ties the joists together, keeps them from rolling over, and gives the floor its stiffness. On walls, the sheathing also ties the top and bottom plates together, so the wall works as one unit from the foundation to the roof.</p>"
