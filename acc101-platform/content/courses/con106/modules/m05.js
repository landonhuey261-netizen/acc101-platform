      "html": "<p>Subfloor is glued and fastened: a bead of subfloor adhesive on each joist, then the panel set in place and nailed or screwed down. The glue does two jobs: it bonds the panel to the joist so the two act as one, and it fills the small gaps that cause squeaks. A floor that is only nailed will squeak as the nails work loose; a floor that is glued and fastened stays quiet.</p>\n<p>Fasteners go around the panel edges every 6 inches and in the field — the joists in the middle of the panel — every 12 inches, or as the panel manufacturer specifies. Nails are usually 8d ring-shank or screws of the right length — long enough to go through the panel and well into the joist, usually about 2 inches into the joist. Ring-shank nails grip far better than smooth nails, and screws grip best of all, which is why screws are the choice for a squeak-free floor.</p>\n<p>The panels are set with a small gap — about 1/8 inch — between them, at the edges and the ends, so they have room to expand with moisture. Panels butted tight swell against each other and buckle up at the joints. The gap is set with a spacer — a nail or a scrap of panel — and it disappears under the finish floor.</p>"
