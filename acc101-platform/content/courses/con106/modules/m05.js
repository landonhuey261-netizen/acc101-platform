      "html": "<p>The subfloor is the structural panel layer over the joists — the deck that the walls stand on and the finished floor sits over. The two materials are plywood and oriented strand board (OSB). Plywood is layers of wood veneer glued with the grain alternating, strong and stable, and it holds up better when it gets wet. OSB is strands of wood pressed and glued into a panel, cheaper and very flat, and it is the standard subfloor on most houses today.</p>\n<p>Thickness depends on the joist spacing: 3/4-inch tongue-and-groove plywood or OSB is the standard for joists at 16 inches on center, and it is the thickness the span tables assume. At 24-inch spacing, the subfloor goes thicker — often 7/8 inch — or the floor will feel bouncy between joists. The panels are rated for their span, and the rating is stamped on the sheet: a panel rated 24/16, for example, is rated for 24-inch roof spacing and 16-inch floor spacing.</p>\n<p>Subfloor panels are also rated for exposure: Exposure 1 panels can take the rain during construction and dry out, while Exterior panels are bonded to take permanent wetting. A subfloor that gets soaked during framing and never dries will swell at the edges and stay swollen — the finished floor telegraphs every swollen joint. The panels are covered as soon as the roof is on, and wet panels are allowed to dry before the finish floor goes down.</p>"
