      "heading": "Tongue-and-Groove & Staggering",
      "html": "<p>Subfloor panels have tongue-and-groove edges: a tongue on one edge fits into a groove on the next, locking the panels together so one cannot deflect without its neighbor. That joint is what makes a 3/4-inch subfloor feel solid between joists — the load is shared across the joint instead of resting on a single panel edge. Square-edge panels need blocking under every joint, which is why tongue-and-groove is the standard.</p>\n<p>Joints are staggered: the end joint of one row falls in the middle of the panel in the next row, like brickwork. Staggering spreads the joints so no line of weakness runs across the floor, and it keeps the floor flat — a row of joints in a straight line is a hinge the floor can bend on. The stagger also means the panels are cut in a pattern, and the offcuts start the next row.</p>\n<p>The panels run with their long direction across the joists — perpendicular to them — so each panel crosses as many joists as possible. A panel run parallel to the joists would span between only two of them and sag. The layout is planned so the panel ends land on joists, and any panel that does not reach a joist gets blocking under its end.</p>"
