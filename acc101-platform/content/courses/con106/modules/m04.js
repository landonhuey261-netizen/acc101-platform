      "html": "<p>Span is the distance a joist covers between its supports — from the sill to the girder, or from wall to wall. The longer the span, the more the joist bends under load and the more it bounces underfoot. The limits on span are deflection — how much the joist bends — and strength — how much load it can carry before it fails. Floors are usually limited by deflection, not strength: a floor that is strong enough but bouncy is still a bad floor.</p>\n<p>The code’s deflection limit for floors is L/360: the joist may bend no more than its span divided by 360 under live load. For a 16-foot span, that is 192 inches divided by 360, or about 1/2 inch. That sounds like a lot until you stand on it — half an inch of bounce underfoot feels like a trampoline. The limit keeps floors feeling solid, not just standing up.</p>\n<p>Span depends on four things: the joist’s size, its spacing, its species and grade, and the load. A deeper joist spans farther than a shallow one; closer spacing spans farther than wide spacing; stronger species span farther; and a heavier load shortens the span. Change any one, and the span changes with it.</p>"
