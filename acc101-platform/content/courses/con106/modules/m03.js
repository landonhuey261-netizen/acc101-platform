      "html": "<p>Floor layout starts with the sill: level, square, and fastened. Then the rim joists — also called band joists — go on: boards on edge around the perimeter of the floor, nailed to the sill, that close the ends of the joists and give the subfloor its edge. The rim is set flush with the outside of the foundation, and its top is level with the joists, so the subfloor has a flat surface all the way across.</p>\n<p>Inside the perimeter, the girder runs down the middle: a beam — often a built-up beam of two or three 2×10s or 2×12s, or an LVL — that supports the joists at midspan and is itself supported by posts down to footings. The girder cuts the joist span in half, which is what lets a 24-foot-wide house use 12-foot joists. The girder must be level and its posts must sit on footings, not on the slab alone.</p>\n<p>The joists are then laid out on the sill and the girder at their spacing — usually 16 inches on center — marked with a tape and a square, crown up, and nailed to the rim and the girder. The layout is marked on the sill and the rim before any joist goes in, so the spacing is consistent from one end to the other. A joist that is off by an inch is a subfloor joint that misses its support.</p>"
