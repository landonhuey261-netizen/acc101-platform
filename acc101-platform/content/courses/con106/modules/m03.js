      "html": "<p>The sill plate is the first piece of wood in the house: a flat board — usually a 2×6 or 2×8 — laid on top of the foundation wall, that the whole floor frame sits on. It does three jobs: it spreads the load of the frame evenly onto the concrete, it gives the frame a level surface to start from, and it is the piece the anchor bolts hold down, tying the wood house to the concrete foundation against wind uplift.</p>\n<p>The sill must be pressure-treated lumber, because it sits directly on concrete, and concrete wicks moisture. Untreated wood on concrete rots, and a rotted sill lets the whole frame settle. Pressure treatment forces preservative deep into the wood, and the treatment is rated for ground contact — the stamp on the board says so. Cut ends of treated lumber are brushed with preservative, because the cut exposes untreated wood inside.</p>\n<p>A foam sill sealer goes between the sill and the concrete: a thin gasket that seals the joint against air and insects and takes up the small unevenness of the concrete. The sill is leveled with shims where the foundation is low, and any gap under the sill is filled with grout or shims so the plate bears fully. A sill that rocks on a high spot is a floor that rocks with it.</p>"
