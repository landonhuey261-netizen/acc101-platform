      "html": "<p>Ceiling joists are sized from a span table, like floor joists, but with the ceiling load instead of the floor load. A 2×6 ceiling joist at 16 inches on center spans about 10 feet with a light ceiling load; a 2×8 spans about 13 feet; a 2×10 spans about 16 feet. The exact span depends on the species, the grade, and the load — including whether the attic will store anything, which adds a live load the table must account for.</p>\n<p>The spacing is usually 16 inches on center, matching the studs and the rafters below and above, so the loads line up: rafter to joist to stud to foundation. Where the rafters are spaced 24 inches on center, the ceiling joists are often spaced 24 inches too, so each rafter lands on a joist and the tie is direct.</p>\n<p>The joists are crowned up, like floor joists, so the ceiling does not sag visibly. A ceiling joist with its crown down will show a sag in the drywall that no amount of finishing can hide. The crown is checked with the eye down the length of the board before it is nailed.</p>"
