      "html": "<p>Excavation is measured and paid for by volume, in cubic yards. The math is simple: volume in cubic feet equals length × width × depth, and one cubic yard equals 27 cubic feet. A basement 36 feet by 27 feet and 9 feet deep is 36 × 27 × 9 = 8,748 cubic feet, which is 8,748 ÷ 27 = 324 cubic yards. That is the bank volume — the dirt as it sits in the ground.</p>\n<p>Dirt swells when it is dug: the same soil takes up more room loose in a truck than it did in the ground, because digging fluffs air into it. Clay can swell 25% or more, so 324 bank yards become about 405 loose yards, and at 12 yards per truck that is 34 truckloads instead of 27. Estimators who forget swell order too few trucks and the job stalls with a pile of dirt and no truck to take it.</p>\n<p>The volume also decides the cost of hauling and the size of the spoil pile. A cubic yard of soil weighs roughly 2,000 to 2,700 pounds depending on type and moisture, so a 324-yard basement dig is on the order of 350 tons of material. Knowing the number before the machine arrives is the difference between a planned job and a surprise.</p>"
