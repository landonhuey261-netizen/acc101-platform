      "heading": "The Four Protective Systems",
      "html": "<p>Sloping cuts the trench walls back at an angle so the soil cannot fall on the workers. The angle depends on the soil type, as above, and the slope must run from the bottom of the trench to the top — a slope that stops halfway leaves an unsupported face. Sloping needs room, which is why it is the choice on open sites and not on tight city lots.</p>\n<p>Benching cuts the walls in steps, like a staircase, with each step no higher than the soil allows. Benching is allowed in Type A and Type B soils but never in Type C, where the steps themselves can crumble. Like sloping, benching needs space, and the steps must be cut to the right dimensions for the soil.</p>\n<p>Shoring holds the walls up with supports: timber or aluminum panels pressed against the walls by hydraulic struts or screw jacks. Shoring is the choice where there is no room to slope — beside a road or a building — because it keeps the trench narrow. It must be installed from outside the trench, from the top down, and removed from the bottom up, so nobody is ever in an unprotected trench.</p>\n<p>Shielding does not hold the wall up; it protects the workers inside when the wall fails. A trench box — a steel or aluminum box lowered into the trench — gives the crew a safe space to work in while the walls around it do what they will. The box must be rated for the depth, it must extend above the trench edge, and workers must stay inside it. Shielding is not a substitute for a box that fits: a box too small for the trench leaves workers exposed at the ends.</p>"
