      "html": "<p>Protection starts with the soil. OSHA groups soils into three types. Type A is the most stable: cohesive clay with high strength, the kind that holds a vertical face. Type B is medium: less cohesive soils, including some clays and silts, and previously disturbed soil. Type C is the least stable: granular soils like sand and gravel, submerged soil, and soil that is already slumping — the kind that will not stand on its own.</p>\n<p>The soil type decides how steep a slope can be. In Type A soil, a trench wall can be sloped at 3/4 to 1 — for every foot down, the wall goes back 3/4 of a foot. In Type B, the slope is 1 to 1 — one foot back for every foot down. In Type C, it is 1-1/2 to 1 — a foot and a half back for every foot down, a much flatter, wider cut. The weaker the soil, the flatter the slope.</p>\n<p>The competent person classifies the soil before anyone enters, using tests like the thumb test — pressing the soil to feel its strength — and the pocket penetrometer, which measures how much pressure the soil resists. If the classification is in doubt, the soil is treated as the weaker type. Guessing the soil is strong is how trenches fail.</p>"
