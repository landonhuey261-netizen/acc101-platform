      "html": "<p>A batter board is a simple wooden frame: two stakes driven into the ground with a horizontal board nailed across them. It sits a few feet outside each building corner, and its job is to hold the string lines that mark the building while the digging happens. The strings cross exactly over the building corners, but the boards themselves are safely out of the way of the excavator.</p>\n<p>The reason for batter boards is that corner stakes cannot survive excavation. The first bucket of the backhoe would take them out, and with them the whole layout. Batter boards solve that by moving the reference outside the hole: the strings can be taken down while the machine digs, then put back up on the same boards, in the same nail holes, and the layout returns exactly.</p>\n<p>Every batter board carries two things: position and height. The strings are set at a known elevation — often the top of the foundation wall — so the same boards that mark where the building goes also tell the crew how high it goes. That double duty is why batter boards are set carefully, leveled, and protected.</p>"
