      "html": "<p>At around 6 months, a baby is ready for <strong>complementary foods</strong> — foods that complement, not replace, breast milk or formula. The signs of readiness are: the baby can sit up with support, has good head control, shows interest in food, and has lost the tongue-thrust reflex that pushes food out of the mouth. The first foods should be iron-rich, because a baby's iron stores from birth run out at about 6 months: iron-fortified infant cereal, pureed meat, or pureed beans and lentils are good first foods. Vegetables and fruits follow, one new food at a time, so any reaction can be traced.</p>\n<p>Texture progresses with the baby: smooth purees at 6 months, mashed and soft lumpy foods at 7–8 months, soft finger foods at 8–9 months, and family foods (cut small and soft) by 12 months. Variety matters from the start — babies who taste many flavors early accept more foods later. Allergenic foods (peanut, egg, fish) should be introduced early, at around 6 months, in age-appropriate forms (for example, thinned peanut butter, never whole peanuts) — current guidance is that early introduction reduces the risk of allergy, not increases it. Any question about a baby's feeding goes to their clinician.</p>\n<p>Foods to avoid in infancy: <strong>honey before 12 months</strong> (it can carry the spores that cause infant botulism, a rare but serious illness); <strong>cow's milk as the main drink before 12 months</strong>; <strong>choking hazards</strong> (whole grapes, whole nuts, popcorn, hot dog rounds, hard raw vegetables — cut grapes in quarters lengthwise and avoid the rest until the child is older); <strong>added sugars and salt</strong> (a baby's kidneys and tastes do not need them); and <strong>unpasteurized milk and juice</strong>. Fruit juice is not recommended in the first year at all, and only in small amounts after that.</p>"
