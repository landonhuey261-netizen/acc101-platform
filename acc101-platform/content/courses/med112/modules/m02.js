      "html": "<p>After the first year, growth slows and so does appetite — a toddler who ate eagerly at 9 months may eat like a bird at 2 years, and that is normal. A young child's stomach is small, so they need small, frequent meals and snacks: three meals and two snacks a day is the usual pattern. Their needs are like an adult's in miniature: vegetables, fruits, whole grains, protein foods, and dairy (whole milk until age 2, then low-fat milk), with water as the drink and very little added sugar, salt, or juice.</p>\n<p><strong>Picky eating</strong> is normal in young children — it is a developmental stage, not a crisis. The useful strategies are: offer a food many times (it can take 10–15 exposures before a child accepts it), offer choices (\"carrots or peas?\"), eat the same food yourself, keep portions small, and never force, bribe, or punish around food. Pressure backfires: it makes the food more disliked, not less. The parent's job is to decide what food is offered, when, and where; the child's job is to decide how much to eat. That division of responsibility is the foundation of a healthy relationship with food.</p>\n<p>Iron remains important in early childhood — iron-deficiency anemia is common in toddlers who drink too much milk (more than about 24 ounces a day) and eat too little iron-rich food. Vitamin D is also a concern: children need vitamin D for bone growth, and many do not get enough sun or fortified foods, so a clinician may recommend a supplement. And the habits built now last: children who eat vegetables, drink water, and eat regular family meals are more likely to keep those habits as adults.</p>"
