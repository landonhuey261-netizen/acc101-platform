      "html": "<p><strong>Sarcopenia</strong> is the age-related loss of muscle mass, strength, and function. It starts slowly after age 30 and speeds up after 60: an older adult can lose 1–2 percent of muscle a year, and the loss is faster during illness or bed rest. Sarcopenia is not just weakness — it is the main cause of falls, fractures, frailty, and loss of independence in old age. A fall that breaks a hip can end independent living.</p>\n<p>The fight against sarcopenia has two weapons, and both are needed. The first is <strong>protein</strong>: older adults need more protein than younger adults — about <strong>1.0 to 1.2 grams per kilogram of body weight per day</strong>, spread across meals, with 25–30 grams at each main meal — because aging makes the body less efficient at using protein to build muscle. The second is <strong>resistance exercise</strong>: lifting, bands, body-weight exercises, even twice a week, preserves muscle and strength at any age. Protein without exercise does little; exercise without protein does little. Together, they work.</p>\n<p>One practical problem: many older adults eat very little protein at breakfast (tea and toast) and most of it at dinner. Spreading protein across the day — eggs or yogurt at breakfast, beans or fish at lunch, meat or tofu at dinner — uses protein more efficiently than loading it all into one meal.</p>"
