      "html": "<p>The eating pattern that protects the heart is the one you already know, with a few emphases. <strong>More:</strong> vegetables and fruits, whole grains, beans and lentils, nuts and seeds, fish (especially fatty fish twice a week for omega-3s), and unsaturated fats (olive oil, canola oil). <strong>Less:</strong> saturated fat (butter, fatty and processed meats, full-fat cheese), trans fat, added sugars, sodium, and alcohol. The Mediterranean and DASH patterns are both heart-healthy patterns, and both are linked to lower rates of heart attack and stroke in large studies.</p>\n<p>Four foods deserve special attention. <strong>Soluble fiber</strong> (oats, beans, lentils, apples, barley) lowers LDL cholesterol by binding bile acids in the gut — eating oats and beans daily is one of the most effective dietary moves for cholesterol. <strong>Fatty fish</strong> (salmon, sardines, mackerel) provides EPA and DHA, which lower triglycerides and protect the heart's rhythm. <strong>Nuts</strong> (walnuts, almonds) provide unsaturated fats, fiber, and plant sterols, and a small handful a day is linked to lower heart risk. <strong>Plant sterols and stanols</strong> (found in small amounts in vegetables, nuts, and seeds, and added to some spreads) block cholesterol absorption in the gut and can lower LDL further.</p>\n<p>What about eggs and dietary cholesterol? For most people, saturated fat raises blood cholesterol more than dietary cholesterol does, so eggs are a reasonable food for most people — but people with heart disease or high cholesterol should follow their clinician's advice, not general guidance. And no single food prevents heart disease: it is the pattern over years that matters, along with not smoking, regular activity, and — when a clinician advises it — medication such as a statin, which lowers LDL far more than diet alone can.</p>"
