      "html": "<p>The main risk factors for heart disease are: high LDL cholesterol, low HDL cholesterol, high blood pressure, diabetes or high blood sugar, excess weight (especially around the waist), smoking, physical inactivity, and a family history of early heart disease. Some of these cannot be changed (age, family history); most of them can be improved by diet, activity, and — when a clinician advises it — medication.</p>\n<p>Blood fats are measured in a <strong>lipid panel</strong>. <strong>LDL cholesterol</strong> (\"bad\" cholesterol) carries cholesterol to tissues and deposits it in artery walls when high — the higher the LDL, the faster plaque builds. <strong>HDL cholesterol</strong> (\"good\" cholesterol) carries cholesterol away from tissues back to the liver. <strong>Triglycerides</strong> are the main form of fat in the blood; they rise with excess calories, alcohol, and refined carbohydrate, and high triglycerides raise heart risk. The goal is lower LDL, higher HDL, and lower triglycerides — and diet moves all three.</p>\n<p><strong>Blood pressure</strong> is the other key number. High blood pressure (hypertension) damages artery walls, making it easier for plaque to form. The DASH eating pattern was designed to lower blood pressure, and it works: it is rich in potassium, calcium, and magnesium from vegetables, fruits, and low-fat dairy, and low in sodium. Sodium is the main dietary driver of blood pressure — the limit is below 2,300 milligrams a day — and most of it comes from processed foods, not the salt shaker.</p>"
