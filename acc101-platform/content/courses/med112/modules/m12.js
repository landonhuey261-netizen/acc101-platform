      "html": "<p>This course followed nutrition across the whole of life, and the pattern that emerges is simple: the needs change, but the principles do not. <strong>Pregnancy:</strong> folic acid 400–800 mcg before conception (neural tube closes by day 28), about 340 extra kcal a day in the second trimester and 450 in the third, iron needs rising sharply, and alcohol avoided entirely. <strong>Infancy:</strong> breast milk or formula only for about the first 6 months, complementary foods from about 6 months (iron-rich first), no honey before 12 months, no cow's milk as the main drink before 12 months. <strong>Childhood:</strong> small, frequent meals, whole milk until 2 then low-fat, picky eating handled with patience and repeated exposure, family meals without screens.</p>\n<p><strong>Adolescence:</strong> the fastest growth since infancy, iron the most commonly lacking nutrient, calcium about 1,300 mg a day building peak bone mass (90 percent built by age 18), and body image and eating disorders handled with care and referral. <strong>Adulthood:</strong> maintenance, not growth — energy needs falling slowly, weight rising from muscle loss, less activity, and portion creep, protected by resistance exercise, daily movement, and the healthy pattern. <strong>Aging:</strong> energy needs falling but nutrient needs not — protein 1.0–1.2 g/kg a day plus resistance exercise against sarcopenia, B12 absorption falling, vitamin D and calcium protecting bone, dehydration a constant risk because thirst weakens.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The needs change at every stage, but the principles do not: mostly plants, whole grains, varied protein, healthy fats, water as the drink — and limits on sugar, saturated fat, sodium, and alcohol. The pattern is the point, at every age.</div>"
