      "html": "<p><strong>Diabetes:</strong> type 1 is autoimmune (insulin for life); type 2 is about 90–95 percent of cases (insulin resistance). A1C measures average blood sugar over 2–3 months, with a common general target below 7 percent for many nonpregnant adults. Carbohydrate matters most — amount, type, and timing — and the tools are carbohydrate counting and the plate method, taught by clinicians and dietitians. <strong>Heart disease:</strong> atherosclerosis develops slowly over decades; LDL is \"bad,\" HDL is \"good,\" triglycerides rise with excess calories, alcohol, and refined carbohydrate; the heart-healthy pattern is more vegetables, fruits, whole grains, beans, nuts, and fish, and less saturated fat, trans fat, added sugars, sodium, and alcohol — and chest pain is an emergency, call 911.</p>\n<p><strong>Obesity:</strong> BMI categories (underweight below 18.5, normal 18.5–24.9, overweight 25–29.9, obese 30 or above), a screening tool that does not distinguish muscle from fat. A 5–10 percent weight loss improves blood pressure, blood sugar, and cholesterol. Obesity is a chronic medical condition, not a character flaw, and weight stigma harms health. <strong>Food safety:</strong> clean, separate, cook, chill; poultry 165°F, ground meat 160°F, steaks 145°F with a 3-minute rest; the danger zone is 40–140°F and the two-hour rule is the clock. <strong>Community:</strong> food insecurity affects about 1 in 8 U.S. households; SNAP, WIC, school meals, food banks, and community gardens are the safety net; and a coach who knows them can connect a person to food, not just to advice.</p>"
