      "html": "<p>Every module in this course ended with the same message, because it is the message that makes all the others safe to use. An <strong>RDN</strong> is credentialed and licensed to provide medical nutrition therapy. A <strong>nutrition coach</strong> gives general education for healthy people. A coach can teach, plan meals for healthy people, support habits, share general information, and refer. A coach cannot diagnose, design medical diets, set personal targets for medical conditions, interpret tests, prescribe supplements, or adjust medication. Referral is the coach's most important clinical skill — immediately (call 911) for chest pain, breathing difficulty, severe low blood sugar, anaphylaxis, or abuse, and promptly for new diagnoses, unexplained weight loss, feeding problems, and any request for a medical diet.</p>\n<p>The ethics are four: <strong>honesty</strong> (admit what you do not know), <strong>confidentiality</strong> (keep health information private), <strong>cultural respect</strong> (work inside a person's traditions), and <strong>evidence-based practice</strong> (Guidelines 2025–2030 and the inverted food pyramid, peer-reviewed evidence). Supplements are a clinician's decision; never prescribe, sell, or take a commission. Detoxes have no scientific basis. Fad diets are discussed honestly. A coach who sells a miracle is a salesperson, not a coach.</p>"
