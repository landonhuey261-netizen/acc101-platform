      "html": "<p><strong>Referral</strong> is the coach's most important clinical skill: recognizing when a person needs a clinician or an RDN, and helping them get there. Refer immediately — and urgently — for: chest pain or trouble breathing (call 911); signs of an eating disorder (rapid weight loss, purging, severe restriction); signs of low blood sugar with confusion or loss of consciousness (call 911); a suspected food allergy with breathing difficulty (call 911); and any sign of abuse, self-harm, or a mental-health crisis. Refer promptly (within days) for: a new diagnosis of diabetes, heart disease, kidney disease, or celiac disease; unexplained weight loss; persistent digestive problems; a baby or child with feeding problems; a pregnant person with nutrition questions; and anyone who asks for a diet to treat a condition.</p>\n<p>How to refer matters as much as when. Be specific: name the professional (\"a Registered Dietitian Nutritionist\" or \"your clinician\"), explain why (\"diabetes care needs a plan built for your medications and blood sugar\"), and make it easy (offer to help find one, or give the name of a local clinic). Never make the person feel dismissed or judged for asking — they asked because they trust you, and the referral is how you honor that trust.</p>"
