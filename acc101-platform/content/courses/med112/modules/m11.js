      "html": "<p>Two roles work in nutrition, and the difference between them is the most important fact in this module. A <strong>Registered Dietitian Nutritionist (RDN)</strong> is a credentialed professional: they have completed a bachelor's degree in nutrition, an accredited supervised practice program, a national exam, and continuing education, and in many states they are licensed. An RDN can provide <strong>medical nutrition therapy</strong> — diagnosing nutrition problems, designing diets to treat medical conditions, and working in hospitals and clinics. An RDN is the only nutrition professional qualified to treat disease with diet.</p>\n<p>A <strong>nutrition coach</strong> (sometimes called a nutritionist, health coach, or certified nutrition coach) gives <strong>general nutrition education</strong> for healthy people: teaching the food groups, reading labels, planning meals, and supporting healthy habits. A coach's training varies — some coaches hold a respected certification, others hold a short online certificate — and the title \"nutritionist\" is not regulated in most states, which means anyone can use it. That is exactly why scope of practice matters: the less regulated the title, the more important it is for the person holding it to know their limits and stay inside them.</p>\n<div class=\"callout\"><strong>Key idea:</strong> An RDN is credentialed and licensed to treat disease with diet. A nutrition coach gives general education for healthy people. The title \"nutritionist\" is not regulated in most states — which is why knowing your limits matters more, not less.</div>"
