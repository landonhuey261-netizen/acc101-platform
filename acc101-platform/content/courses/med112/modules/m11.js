      "html": "<p>A nutrition coach's ethics rest on four duties. <strong>Honesty:</strong> tell the truth about what is known and what is not, admit uncertainty, and never invent a fact, a dose, or a recommendation. If you do not know, say so — and find out from a reliable source. <strong>Confidentiality:</strong> keep what a person tells you private. Do not share their health information, their weight, or their eating habits with anyone else, including family, without their permission. <strong>Cultural respect:</strong> work inside a person's food traditions, faith, and budget — never mock, dismiss, or try to replace them. <strong>Evidence-based practice:</strong> base your guidance on the Dietary Guidelines 2025–2030 and the inverted food pyramid, and peer-reviewed evidence — not on social media trends, influencer claims, or a single study.</p>\n<p>Two topics test ethics more than any others: <strong>supplements and detoxes</strong>, and <strong>fad diets</strong>. Supplements are a clinician's decision — a coach never prescribes them, never sells them for profit, and never takes a commission on them, because a financial interest in a product destroys trust. \"Detox\" products and cleanses have no scientific basis — the liver and kidneys detox the body already — and a coach should say so plainly. Fad diets (keto, juice cleanses, extreme fasting, single-food diets) should be discussed honestly: what the evidence actually says, who should not attempt them, and why a sustainable pattern beats a dramatic one. A coach who sells a product or a miracle is not a coach — they are a salesperson.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Honesty, confidentiality, cultural respect, and evidence. A coach never prescribes supplements, never sells products for profit, and never presents a fad as a fact. If you do not know, say so.</div>"
