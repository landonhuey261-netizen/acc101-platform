      "html": "<p>A nutrition coach <strong>can</strong>: teach general nutrition knowledge (the food groups, the Dietary Guidelines 2025–2030 and the inverted food pyramid, label reading); help a healthy person plan balanced meals; support healthy habits (cooking, shopping, meal planning, mindful eating); share general information about how food affects health; and encourage a person to see a clinician when needed. A coach <strong>cannot</strong>: diagnose any condition (diabetes, eating disorders, allergies, celiac disease, kidney disease); design a diet to treat a medical condition; set personal calorie, carbohydrate, sodium, or protein targets for someone with a medical condition; interpret blood tests, A1C, or lipid panels; prescribe supplements or high-dose vitamins; adjust medication or insulin; or provide medical nutrition therapy of any kind.</p>\n<p>The line is simple to state and hard to keep in practice, because people ask for help at the line every day. \"Can you make me a meal plan for my diabetes?\" — no, but you can explain the plate method in general and refer them to an RDN. \"Can you tell me if I have a food allergy?\" — no, but you can explain what an allergy is and encourage them to see a clinician. \"Can you tell me what supplement to take?\" — no, but you can explain that supplements are a clinician's decision. The skill is not saying no — it is saying no kindly, explaining why, and pointing to the right professional.</p>"
