      "heading": "What Obesity Is — and How It Is Measured",
      "html": "<p><strong>Obesity</strong> is a medical condition in which excess body fat has accumulated to the point that it can harm health. It is measured most often with <strong>body mass index (BMI)</strong> — weight in kilograms divided by height in meters squared. The standard categories are: underweight below 18.5, normal weight 18.5–24.9, overweight 25–29.9, and obese 30 or above. Obesity is further divided into class I (30–34.9), class II (35–39.9), and class III (40 or above). About 40 percent of adults in the United States have obesity, and about 70 percent have overweight or obesity — it is one of the most common health conditions in the country.</p>\n<p>BMI is a useful screening tool, but it is not a perfect measure of health. It does not distinguish muscle from fat — a muscular athlete can have a high BMI without excess fat — and it does not say where fat is carried. <strong>Waist circumference</strong> adds that information: fat carried around the waist (abdominal fat) carries higher health risk than fat carried on the hips. A waist over 40 inches (102 cm) in men or over 35 inches (88 cm) in women is a marker of increased risk. BMI and waist circumference are screening tools, not diagnoses — and a nutrition coach never diagnoses obesity or tells a person their BMI category as a judgment. A clinician makes the assessment.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Obesity is excess body fat that can harm health. BMI is a screening tool, not a diagnosis — and it does not distinguish muscle from fat or say where fat is carried. Waist circumference adds that information.</div>"
