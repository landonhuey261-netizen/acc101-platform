      "html": "<p>Obesity happens when energy intake exceeds energy expenditure over a long time — but that simple law hides a complex reality. The causes include: <strong>genetics</strong> (genes affect appetite, metabolism, and where fat is stored); <strong>the food environment</strong> (cheap, energy-dense, heavily advertised foods are everywhere, and portions grew larger); <strong>medications</strong> (some antidepressants, steroids, and diabetes drugs cause weight gain); <strong>medical conditions</strong> (hypothyroidism, Cushing's syndrome, and others); <strong>sleep</strong> (short sleep raises hunger hormones); <strong>stress</strong> (stress drives comfort eating); and <strong>reduced activity</strong> (desk jobs, cars, and screens).</p>\n<p>That list is why \"eat less, move more\" is true but incomplete — and why blaming a person for their weight is both wrong and useless. A person can know exactly what to eat and still struggle, because appetite, environment, medications, and biology are all pushing the other way. Obesity is a chronic, relapsing medical condition, not a character flaw — and it is treated like one: with long-term support, not with a single diet or a single lecture.</p>"
