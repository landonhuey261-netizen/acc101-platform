      "heading": "Folic Acid: The Single Most Important Nutrient",
      "html": "<p><strong>Folate</strong> (vitamin B9) is needed to make DNA and red blood cells, and in early pregnancy it is needed to close the baby's neural tube. If the tube does not close, the baby is born with a <strong>neural tube defect</strong> such as spina bifida or anencephaly. The neural tube closes by about day 28 of pregnancy — before many people know they are pregnant — which is why the recommendation is to have enough folate <em>before</em> conception. The Centers for Disease Control and Prevention recommends that all people who could become pregnant take <strong>400 to 800 micrograms of folic acid daily</strong> (folic acid is the supplement form of folate), starting at least one month before conception and continuing through the first 12 weeks of pregnancy, in addition to eating folate-rich foods such as leafy greens, beans, and fortified grains.</p>\n<p>People with a previous pregnancy affected by a neural tube defect, or with certain medical conditions, may need a higher dose — that is a clinician's decision, not a self-care choice. Folic acid is one of the great public-health success stories: since the United States began fortifying flour with folic acid in 1998, neural tube defects have fallen substantially. It is also a reminder of why this course never prescribes supplements: the dose depends on the person, and the person who decides is a clinician.</p>"
