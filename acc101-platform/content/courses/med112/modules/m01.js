      "html": "<p>Energy needs rise in pregnancy, but not by as much as people think — and not at all in the first trimester. The standard guidance is about <strong>340 extra kilocalories a day in the second trimester and about 450 extra in the third</strong>, on top of the person's usual needs. That is roughly a snack, not a second dinner: a yogurt with fruit and nuts, or a sandwich with an apple. \"Eating for two\" is a myth; the baby needs nutrients, not double portions.</p>\n<p>Several nutrients need special attention. <strong>Iron</strong> needs rise sharply, because blood volume increases by about 50 percent and the baby needs iron for its own blood — iron-deficiency anemia is common in pregnancy, and a clinician may recommend an iron supplement. <strong>Calcium</strong> needs are met by the usual adult intake (about 1,000 mg a day); the body absorbs calcium more efficiently in pregnancy, so extra calcium is not usually needed. <strong>Iodine</strong> needs rise because the baby's thyroid and brain depend on it — iodized salt and dairy are the main sources. <strong>Vitamin D</strong> supports the baby's bones; a clinician may check levels and recommend a supplement. <strong>Omega-3 fatty acids</strong> (especially DHA) support the baby's brain and eye development; low-mercury fish twice a week is the standard recommendation.</p>\n<p>Weight gain in pregnancy depends on the person's weight before pregnancy. The Institute of Medicine's ranges are: underweight (BMI below 18.5), 28–40 pounds; normal weight (BMI 18.5–24.9), 25–35 pounds; overweight (BMI 25–29.9), 15–25 pounds; obese (BMI 30 or above), 11–20 pounds. These are general ranges — the right target for an individual is set with their clinician, and gaining too little or too much both carry risks.</p>"
