      "html": "<p>Carbohydrate is the nutrient that raises blood sugar, so it is the nutrient that matters most in diabetes eating. The key ideas are <strong>amount</strong>, <strong>type</strong>, and <strong>timing</strong>. Amount: the total carbohydrate in a meal decides how far blood sugar rises — so keeping carbohydrate portions consistent from meal to meal makes blood sugar more predictable. Type: whole, fiber-rich carbohydrate foods (whole grains, beans, vegetables) raise blood sugar more slowly than refined and sugary foods. Fiber is especially helpful: it slows digestion and steadies blood sugar. Timing: regular meals, spaced through the day, prevent the large swings that come from skipping meals and then eating a lot at once.</p>\n<p><strong>Carbohydrate counting</strong> is the main tool many people with diabetes use: they count the grams of carbohydrate in each meal and match it to their medication or insulin dose, following a plan set by their clinician or dietitian. The <strong>plate method</strong> is a simpler tool: half the plate non-starchy vegetables, a quarter lean protein, a quarter carbohydrate foods, with water as the drink. Both tools are taught by clinicians and dietitians — a nutrition coach may explain the general ideas, but must never set a carbohydrate target or an insulin dose for an individual.</p>\n<p>Two more points. First, <strong>sugar is not banned</strong> in diabetes — it is the total carbohydrate that matters, and a small amount of sugar inside a balanced meal affects blood sugar less than a large amount on an empty stomach. Second, <strong>alcohol</strong> is risky in diabetes because it can cause low blood sugar hours later, especially on an empty stomach — anyone with diabetes who drinks should do so only with food and only as their clinician advises.</p>"
