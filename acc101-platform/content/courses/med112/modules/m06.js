      "html": "<p>After a meal, blood sugar rises as carbohydrate is digested into glucose. In a healthy person, the pancreas releases insulin, glucose moves into cells, and blood sugar returns to normal within a couple of hours. In a person with diabetes, that system fails: blood sugar rises higher and stays high longer. The symptoms of high blood sugar include thirst, frequent urination, fatigue, and blurred vision — and many people with type 2 diabetes have no symptoms at all, which is why it is often found by a blood test rather than by feeling ill.</p>\n<p>Clinicians measure blood sugar control in two ways. A <strong>fasting blood sugar</strong> or a random blood sugar measures the level at one moment. <strong>A1C</strong> (hemoglobin A1c) measures the average blood sugar over the past two to three months, because glucose sticks to hemoglobin in red blood cells. A common general target for many nonpregnant adults with diabetes is an A1C below 7 percent, but the right target is set individually by the clinician — it depends on age, other conditions, and the risk of low blood sugar. A nutrition coach never sets or interprets an A1C target; that is a clinician's job.</p>\n<p><strong>Low blood sugar (hypoglycemia)</strong> is the other side of the coin: blood sugar that falls too low, usually in a person taking insulin or certain diabetes medications. The signs are shakiness, sweating, fast heartbeat, confusion, and irritability — and severe low blood sugar can cause loss of consciousness. It is treated by taking fast-acting carbohydrate (glucose tablets or juice) and then rechecking. Anyone with diabetes should have a plan for low blood sugar from their clinician, and a coach should know the signs and know to call for help.</p>"
