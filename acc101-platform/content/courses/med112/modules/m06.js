      "html": "<p><strong>Diabetes</strong> is a condition in which blood sugar (glucose) stays too high because the body cannot make enough insulin or cannot use insulin properly. <strong>Insulin</strong> is the hormone from the pancreas that moves glucose from the blood into cells. Without enough working insulin, glucose builds up in the blood instead of entering cells — and over years, high blood sugar damages blood vessels, nerves, eyes, kidneys, and the heart.</p>\n<p>There are two main types. <strong>Type 1 diabetes</strong> is an autoimmune condition in which the immune system destroys the insulin-making cells of the pancreas; it usually starts in childhood or adolescence, and the person must take insulin for life. <strong>Type 2 diabetes</strong> is far more common (about 90–95 percent of cases): the body's cells respond poorly to insulin (insulin resistance), and over time the pancreas cannot make enough to compensate. Type 2 is linked to excess weight, inactivity, and family history, and it develops gradually — often after years of <strong>prediabetes</strong>, in which blood sugar is higher than normal but not yet in the diabetes range. Prediabetes can often be reversed with weight loss, activity, and diet — which is why it matters to catch it.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Diabetes is high blood sugar because insulin is missing (type 1) or not working well (type 2). Type 2 is far more common and develops gradually — often after years of prediabetes that can be reversed.</div>"
