      "html": "\n<p><strong>Maslow's hierarchy</strong> arranges needs in five levels: physiological (food, rest), safety (security, stable income), social (belonging), esteem (recognition, status), and self-actualization (becoming one's best). The claim: unmet lower needs dominate, and satisfied needs stop motivating. It is a useful map of what people care about, but the strict ladder is not supported — people pursue higher needs while lower ones are still unmet, and the order varies by culture and person.</p>\n<p><strong>Herzberg's two-factor theory</strong> splits job factors into <strong>hygiene factors</strong> (pay, working conditions, company policy, supervision) and <strong>motivators</strong> (achievement, recognition, the work itself, responsibility, growth). Fixing hygiene removes dissatisfaction but does not motivate; only motivators create satisfaction and drive. That is why a pay rise makes people less unhappy for a month, while a more interesting job keeps them engaged for a year.</p>\n<p><strong>McClelland</strong> adds three learned needs: <strong>achievement</strong> (do well, beat a standard), <strong>affiliation</strong> (belong, be liked), and <strong>power</strong> (influence others). High achievers want challenging goals and fast feedback; high affiliation people want harmony; high power people — the institutional kind — want to organize others toward a goal, and make good managers.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Herzberg's test: if fixing it only stops complaints, it is hygiene. If adding it creates energy, it is a motivator. Pay is usually hygiene — which is why pay rises alone rarely fix motivation.</div>"
