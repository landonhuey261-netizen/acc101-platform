      "html": "\n<p><strong>Expectancy theory (Vroom)</strong> says motivation = Expectancy × Instrumentality × Valence. <strong>Expectancy:</strong> \"If I try, can I succeed?\" <strong>Instrumentality:</strong> \"If I succeed, will I be rewarded?\" <strong>Valence:</strong> \"Do I value that reward?\" Because the three multiply, a zero anywhere kills motivation: a worker who believes effort cannot succeed (E = 0), or that success brings no reward (I = 0), or that the reward is worthless (V = 0) will not try, however large the other two are.</p>\n<p><strong>Worked example.</strong> A bonus scheme: expectancy 0.9 (the target is reachable), instrumentality 0.8 (good performers usually get the bonus), valence 0.5 (the bonus is small and the worker would rather have time off). Motivation = 0.9 × 0.8 × 0.5 = <strong>0.36</strong>. Raise the valence — offer a choice between the bonus and an extra day off — to 0.9, and motivation becomes 0.9 × 0.8 × 0.9 = <strong>0.65</strong>, nearly double, without spending more.</p>\n<p><strong>Equity theory (Adams)</strong> says people compare their ratio of outcomes to inputs against other people's ratios. Outcomes are pay, recognition, and benefits; inputs are effort, skill, and hours. If the ratios feel unequal, people restore balance — by working less, asking for more, or leaving. Perceived fairness matters more than the absolute amount: a $500 bonus feels like an insult if a colleague got $2,000 for the same work.</p>\n<p><strong>Goal-setting theory (Locke)</strong> is the most practical of all: specific, challenging goals with feedback beat vague \"do your best\" goals. The goal must be accepted, the person must believe it is reachable, and feedback must show progress. That is SMART (Module 3) with a motivation engine attached.</p>"
