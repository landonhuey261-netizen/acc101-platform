      "heading": "Why Plan at All?",
      "html": "\n<p>Planning is deciding in advance what to do, how to do it, and when. It gives direction (everyone pulls the same way), reduces uncertainty (the team has thought about what could happen), minimizes waste (resources are committed on purpose, not by accident), and sets the standard that controlling later measures against. A team without a plan can still work hard — it just cannot tell whether the hard work is taking it anywhere.</p>\n<p>Planning has limits. A plan is a bet about the future, and the future does not cooperate. The answer is not to plan less but to plan in layers: a <strong>strategic plan</strong> (3–5 years, whole organization), <strong>tactical plans</strong> (1–2 years, a department), and <strong>operational plans</strong> (days to months, a team or shift). Short plans can change fast; long plans set direction. And every plan needs a review date, or it quietly becomes history.</p>\n<div class=\"callout\"><strong>Key idea:</strong> A plan is not a prediction. It is a decision made in advance, with a date to revisit it. The value is in the deciding, not in the document.</div>"
