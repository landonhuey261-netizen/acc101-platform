      "heading": "Commissioning: Starting It Up Right",
      "html": "<p>Commissioning is the process of starting up every system, testing it, and proving it works the way it was designed to work — before the homeowner moves in. The furnace runs and heats. The air conditioner runs and cools. Every faucet runs and drains. Every light, receptacle, and appliance works. It sounds obvious, but a system that was never started up is a system nobody knows works.</p>\n<p>The trades do their own startup: the HVAC installer starts the furnace and checks the airflow, the plumber pressurizes the water lines and checks for leaks, the electrician tests the circuits and the panel. The builder's job is to witness it, to check it against the plan, and to record that it was done. A startup with no record is a startup that never happened, as far as anyone can prove later.</p>\n<p>Balancing is part of commissioning for HVAC. The installer adjusts the dampers so each room gets its share of air — the far bedroom gets as much as the room next to the furnace. A house where one room is always hot and one is always cold was never balanced, and the homeowner will blame the builder, not the damper. The builder asks for the balancing check and records it.</p>\n<p>The thermostat is the homeowner's main control, and it deserves a check of its own. Set it to heat, confirm the furnace starts. Set it to cool, confirm the air conditioner starts. Check that the thermostat is level, that it is not on an outside wall or above a heat source, and that the homeowner knows how to use it. A thermostat the homeowner cannot work is a system the homeowner cannot control.</p>\n<p>Commissioning also includes the small systems: the garage door opener, the bath fans, the range hood, the smoke and carbon monoxide alarms, the water heater temperature. Test each one, write it down, and fix what fails. A failed item found at commissioning costs minutes; the same item found by the homeowner on the first night costs the builder a call-back and a reputation.</p>"
