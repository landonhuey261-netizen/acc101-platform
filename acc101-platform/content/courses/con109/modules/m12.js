      "heading": "The Handover Package",
      "html": "<p>The handover package is the folder — paper or digital — that the builder gives the homeowner at the end of the job. It contains everything the homeowner needs to live in the house and to maintain it: the as-built drawings, the equipment manuals, the warranty information, the inspection records, and the contact list for the trades. A house without a handover package is a house whose owner is guessing.</p>\n<p>As-built drawings are the plans updated to show what was actually built: every field fix, every moved duct, every soffit and chase, every change from the original design. The original plans show what was intended; the as-builts show what is in the walls. Years later, when someone opens a wall to remodel, the as-builts tell them where the pipes and wires are — and keep them from drilling into a drain.</p>\n<p>Equipment manuals belong in the package, not in a box in the garage. The furnace manual, the water heater manual, the thermostat instructions, the appliance booklets — each one tells the homeowner how to run the equipment, how to change the filter, and who to call for service. The builder collects them during the job, because a manual lost on site is a manual the homeowner never gets.</p>\n<p>The inspection records go in too: the dates of the rough-in, insulation, and final inspections, the correction notices, and the re-inspection results. They prove the house was checked at every gate. The punch list goes in as well, with every item checked off — proof that the job was finished, not just nearly finished.</p>\n<p>Finally, the package includes the service record: filter sizes, the location of the main water shutoff, the location of the electrical panel, and the contact information for each trade. The homeowner who knows where the main shutoff is can stop a leak in a minute; the homeowner who does not know will watch the water spread while they search.</p>"
