      "html": "<p>A warranty is a written promise to fix something if it fails within a set time. There are two kinds on a house: the builder's warranty, which covers the builder's own work, and the manufacturers' warranties, which cover the equipment and materials — the furnace, the water heater, the windows, the roofing. Each one has its own terms, its own length, and its own conditions.</p>\n<p>Warranty terms vary widely, and the builder must never promise a length or a coverage that is not in writing. Many builders offer a one-year warranty on their own workmanship, but that is a common practice, not a rule — the actual terms are whatever the builder's contract says. The builder's job is to know what their own contract promises, to put it in writing, and to honor it.</p>\n<p>Record every warranty in the handover package: what is covered, for how long, who provides it, and how to make a claim. A furnace warranty that requires annual service to stay valid is useless if the homeowner never learns about the service requirement. A roofing warranty that is voided by walking on the roof is useless if nobody tells the homeowner.</p>\n<p>Warranties also have limits the homeowner should understand. A warranty does not cover damage the homeowner causes, normal wear, or a lack of maintenance — a furnace filter never changed is not a warranty claim, it is a maintenance failure. The builder explains this plainly at the walkthrough, so the homeowner knows what is covered and what is their own job.</p>\n<p>The builder's own record matters too. Keep a copy of every warranty, every handover package, and every walkthrough checklist in the job file. When a homeowner calls two years later about a window, the builder who can open the file and see the window's warranty, the installer's name, and the install date can help in five minutes. The builder who cannot is starting from zero.</p>"
