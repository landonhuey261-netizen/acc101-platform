      "html": "<p>A coordination conflict is two things trying to occupy the same space. A duct and a beam. A drain and a joist. A panel and a water line. A recessed light and a duct. Conflicts are not a sign that someone did bad work — they are a normal result of three trades, each with their own plan, working in the same walls. The builder's job is to find them on paper, where they are free, instead of in the wall, where they are expensive.</p>\n<p>Conflicts happen in predictable places. Where a duct crosses a beam. Where a drain drops through a floor. Where a tall cabinet meets a soffit. Where a light fixture lands on a joist. Where the panel's working space meets a water heater. The builder who has seen one house knows where to look on the next one — and looks there before the trades arrive, not after.</p>\n<p>The cost of a conflict depends on when it is found. Found on the drawing, it costs a pencil line. Found at rough-in, it costs a trade's time to re-route. Found after drywall, it costs tear-out, repair, and repaint. Found by the homeowner after move-in — a duct that rattles, a door that hits a vent — it costs the builder's reputation. Early is cheap; late is expensive.</p>\n<p>Some conflicts are not about space at all. A conflict can be about order: the electrician needs the wall, but the plumber is not done. A conflict can be about access: the air handler is installed, but the filter cannot be reached. A conflict can be about weight: a heavy water heater hung on a wall that was never framed for it. The builder's eye has to catch all three kinds.</p>\n<p>The first step in resolving any conflict is to stop and look. Do not let a trade 'just make it fit' — that is how a joist gets notched, a wire gets crushed, or a drain loses its slope. Pause the work in that spot, gather the trades involved, and agree on a fix. A ten-minute pause now is cheaper than a ten-hour repair later.</p>"
