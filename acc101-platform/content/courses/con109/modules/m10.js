      "html": "<p>When a conflict is found, the fix follows a simple order: move the cheapest, most flexible thing first. A wire moves before a duct. A duct moves before a drain. A drain moves before a beam. And nothing — ever — moves by cutting structure. That order is the whole job in one sentence.</p>\n<p>A wire is the easiest thing to move: it bends, it re-routes, and moving it costs minutes. A duct is next: it can drop, shift sideways, or go into a soffit, but each bend costs airflow and each move costs time. A drain is hard to move: gravity sets its slope, and moving it means changing the slope of the whole run. A beam, a joist, or a truss does not move at all — the structure is the structure.</p>\n<p>Sometimes the right fix is not to move anything but to give the conflict a designed home. That is what soffits and chases are for. A soffit is a dropped section of ceiling that hides a duct or a pipe running below the joists. A chase is a boxed-in vertical shaft that carries pipes or ducts between floors. Both are planned on the drawing, framed deliberately, and finished to look like part of the house.</p>\n<p>A soffit needs real math. A duct that is 8 inches tall, with 1 inch of clearance above it and 1/2 inch of drywall below it, needs a soffit about 9-1/2 inches deep. A chase that carries a 3-inch drain and a 2-inch vent side by side needs to be at least as wide as both pipes plus clearance on each side — a 12-inch by 12-inch chase is a common size. The builder works out the size before framing, not after the duct is hanging.</p>\n<p>If no move works and no soffit or chase fits, the fix is a design change — and that goes back to the designer, not to a trade with a saw. A beam that has to move, a duct that has to go through a floor, a drain that has to cross a beam: these are engineering questions. The builder's job is to recognize that the conflict has outgrown a field fix and to get the right person involved.</p>"
