      "html": "<p>The coordination drawing is the builder's main tool for catching conflicts early. It is a single drawing — or a set of overlaid drawings — that shows the framing, the ducts, the pipes, and the wires together. When the duct run is drawn over the framing plan, a duct crossing a beam is obvious. When it is not drawn, nobody sees it until the HVAC installer is standing on a ladder with a duct in his hands.</p>\n<p>On larger jobs, coordination drawings are built in software that checks for clashes automatically — the program flags every place two objects overlap. On a single-family house, the same check is done by hand: the builder lays the mechanical plans over the framing plan and looks for overlaps. The tool is different; the thinking is the same.</p>\n<p>The builder runs the clash check before rough-in starts, at the coordination meeting from Module 8. Each trade brings their plan, the builder overlays them, and the group walks through the overlaps one by one. The plumber moves a drain six inches. The HVAC installer drops a duct into a soffit. The electrician re-routes a wire. Every fix is agreed in the room, and the builder writes it down.</p>\n<p>The most valuable clash check is the one the builder does alone, quietly, the night before a trade starts. Read the plan, picture the work, and ask: what is in the way? A duct that has to cross a steel beam. A vent that has to rise through a second-floor bathroom. A panel that sits behind a future cabinet. The builder who finds these the night before saves the trade a wasted morning.</p>\n<p>Keep the marked-up drawings. When a conflict is found and fixed on paper, the drawing with the fix is the record of what was agreed. If a trade later installs the old version, the drawing settles the argument. And on the next house, the marked-up drawings are the checklist of conflicts to check for first.</p>"
