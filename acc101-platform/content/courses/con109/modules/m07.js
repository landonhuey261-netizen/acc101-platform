      "html": "<p>A furnace or air handler typically needs about 30 inches of clear working space in front of it — enough for a technician to stand, open the service panel, and pull out a filter or a blower. That 30 inches is measured from the front of the unit to the nearest wall, door, or stored item. It is not a suggestion: the maker's installation instructions list it, and inspectors check it.</p>\n<p>The sides and back of a furnace have smaller clearances, often just 1 inch to 6 inches, because the hot parts face the front. But those small numbers still matter. A furnace pushed tight against a wall on the side where its gas or vent connection sits cannot be connected properly, and a unit with zero side clearance cannot be pulled out for replacement without cutting the wall.</p>\n<p>A water heater needs similar respect. It needs clear space in front for service, room above for the vent or flue, and a drain pan underneath with a drain to a safe place if it is installed where a leak could damage finished space. A water heater in a closet also needs combustion air if it burns gas — a sealed closet with no air supply will starve the burner.</p>\n<p>The builder's coordination task here is simple: when the HVAC contractor says the furnace goes in the northwest corner of the basement, ask where the 30 inches of working space will be, where the filter is changed from, and how the unit comes out if it ever has to be replaced. If the answer is 'through the finished wall,' the layout is wrong.</p>\n<p>One more trap: storage. A mechanical room with perfect clearances on the day of the final inspection can be ruined in a month when the homeowner stacks boxes in front of the furnace. A good builder labels the clearance zone — a painted line on the floor or a sign on the wall — and tells the homeowner in the walkthrough that the space in front of the furnace stays empty.</p>"
