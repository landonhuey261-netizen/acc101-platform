      "heading": "Spot Ventilation: Bathrooms and Kitchens",
      "html": "<p>Spot ventilation is exhaust at the source: a fan in the bathroom that removes steam, and a range hood in the kitchen that removes smoke, grease, and cooking moisture. These fans run when the room is in use and stop when it is not. They are the first line of defense against moisture, and moisture is the enemy of every house.</p>\n<p>The common guidance for a bathroom fan is about 50 cubic feet per minute (CFM) when it runs on a switch, or about 20 CFM if it runs continuously. CFM is the measure of how much air a fan moves — 50 CFM means the fan moves 50 cubic feet of air every minute. A bathroom that is 8 feet by 10 feet with an 8-foot ceiling holds 640 cubic feet of air, so a 50-CFM fan changes the room's air roughly every 13 minutes.</p>\n<p>The common guidance for a kitchen range hood is about 100 CFM when it runs on a switch, or about 25 CFM if it runs continuously. A range hood also needs a duct to the outside — a hood that recirculates air through a filter does not remove moisture, it only catches some grease. The builder checks that the hood's duct is on the plan and that it actually goes outside.</p>\n<p>Every exhaust fan must vent to the outside, never into an attic, a crawl space, or a wall cavity. A bath fan that dumps steam into an attic grows mold on the roof sheathing. A range hood that dumps grease into a wall cavity is a fire risk. The builder's check at rough-in is simple: follow each exhaust duct with your eyes and confirm it ends outside the house.</p>\n<p>Fans also need a path for makeup air — the air that replaces the air the fan pushes out. In a tight house, a powerful range hood can pull air backwards down a furnace flue or a water heater vent if there is no makeup air path. That is called backdrafting, and it can pull carbon monoxide into the house. The mechanical design should account for it, and the builder should ask the HVAC contractor how it is handled.</p>"
