      "heading": "A Tight House Still Needs Air",
      "html": "<p>Modern houses are built tight. House wrap, sealed penetrations, good windows, and careful framing keep outside air out and conditioned air in. That is good for energy bills — but a house that never gets fresh air is a house where moisture, cooking smells, and indoor pollutants build up. A tight house needs planned ventilation, because the random leaks that used to ventilate old houses are gone.</p>\n<p>Ventilation is controlled fresh air. It is not a draft through a crack in the wall — it is a fan or a system that brings in a known amount of outside air and exhausts a known amount of stale air. The builder's job is to make sure the house has both: a tight envelope and a ventilation plan. One without the other is a problem.</p>\n<p>The amount of air a house needs depends on its size and how many people live in it. The common guidance works out to roughly one full air change every three hours for the whole house — about 0.35 air changes per hour — plus extra exhaust for kitchens and bathrooms. The exact number comes from the local code and the mechanical design; the builder's job is to make sure the design exists and the equipment that delivers it is installed.</p>\n<p>Indoor air quality is not only about fresh air. It is about what the air carries: moisture from showers and cooking, dust, chemicals from paints and finishes, and carbon monoxide from fuel-burning appliances. Ventilation removes the bad air; the envelope, the finishes, and the combustion safety measures keep the bad air from being made in the first place.</p>\n<p>The builder's coordination role here is to make sure the ventilation plan is on the drawings before rough-in. A bath fan needs a duct to the outside. A range hood needs a duct to the outside. A whole-house system needs a place for its equipment and its ducts. If the plan forgets the duct, the fan gets installed with nowhere to exhaust — and a fan that exhausts into the attic is worse than no fan at all.</p>"
