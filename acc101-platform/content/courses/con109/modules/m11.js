      "heading": "Whole-House Ventilation",
      "html": "<p>Spot fans handle the wet rooms, but the whole house still needs fresh air. Whole-house ventilation is a system that brings fresh air into the living spaces and exhausts stale air from the house, on a steady schedule, all year. It is different from a bath fan: it serves the whole house, not one room, and it runs quietly in the background.</p>\n<p>The simplest whole-house system is a supply fan that brings in outside air, often tied into the HVAC ductwork. A more complete system is a heat-recovery or energy-recovery ventilator — an HRV or ERV — which moves heat (and, for an ERV, moisture) between the outgoing stale air and the incoming fresh air, so the house gets fresh air without throwing away all the heating or cooling energy.</p>\n<p>The builder's coordination tasks for whole-house ventilation are the same as for any mechanical system: space for the equipment, a duct path, a place for the fresh-air intake and the exhaust to go through the wall or roof, and clearances for service. The intake and the exhaust must be separated — an intake right next to an exhaust just recycles the same stale air.</p>\n<p>Controls matter too. A whole-house system that the homeowner does not understand will be switched off and forgotten. The builder's handover should include a plain explanation: what the system is, when it runs, how to change the filter, and what to do if it seems to stop working. A ventilation system that is switched off is a house with no fresh air.</p>\n<p>In some climates and some codes, whole-house ventilation is required; in others it is good practice. Either way, the builder should know whether the house they are building has one, what kind it is, and where its parts are. It is a mechanical system like any other, and it deserves the same coordination.</p>"
