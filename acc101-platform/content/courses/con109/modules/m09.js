      "html": "<p>The insulation inspection, where the local code requires one, happens after insulation is installed and before drywall covers it. The inspector checks that the insulation is the right type and thickness for each space, that it is installed without gaps, compression, or voids, and that air sealing is in place at the plates, penetrations, and rim joists.</p>\n<p>Gaps and compression are the two most common insulation failures. A gap is a spot with no insulation at all — behind a pipe, around a wire, at a corner. Compressed insulation is insulation squeezed into a space too small for it, which crushes the air pockets that do the insulating and cuts its performance. Both are invisible after drywall, which is why this inspection exists.</p>\n<p>Air sealing gets checked at the same time. Every penetration through a top plate, every wire hole, every pipe hole should be sealed before insulation goes in, because air leaking through the wall carries moisture with it. The inspector looks for sealant at the plates and around the penetrations — the same sealing the builder required in Module 6.</p>\n<p>The builder's pre-inspection walk for insulation is simple: look in every stud bay, especially the ones with pipes and wires in them, and check that insulation fills the bay fully and evenly. Pay attention to the bays the trades worked in — those are the bays where insulation gets pushed aside and forgotten.</p>\n<p>Not every jurisdiction requires a separate insulation inspection; in some places it is folded into the rough-in or the final inspection. The builder checks the local requirement at the start of the job and plans the sequence around it. Whether or not a separate inspection is required, the check itself is still worth doing — the drywall crew will cover the insulation forever.</p>"
