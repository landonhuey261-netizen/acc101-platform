      "html": "<p>The rough-in inspection happens after framing and after all three rough-in trades have finished, and before any insulation or drywall goes up. The inspector walks the whole house with the approved plans in hand and checks each system while it is still visible: the framing, the plumbing, the HVAC, and the electrical.</p>\n<p>For plumbing, the inspector checks that drains slope the right way, that vents rise to the roof, that pipes are supported, and that water lines are protected where they pass through framing. For HVAC, they check that ducts are sealed and supported, that the equipment has its clearances, and that combustion appliances have air and a proper vent. For electrical, they check that wires are stapled and protected, that boxes are set at the right depth, and that the panel has its working space.</p>\n<p>The inspector also checks the framing itself: that holes and notches are within the limits from Module 6, that no truss has been cut, and that fire blocking is in place where the code requires it. This is why the builder's coordination work matters — most rough-in failures are not trade mistakes, they are coordination mistakes: a pipe through a truss, a wire with no protection plate, a duct blocking a panel.</p>\n<p>A common cause of a failed rough-in inspection is simply that the house was not ready. A trade left a room unfinished, a fixture was not set, a vent was not run to the roof. The builder's pre-inspection walk catches this: do not call the inspector until every trade's rough-in work is actually done. An inspector who arrives to an unfinished house will fail the inspection, and the builder pays for the re-inspection visit.</p>\n<p>When the rough-in inspection passes, the gate opens: insulation can go in, and then drywall. Nothing should go in before that pass. The builder who starts insulation the morning of the inspection, hoping it will pass, is gambling with the whole drywall schedule.</p>"
