      "html": "<p>An inspection is a visit from the local building department's inspector, who checks the work against the local code and the approved plans. The inspector is not the enemy and not a consultant — they are an independent set of eyes whose job is to catch mistakes while they are still cheap to fix. A house that passes its inspections is a house that was built to the code that protects the people who will live in it.</p>\n<p>Inspections happen at gates — points in the sequence where work is about to be covered up or finished. The three big gates in this course are the rough-in inspection, the insulation inspection where the local code requires one, and the final inspection. Each gate has the same logic: look at the work while you can still see it, fix what is wrong, and only then move on.</p>\n<p>The builder schedules inspections, not the trades. The builder knows the whole sequence and knows when every trade's work is ready. If each trade called its own inspection, the inspector might arrive while another trade's work is still unfinished, and the visit would be wasted — or worse, the inspection might pass one trade's work while a different trade's problem sits right next to it, unseen.</p>\n<p>Before calling the inspector, the builder does their own walk first. Walk every room, look at the framing, the pipes, the ducts, and the wires, and check them against the plan and the common mistakes in this course. Fix what you find before the inspector finds it. A builder's own pre-inspection walk is the cheapest quality control in the whole job.</p>\n<p>Keep the inspection record. Note the date of every inspection, whether it passed or failed, what failed if it did, and who fixed it. That record goes into the handover package at the end of the job. It proves the house was checked at every gate, and it protects the builder if anyone later asks whether the work was inspected.</p>"
