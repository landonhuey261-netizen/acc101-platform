      "html": "<p>Most workplace emails are never really read — they are triaged. A busy reader scans a list of subject lines and decides in seconds which emails to open now, which to save, and which to ignore. The subject line is therefore not a label; it is the email's first sentence and often its only sentence. \"Question\" tells the reader nothing. \"Approval needed by Friday: new copier lease\" tells the reader what the email is, what action is needed, and when — before they even open it.</p><p>A good subject line names the topic and the action: \"Action needed: approve Q3 travel budget by Thursday,\" \"FYI: loading dock closed Tuesday 6 a.m.–noon,\" \"Decision: choose vendor A or B for the lobby renovation.\" Notice what each one does: the reader knows whether to open it now, what they will be asked to do, and how urgent it is. Vague subjects — \"Hi,\" \"Quick question,\" \"Update\" — force the reader to open the email just to find out whether it matters, which is exactly the tax busy people resent.</p><div class=\"callout\"><strong>Key idea:</strong> Write the subject line last, after the email is drafted, so it describes what the email actually asks for — not what you meant to ask for.</div>"
