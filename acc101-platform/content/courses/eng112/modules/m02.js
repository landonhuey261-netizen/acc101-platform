      "html": "<p>The single most powerful plain-language habit is the active voice: the subject does the action. \"The committee approved the budget\" beats \"The budget was approved by the committee\" because the reader learns who acted in the first three words. Passive voice hides the actor, which is sometimes useful — \"Mistakes were made\" is famous precisely because it hides who made them — but in workplace writing, hiding the actor usually hides responsibility, and it always adds words.</p><p>Strong verbs do the same work at the word level. \"The manager decided\" beats \"The manager made a decision.\" \"We tested the pump\" beats \"We conducted testing of the pump.\" Every time a verb is turned into a noun — decide into decision, test into testing, improve into improvement — the sentence gets longer and weaker. Linguist Helen Sword calls these turned-into-nouns \"zombie nouns\" because they suck the life out of prose. Find them by looking for words ending in -tion, -ment, -ance, and -ity, and turn them back into verbs.</p>"
