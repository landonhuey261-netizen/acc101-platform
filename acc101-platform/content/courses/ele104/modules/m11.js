      "html": "<p>A kick is a single bend that moves the conduit a short distance — usually to enter a box that sits off the wall. A kick is laid out like half an offset: pick the angle, find the multiplier, and place the mark so the bend lands where it should. A box offset, also called a bayonet, is a small offset (often 1/2 inch) made with two 10-degree bends to step the conduit out to the face of a box. The 10-degree multiplier is 6, so a 1/2-inch box offset needs marks 3 inches apart.</p><p>Offsets are the daily work: two equal bends, mark spacing equal to the depth times the multiplier, shrink added to the run. The most common error is bending the second bend in the wrong direction, which makes a Z instead of an offset, or bending both bends on the same side of the marks, which makes a dogleg — a bend that is not in the same plane as the run. A dogleg is fixed by bending the conduit back, but every correction weakens the tube, so the goal is to get it right the first time.</p><p>Practice sequence for an offset: measure the depth, pick the angle (30 degrees is the default), multiply for the mark spacing, add the shrink to the run length, mark both bends, bend the first to the angle, flip the bender, slide to the second mark, bend the second to the same angle in the opposite direction, and check the result on a flat surface.</p><ul><li>Kick: one bend to step into a box. Box offset: two 10° bends, multiplier 6.</li><li>Offset: mark spacing = depth × multiplier; add shrink to the run.</li><li>Dogleg = bends not in the same plane; prevent it by keeping the conduit flat and the bender oriented the same way.</li></ul>"
