      "heading": "Offsets: The Multiplier Method",
      "html": "<p>An offset moves the conduit sideways by a set distance — to enter a box mounted on a wall, or to step around an obstruction. An offset is two equal and opposite bends, and the distance between the bend marks is the offset depth times the multiplier for the bend angle. The multipliers are: 10 degrees — 6.0; 22.5 degrees — 2.6; 30 degrees — 2.0; 45 degrees — 1.4; 60 degrees — 1.2. The 30-degree offset is the workhorse: its multiplier is 2, so the mark spacing is simply twice the offset depth.</p><p>Example: a 4-inch offset with 30-degree bends needs marks 4 × 2.0 = 8 inches apart. Mark the first bend, bend 30 degrees, flip the bender, slide it to the second mark, and bend 30 degrees the other way. The result is a parallel offset that lands the conduit exactly 4 inches sideways. Shrink — the amount the run shortens — is 1/4 inch per inch of offset for 30-degree bends, so add it to the overall measurement: a 4-inch offset shrinks the run by 1 inch.</p><p>Common offset angles and their shrink per inch of offset: 10 degrees, 1/16 inch; 22.5 degrees, 3/16 inch; 30 degrees, 1/4 inch; 45 degrees, 3/8 inch; 60 degrees, 1/2 inch. Smaller angles mean less shrink and a gentler pull, which is why 30 degrees is the usual choice and 10 degrees is used for box offsets where the depth is small.</p><ul><li>Multipliers: 10° 6.0 · 22.5° 2.6 · 30° 2.0 · 45° 1.4 · 60° 1.2.</li><li>Mark spacing = offset depth × multiplier.</li><li>Shrink per inch of offset: 10° 1/16 · 22.5° 3/16 · 30° 1/4 · 45° 3/8 · 60° 1/2 in.</li></ul>"
