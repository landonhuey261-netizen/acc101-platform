      "html": "<p>Electrical Metallic Tubing (EMT), Article 358, is thin-wall steel (or aluminum) tubing joined with compression or set-screw fittings. It is the most common raceway in commercial work and the first conduit an apprentice learns to bend. It is lighter and cheaper than rigid conduit, it bends with a hand bender, and it serves as an equipment grounding conductor when properly installed with tight fittings.</p><p>EMT is permitted in exposed and concealed work, in dry and damp locations, and in concrete where protected, but it may not be used where subject to severe physical damage, in corrosive environments unless protected, or where cinder fill or corrosive conditions will attack it (358.12). In a warehouse where forklifts hit the walls, EMT at floor level is the wrong choice — rigid conduit or a guard is needed.</p><p>Fittings matter as much as the tube. Compression fittings are watertight when properly tightened and are required in wet locations; set-screw fittings are for dry locations. A loose set screw breaks the grounding path, and a fitting tightened onto a burred tube end cuts the conductors during the pull.</p><div class=\"callout\"><strong>Key idea:</strong> EMT is the commercial standard raceway: light, bendable, and a grounding conductor when its fittings are tight. It is not for severe physical damage.</div>"
