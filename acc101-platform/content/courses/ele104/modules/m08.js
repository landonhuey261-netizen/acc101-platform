      "heading": "The Hand Bender and the 90-Degree Stub-Up",
      "html": "<p>A hand bender is a shoe with marks: the arrow (for offsets and stub-ups), the star (for back-to-back bends), the rim notch, and the degree marks. For a 90-degree stub-up — a bend that raises the conduit a set height — you use the take-up, also called the deduct: the distance from the end of the conduit to the bend mark that accounts for the radius of the bend. For 1/2-inch EMT the take-up is 5 inches; for 3/4-inch it is 6 inches; for 1-inch it is 8 inches.</p><p>The procedure: measure the desired stub height from the floor, subtract the take-up, and mark the conduit at that point. Place the bender's arrow on the mark, put your foot on the bender, and bend with steady pressure until the conduit is vertical and the bender reads 90 degrees. Check with a level — a stub that leans 5 degrees looks fine until the box is mounted on it.</p><p>Springback is real: conduit relaxes a few degrees when you release pressure, so bend a degree or two past 90 and let it settle back. Overbending and bending back weakens the tube and flattens the bend, so aim for one smooth bend to the mark.</p><ul><li>Take-up (deduct): 1/2-in. EMT 5 in. · 3/4-in. 6 in. · 1-in. 8 in.</li><li>Mark = desired stub height minus take-up; arrow on the mark.</li><li>Bend past 90 slightly for springback; check with a level.</li></ul>"
