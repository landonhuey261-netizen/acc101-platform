      "html": "<p>The NEC has nine chapters. Chapters 1 through 4 apply generally: Chapter 1 is general rules, Chapter 2 is wiring and protection, Chapter 3 is wiring methods and materials, and Chapter 4 is equipment for general use. Chapters 5, 6, and 7 are special: special occupancies, special equipment, and special conditions. Chapter 8 covers communications systems, and Chapter 9 holds the tables. The annexes at the back are explanatory, not enforceable — except Annex C, which is referenced by the conduit-fill rules.</p><p>Inside a chapter, the Code is divided into articles, each covering one topic and numbered to match its chapter: Article 250 (grounding and bonding) lives in Chapter 2, Article 310 (conductors) in Chapter 3, and Article 358 (EMT) in Chapter 3. Articles are divided into parts, and parts into numbered sections such as 250.66 or 314.16(B). The section number is the address you use to find, cite, and argue a rule.</p><p>The front of the book holds the table of contents and, at the back, a detailed index. The index is the fastest way in when you know the topic but not the article — look up “box fill” or “grounding electrode conductor” and it points you to the article. The table of contents is the fastest way in when you know the article family already.</p><ul><li>Chapters 1–4: general rules that apply to almost every job.</li><li>Chapters 5–7: special occupancies, equipment, and conditions that add to or modify the general rules.</li><li>Chapter 8: communications systems.</li><li>Chapter 9: tables for conduit fill, conductor properties, and bending radii.</li><li>Annexes A–J: explanatory material (Annex C is used for conduit fill).</li></ul>"
