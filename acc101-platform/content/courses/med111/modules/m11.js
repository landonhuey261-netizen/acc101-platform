      "html": "<p>A <strong>food allergy</strong> is an immune reaction to a food protein. It can be life-threatening: even a trace of the food can trigger anaphylaxis — trouble breathing, throat swelling, a drop in blood pressure — which needs epinephrine and emergency care. The major food allergens that must be named on U.S. labels are milk, eggs, fish, crustacean shellfish, tree nuts, peanuts, wheat, soybeans, and sesame. A person with a food allergy must read every label, every time, because recipes change — and must tell restaurants about the allergy clearly, because cross-contact in a kitchen can be enough to trigger a reaction.</p>\n<p>A <strong>food intolerance</strong> is different: it is not an immune reaction, and it is not life-threatening, though it can be very uncomfortable. <strong>Lactose intolerance</strong> is the most common — the body makes too little lactase, the enzyme that digests the milk sugar lactose, so milk causes gas, bloating, and diarrhea. People with lactose intolerance can often eat yogurt and hard cheese (which have little lactose) and can use lactose-free milk. <strong>Celiac disease</strong> is an autoimmune condition, not an allergy or a simple intolerance: eating gluten (a protein in wheat, barley, and rye) damages the small intestine, and the only treatment is a strict gluten-free diet for life — a medical condition that needs a clinician and a dietitian, not general advice. A nutrition coach must never diagnose an allergy or intolerance, and must never tell someone to stop eating a food group without a clinician's guidance.</p>"
