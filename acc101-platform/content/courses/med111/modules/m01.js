      "html": "<p>A <strong>calorie</strong> (technically a kilocalorie, or kcal) is a unit of energy: the amount of heat needed to raise one kilogram of water by one degree Celsius. On food labels, \"calories\" means kilocalories. When a label says a food has 200 calories, it means your body can get about 200 kcal of energy from it. That energy powers everything: heartbeat, breathing, thinking, walking, digesting the next meal.</p>\n<p>The body spends energy in three main ways. The largest share goes to the <strong>basal metabolic rate (BMR)</strong> — the energy needed just to stay alive at rest: heartbeat, breathing, body temperature, and basic cell work. The second share goes to physical activity, from walking to the bus to running a marathon. The third, smallest share goes to digesting food itself (the thermic effect of food). Together they make up total daily energy expenditure — the number your food intake is balanced against, which is the subject of Module 7.</p>\n<p>Foods are also described by their <strong>nutrient density</strong>: how much nutrition a food provides for its calories. A nutrient-dense food — beans, leafy greens, salmon, whole grains — packs vitamins, minerals, and fiber into relatively few calories. An energy-dense but nutrient-poor food — soda, candy, chips — packs many calories with little else. Eating well is mostly a matter of choosing nutrient-dense foods most of the time and keeping the rest as the exception.</p>"
