      "html": "<p>Nutrients are sorted by how much of them the body needs. <strong>Macronutrients</strong> are needed in large amounts: carbohydrates, proteins, fats, and water. They provide energy (except water, which provides none) and the raw materials for building the body. <strong>Micronutrients</strong> are needed in small amounts: vitamins and minerals. Small does not mean unimportant — a tiny shortage of vitamin C or iron can make a person seriously ill. The difference is quantity, not importance.</p>\n<p>Each macronutrient provides a fixed amount of energy. Carbohydrates and protein each provide <strong>4 kilocalories (kcal) per gram</strong>, and fat provides <strong>9 kcal per gram</strong>. Alcohol provides about 7 kcal per gram, but it is not a nutrient — it provides energy with no building or regulatory value. These three numbers (4, 4, and 9) are the foundation of all calorie math in this course: they are how a label's grams become a label's calories, and how a day's food becomes a day's energy.</p>\n<p>Within each class there is a further split: <strong>essential</strong> nutrients are ones the body cannot make for itself (or cannot make enough of), so they must come from food. Essential amino acids, essential fatty acids, vitamins, minerals, and water are all essential. <strong>Nonessential</strong> nutrients are ones the body can make from other materials — for example, the body can make glucose from other carbohydrates, and it can make many amino acids itself. Essential does not mean \"more important\" — it means \"you must eat it, because your body cannot make it.\"</p>"
