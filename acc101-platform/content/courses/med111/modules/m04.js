      "heading": "Trans Fat and Cholesterol",
      "html": "<p><strong>Trans fat</strong> is made when liquid oil is partially hydrogenated — hydrogen is forced into it to make it solid and shelf-stable, as in old-style margarines, shortenings, and many fried and baked goods. Trans fat is the worst fat for heart health: it raises LDL (\"bad\") cholesterol and lowers HDL (\"good\") cholesterol at the same time. Because of that, the U.S. Food and Drug Administration removed partially hydrogenated oils from the list of foods generally recognized as safe, and they are now effectively banned from the U.S. food supply — but trans fat can still appear in small amounts in some imported foods and in foods fried in reused oil, so checking labels still matters.</p>\n<p><strong>Cholesterol</strong> is a waxy, fat-like substance the body needs: it builds cell membranes, makes vitamin D, and is the raw material for steroid hormones and bile acids. The liver makes all the cholesterol the body needs, so dietary cholesterol is not essential. For many years, guidance focused on limiting dietary cholesterol (eggs were the famous example), but current guidance focuses more on saturated fat, because saturated fat raises blood cholesterol more than dietary cholesterol does for most people. Eggs are now understood to be a reasonable food for most people — it is the bacon and butter alongside them that matter more. People with high cholesterol or heart disease should still follow their clinician's advice, not general guidance.</p>\n<p>Two blood measures matter most in heart health. <strong>LDL cholesterol</strong> carries cholesterol to tissues and, when high, deposits it in artery walls — hence \"bad\" cholesterol. <strong>HDL cholesterol</strong> carries cholesterol away from tissues back to the liver — hence \"good\" cholesterol. Saturated fat raises LDL; trans fat raises LDL and lowers HDL; unsaturated fats tend to lower LDL and, in the case of monounsaturated fat, can help maintain HDL.</p>"
