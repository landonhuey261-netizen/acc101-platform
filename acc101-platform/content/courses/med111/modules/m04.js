      "heading": "Saturated, Monounsaturated, Polyunsaturated",
      "html": "<p>Fatty acids differ in their chemical bonds, and that difference decides whether a fat is solid or liquid at room temperature and how it affects health. <strong>Saturated fats</strong> have no double bonds between their carbon atoms — they are \"saturated\" with hydrogen — and they are usually solid at room temperature: butter, lard, the fat on meat, coconut oil, palm oil. <strong>Unsaturated fats</strong> have one or more double bonds, which bend the molecule and keep it liquid: oils such as olive, canola, and sunflower oil.</p>\n<p>Unsaturated fats split into two groups. <strong>Monounsaturated fats</strong> have one double bond — olive oil, canola oil, avocados, most nuts. <strong>Polyunsaturated fats</strong> have two or more double bonds — sunflower oil, soybean oil, corn oil, walnuts, flaxseed, and fatty fish. As a rule, replacing saturated fat with unsaturated fat — especially polyunsaturated fat — lowers blood cholesterol and lowers heart disease risk. That replacement, rather than simply cutting all fat, is the heart of modern fat guidance.</p>\n<p>Two fatty acids are <strong>essential</strong>, meaning the body cannot make them: <strong>linoleic acid</strong> (an omega-6 fatty acid) and <strong>alpha-linolenic acid</strong> (an omega-3 fatty acid). From these, the body makes longer-chain fatty acids, including <strong>EPA and DHA</strong>, the omega-3s found in fatty fish (salmon, sardines, mackerel) that support heart and brain health. Most people get plenty of omega-6 from vegetable oils and processed foods but too little omega-3 — eating fatty fish twice a week is the standard recommendation for closing that gap.</p>"
