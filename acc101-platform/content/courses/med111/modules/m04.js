      "html": "<p>Fats — also called <strong>lipids</strong> — are the most energy-dense macronutrient, providing <strong>9 kilocalories per gram</strong>, more than double carbohydrate or protein. A fat molecule is built from a glycerol backbone with three <strong>fatty acids</strong> attached, which is why dietary fats are called triglycerides. Fat does far more than store energy: it builds cell membranes, insulates the body, cushions organs, carries the fat-soluble vitamins (A, D, E, and K), and provides the raw material for hormones and for the molecules that control inflammation.</p>\n<p>The body stores fat in adipose tissue — the body's long-term energy bank. Unlike glycogen, which holds roughly a day's worth of glucose, fat stores can hold weeks or months of energy. That is a survival advantage, but it is also why excess calories so easily become excess body fat: any macronutrient eaten beyond need can be stored as fat, and fat is the form the body prefers for storage.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Fat is not just stored energy — it is structure (cell membranes), insulation, vitamin transport, and hormone material. The question is never \"fat or no fat\" — it is which fats, and how much.</div>"
