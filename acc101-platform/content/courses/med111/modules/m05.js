      "heading": "What Vitamins Are",
      "html": "<p>Vitamins are organic compounds the body needs in small amounts to regulate processes — they do not provide energy and they are not building materials in the way protein is. Instead, vitamins act as helpers: many of them are <strong>coenzymes</strong>, molecules that enzymes need in order to do their work. Without the right vitamin, the enzyme cannot function, and the reaction it controls slows or stops. That is why a vitamin deficiency shows up as a breakdown in a specific process — bleeding gums without vitamin C, poor night vision without vitamin A, anemia without folate or B12.</p>\n<p>There are 13 vitamins, and they fall into two groups by how they dissolve. <strong>Fat-soluble vitamins</strong> (A, D, E, and K) dissolve in fat, are stored in the body's fat and liver, and can build up to toxic levels if taken in large doses. <strong>Water-soluble vitamins</strong> (vitamin C and the eight B vitamins) dissolve in water, are not stored in large amounts, and excess is usually excreted in urine — which is why they need to be eaten more regularly, but also why they are harder to overdose on. The storage difference is the single most important fact about vitamins: fat-soluble vitamins can accumulate, water-soluble vitamins generally cannot.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Vitamins are regulators, not fuel. Fat-soluble vitamins (A, D, E, K) are stored and can build up to toxic levels. Water-soluble vitamins (C and the B vitamins) are not stored and need regular intake.</div>"
