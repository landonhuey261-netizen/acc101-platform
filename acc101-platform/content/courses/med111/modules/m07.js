      "html": "<p>Total daily energy expenditure has three parts. The largest is the <strong>basal metabolic rate (BMR)</strong> — the energy needed just to stay alive at rest: heartbeat, breathing, body temperature, and basic cell work. BMR is roughly 60 to 75 percent of total expenditure for most people. It depends mainly on body size and composition: bigger people and people with more muscle burn more at rest, because muscle is metabolically active tissue. BMR falls with age (muscle is lost) and rises with fever or illness.</p>\n<p>The second part is <strong>physical activity</strong> — everything from walking to the bus to running a marathon, plus the small movements of daily life (fidgeting, standing, chores), sometimes called non-exercise activity thermogenesis (NEAT). Activity is the most variable part: it can be 15 percent of expenditure for a sedentary person or 50 percent for a very active one. It is also the part you control most directly. The third part is the <strong>thermic effect of food</strong> — the energy spent digesting, absorbing, and processing food, roughly 10 percent of intake. Protein costs the most energy to process, then carbohydrate, then fat — but the differences are small compared with the total.</p>\n<p>To estimate a person's needs, clinicians start with BMR (from a formula using weight, height, age, and sex) and multiply by an activity factor. The result is a maintenance estimate — the calories that hold weight steady. It is an estimate, not a measurement: two people with the same numbers can differ by hundreds of calories a day. The practical use is as a starting point, adjusted by watching what actually happens over weeks.</p>"
