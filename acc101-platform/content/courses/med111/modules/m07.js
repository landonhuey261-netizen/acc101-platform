      "html": "<p>The body uses carbohydrate first for quick energy: glucose in the blood, then glycogen in the liver and muscles. When glycogen runs low — during long exercise or fasting — the body shifts to fat, breaking down stored triglycerides into fatty acids. Protein is the last fuel the body turns to, because protein is needed for structure and work; the body only burns significant protein when energy is scarce or during prolonged fasting or illness. This order is why carbohydrate is the sprinter's fuel and fat is the marathoner's reserve.</p>\n<p><strong>Metabolism</strong> is the sum of all chemical reactions in the body — the building-up reactions (anabolism, such as building muscle from amino acids) and the breaking-down reactions (catabolism, such as breaking down glucose for energy). The two run at the same time, in balance. After a meal, building dominates; between meals, breaking down dominates. Hormones direct the traffic: insulin after eating, glucagon and adrenaline between meals and during exercise.</p>\n<p>One more concept: <strong>metabolic adaptation</strong>. When a person eats much less for a long time, the body adapts — BMR falls, activity drops, hunger hormones rise, fullness hormones fall. The adaptation is the body defending its weight, and it is a major reason weight lost quickly comes back. Slow, steady changes that the body can adapt to — more activity, more protein and fiber, smaller portions of energy-dense foods — are more sustainable than crash diets.</p>"
