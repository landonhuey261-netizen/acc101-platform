      "html": "<p>Water is the most essential nutrient of all: the body can survive weeks without food but only days without water. Water makes up about 60 percent of an adult's body weight. It carries nutrients to cells and waste away from them, regulates body temperature through sweat, lubricates joints, protects the brain and spinal cord, and is the medium in which every chemical reaction in the body happens. Water provides no calories — but without it, nothing else works.</p>\n<p>How much water do people need? The National Academies set <strong>adequate intakes</strong> for total water (from all foods and drinks) at about <strong>3.7 liters per day for men and 2.7 liters per day for women</strong> — roughly 15 cups and 11 cups, though about a fifth of that comes from food. Needs rise with heat, exercise, illness (especially fever, vomiting, or diarrhea), and pregnancy and breastfeeding. The \"eight glasses a day\" rule is a rough folk guideline, not a scientific prescription — thirst, urine color (pale yellow is the goal), and the conditions of the day are better guides. Water is the best drink; sugary drinks add calories without nutrition.</p>\n<p><strong>Dehydration</strong> — losing more water than you take in — causes thirst, dry mouth, dark urine, headache, fatigue, and dizziness, and in severe cases confusion and fainting. Older adults are at higher risk because their sense of thirst weakens with age. <strong>Overhydration</strong> is rarer but real: drinking far more water than the kidneys can handle (usually during extreme endurance exercise) dilutes blood sodium and can cause confusion, seizures, and even death — a condition called hyponatremia. The safe rule is simple: drink to thirst, drink more in heat and exercise, and do not force large volumes of water.</p>"
