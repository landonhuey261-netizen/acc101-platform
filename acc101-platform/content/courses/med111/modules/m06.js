      "heading": "Calcium, Iron, Sodium, and Potassium",
      "html": "<p><strong>Calcium</strong> is the most abundant mineral in the body, and 99 percent of it is in bones and teeth. The other 1 percent is in blood and cells, where it controls muscle contraction, nerve signals, and blood clotting. The body keeps blood calcium in a tight range — if the diet provides too little, it takes calcium from bone. Over years, that weakens bones and leads to osteoporosis. The adult recommendation is about 1,000 milligrams per day (1,200 mg for women over 50 and men over 70). Best sources: dairy, fortified plant milks, leafy greens, and canned sardines with bones. Vitamin D is needed to absorb calcium, which is why the two are always discussed together.</p>\n<p><strong>Iron</strong> carries oxygen: it is the core of hemoglobin in red blood cells and of myoglobin in muscle. Iron deficiency is the most common nutrient deficiency in the world, and it causes <strong>iron-deficiency anemia</strong> — fatigue, weakness, pale skin, and poor concentration. Iron comes in two forms: <strong>heme iron</strong> from animal foods (meat, fish, poultry), which is absorbed well, and <strong>non-heme iron</strong> from plant foods (beans, lentils, spinach, fortified cereals), which is absorbed poorly — unless vitamin C is eaten at the same meal, which sharply improves absorption. Tea and coffee with a meal reduce iron absorption. Women of childbearing age need more iron than men because of blood loss in menstruation.</p>\n<p><strong>Sodium and potassium</strong> work as a pair to control fluid balance and blood pressure. Sodium is the main mineral outside cells; potassium is the main mineral inside cells. The body needs both, but the modern diet is overloaded with sodium and short on potassium. The Dietary Guidelines recommend keeping sodium below <strong>2,300 milligrams per day</strong> — about one teaspoon of salt — while most Americans eat about 3,400 milligrams, mostly from processed foods, restaurant meals, and bread, not from the salt shaker. Potassium, found in fruits, vegetables, beans, and dairy, helps the body excrete sodium and relax blood vessels, which helps lower blood pressure. The practical fix is not a salt-free diet — it is cooking more, eating more whole plant foods, and eating fewer processed foods.</p>"
