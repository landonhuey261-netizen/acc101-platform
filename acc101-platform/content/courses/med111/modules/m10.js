      "html": "<p>Healthy eating is easier to picture as a day than as a list of rules. Breakfast: oatmeal with berries and walnuts, or eggs with whole-wheat toast and fruit — protein and fiber to start the day, not sugar alone. A mid-morning snack if hungry: yogurt, fruit, or a handful of nuts. Lunch: a grain bowl or wrap with beans or chicken, vegetables, and a whole grain, plus water. An afternoon snack if needed: an apple with peanut butter, or vegetables with hummus. Dinner: fish or poultry or beans, a whole grain, and two vegetables — one of them dark green or orange. Water through the day; alcohol, if at all, in moderation and with food.</p>\n<p>Notice what the day does not include: no sugary drinks, no deep-fried foods, no large portions of processed meat, no dessert at every meal. Notice also what it does include: protein and fiber at every meal, vegetables at lunch and dinner, fruit at least twice, whole grains at least twice, and water as the drink. That is the pattern — and it can be built from any cuisine. A Mexican day (beans, rice, corn tortillas, salsa, avocado), an Indian day (dal, rice, vegetables, yogurt), and a Chinese day (tofu, rice, stir-fried vegetables, soup) all fit the same pattern with different foods.</p>\n<p>Portion awareness matters too. The most common portion problem is not one food but the slow growth of portions over decades: bagels, muffins, restaurant entrees, and soft drinks are all much larger than they were a generation ago. Using a smaller plate, serving food in the kitchen rather than at the table, and stopping when comfortably full rather than stuffed are simple, effective habits.</p>"
