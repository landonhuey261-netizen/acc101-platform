      "html": "<p>Many different eating patterns can be healthy, because health comes from the pattern's nutrient profile, not its name. Three well-studied patterns are the <strong>Mediterranean</strong>, <strong>DASH</strong>, and <strong>vegetarian</strong> patterns. The <strong>Mediterranean pattern</strong> comes from the traditional diets of Greece, Italy, and Spain: abundant vegetables, fruits, whole grains, beans, nuts, and olive oil; fish and seafood several times a week; poultry, eggs, and dairy in moderation; red meat rarely; and meals shared with others. It is linked to lower risks of heart disease, stroke, and type 2 diabetes.</p>\n<p>The <strong>DASH pattern</strong> (Dietary Approaches to Stop Hypertension) was designed to lower blood pressure: it is rich in vegetables, fruits, whole grains, low-fat dairy, fish, poultry, beans, nuts, and seeds, and low in sodium, saturated fat, and added sugars. It works — DASH lowers blood pressure measurably, especially when sodium is also reduced. The <strong>vegetarian pattern</strong> excludes meat and fish (with variations that include dairy, eggs, or both) and, when well planned, provides all nutrients except vitamin B12, which needs a fortified source or supplement. All three patterns share the same core: mostly plants, whole grains, healthy fats, and little added sugar, saturated fat, and sodium.</p>\n<p>What makes any pattern healthy is the same list: plenty of vegetables and fruits, whole grains, a variety of protein foods, healthy fats, and limits on added sugars, saturated fat, sodium, and alcohol. A pattern that meets that list is healthy whether it is called Mediterranean, DASH, vegetarian, or simply \"the way my grandmother cooked.\" A pattern that fails the list is not healthy, however fashionable its name.</p>"
