      "heading": "Carbohydrate, Protein, and Fat: The Big Three",
      "html": "<p><strong>Carbohydrate</strong> is the body's main fuel: sugars, starches, and fiber. All digestible carbohydrate becomes glucose; insulin moves glucose into cells; the extra is stored as glycogen or fat. Fiber — soluble (oats, beans) and insoluble (bran, vegetables) — steadies blood sugar, lowers cholesterol, feeds gut bacteria, and adds fullness. Recommendation: about 14 grams of fiber per 1,000 calories, and carbohydrate about 45–65 percent of calories, with added sugars below 10 percent.</p>\n<p><strong>Protein</strong> is the building material: 20 amino acids, 9 of them essential. Complete proteins (animal foods, soy, quinoa) provide all nine; incomplete proteins (most plant foods) are combined across the day as complementary proteins. Protein jobs include muscle, enzymes, antibodies, hormones, hemoglobin, and collagen. The adult RDA is 0.8 grams per kilogram of body weight per day; older adults need about 1.0–1.2 g/kg. Extra protein becomes energy or fat — it does not build muscle alone.</p>\n<p><strong>Fat</strong> is the most energy-dense nutrient at 9 kcal per gram, and it is structure, insulation, vitamin transport, and hormone material. Saturated fats are solid (butter, fatty meat); monounsaturated fats have one double bond (olive oil); polyunsaturated fats have two or more (sunflower oil, fish). The essential fatty acids are linoleic acid (omega-6) and alpha-linolenic acid (omega-3); EPA and DHA come from fatty fish. Trans fat raises LDL and lowers HDL and is effectively banned in the U.S. food supply. Total fat: about 20–35 percent of calories; saturated fat: below 10 percent.</p>"
