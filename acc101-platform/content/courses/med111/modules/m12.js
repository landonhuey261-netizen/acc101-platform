      "heading": "Energy, Labels, and Planning",
      "html": "<p><strong>Energy balance</strong> is intake vs. expenditure: intake above expenditure stores fat; intake below expenditure draws on stores. Expenditure has three parts: BMR (60–75 percent, the largest), physical activity (the most variable), and the thermic effect of food (about 10 percent). The body uses glucose, then glycogen, then fat, then protein — and it defends its weight through metabolic adaptation when intake falls. Healthy weight management is habits, not drama: nutrient-dense foods, moderate portions, water over sugary drinks, more movement, enough sleep, mindful eating.</p>\n<p><strong>Food labels</strong> are read top to bottom: serving size first, then calories, then nutrients. Every number is per serving — multiply by how much you ate. The 5% / 20% rule: 5% DV or less is low, 20% DV or more is high. Ingredients are listed by weight; added sugars hide under many names; whole grain must be the first ingredient. The front of the package is advertising; the back is information.</p>\n<p><strong>Diet planning</strong> rests on six principles: adequacy, balance, calorie control, nutrient density, moderation, and variety. The inverted food pyramid shows the shape: protein, dairy, healthy fats, fruits and vegetables at the wide top, whole grains at the narrow bottom. The Dietary Guidelines set the limits: added sugars below 10 percent, saturated fat below 10 percent, sodium below 2,300 mg, alcohol in moderation if at all. Mediterranean, DASH, and vegetarian patterns are all healthy because they share the same nutrient profile. Special considerations — vegetarian diets, allergies, culture, and budget — are handled by working inside a person's tradition and circumstances, not against them.</p>"
