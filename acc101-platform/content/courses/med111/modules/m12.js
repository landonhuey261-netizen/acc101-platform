      "html": "<p><strong>Vitamins</strong> are regulators, often coenzymes. There are 13: four fat-soluble (A, D, E, K — stored, can be toxic in excess) and nine water-soluble (C and the eight B vitamins — not stored, need regular intake). Vitamin A is for vision and immunity; vitamin D for calcium absorption and bone (made in skin from sunlight); vitamin E is an antioxidant; vitamin K is for blood clotting. Vitamin C is for collagen, wound healing, and iron absorption. Folate prevents neural tube defects; B12 comes only from animal foods or fortified foods. Vitamins follow a U-shaped curve: too little harms, enough helps, too much harms. Food first; supplements only when a clinician identifies a need.</p>\n<p><strong>Minerals</strong> are elements the body cannot make and cooking cannot destroy. Major minerals (over 100 mg/day): calcium, phosphorus, magnesium, sodium, potassium, chloride, sulfur. Trace minerals: iron, zinc, iodine, selenium, and others. Calcium builds bone (~1,000 mg/day, needs vitamin D); iron carries oxygen (vitamin C improves plant iron absorption); sodium stays below 2,300 mg/day (mostly from processed foods); potassium helps lower blood pressure. <strong>Water</strong> is the most essential nutrient: about 60 percent of body weight, with adequate intakes of about 3.7 liters per day for men and 2.7 liters for women from all foods and drinks. Drink to thirst; more in heat and exercise.</p>"
