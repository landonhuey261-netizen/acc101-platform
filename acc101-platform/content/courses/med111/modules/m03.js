      "html": "<p>Protein is the body's main building material. Like carbohydrates, it provides <strong>4 kilocalories per gram</strong>, but its real job is not fuel — it is structure and work. Proteins are built from smaller units called <strong>amino acids</strong>, linked together in long chains that fold into specific shapes. The shape is the job: a protein's shape decides whether it becomes muscle fiber, an enzyme, a hormone, or an antibody. Change the shape and you change the function.</p>\n<p>There are 20 amino acids the body uses to build proteins. Nine of them are <strong>essential amino acids</strong> — the body cannot make them, so they must come from food. The other eleven are <strong>nonessential</strong> — the body can make them from other materials. The word \"essential\" here works exactly as it did in Module 1: it means \"must be eaten,\" not \"more important.\" A food that provides all nine essential amino acids in the right proportions is called a <strong>complete protein</strong>. A food that is low in one or more essential amino acids is an <strong>incomplete protein</strong>.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Protein is not mainly fuel — it is building material and working machinery. Its value comes from its amino acids, and the nine essential amino acids must come from food.</div>"
