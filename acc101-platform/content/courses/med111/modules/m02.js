      "html": "<p>Carbohydrates are the body's main energy source. They are made of carbon, hydrogen, and oxygen — the name literally means \"carbon plus water\" — and they come in three types: <strong>sugars</strong>, <strong>starches</strong>, and <strong>fiber</strong>. Sugars are the simplest form: single sugar molecules (like glucose and fructose) or pairs of them (like sucrose, table sugar, which is one glucose plus one fructose). Starches are long chains of glucose molecules packed together, found in grains, potatoes, and beans. Fiber is also made of long chains, but the human body cannot break its bonds — so fiber passes through mostly undigested.</p>\n<p>Almost all digestible carbohydrate ends up as <strong>glucose</strong> in the blood. Glucose is the fuel the brain runs on and the fuel muscles use first during activity. The body stores a small amount of glucose as <strong>glycogen</strong> in the liver and muscles — a quick-access reserve that lasts roughly a day — and any extra energy beyond that is stored as fat. That is why carbohydrate is the body's main fuel but not its main storage: glycogen is the wallet, fat is the bank.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Sugars, starches, and fiber are all carbohydrates — but they behave very differently. Sugars act fast, starches act more slowly, and fiber does not act as fuel at all. The type matters as much as the amount.</div>"
