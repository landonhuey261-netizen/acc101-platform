      "html": "<p><strong>Fiber</strong> is the part of plant food the human body cannot digest. It comes in two main kinds. <strong>Soluble fiber</strong> dissolves in water and forms a gel in the gut — it slows digestion, steadies blood sugar, and helps lower blood cholesterol. Oats, beans, lentils, apples, and barley are rich in it. <strong>Insoluble fiber</strong> does not dissolve — it adds bulk to stool, keeps things moving through the gut, and helps prevent constipation. Whole wheat, bran, and many vegetables are rich in it. Most plant foods contain both kinds, which is another reason to eat a variety of them.</p>\n<p>Fiber does a lot for very few calories: it adds fullness so you eat less, feeds the gut bacteria that support digestion and immunity, and is linked to lower risks of heart disease, type 2 diabetes, and colon problems. The general recommendation is about <strong>14 grams of fiber for every 1,000 calories</strong> eaten — roughly 25 grams a day for women and 38 grams a day for men on typical calorie intakes, though exact needs vary by age and calorie level. Most Americans eat only about half that much. The fix is simple and gradual: more beans, whole grains, vegetables, and fruit — and more water, because fiber without water can cause discomfort. Increase fiber slowly over a week or two to let the gut adjust.</p>\n<p>One warning: fiber supplements and fiber-added processed foods are not the same as fiber from whole foods. A fiber bar may list 10 grams of fiber, but it does not bring the vitamins, minerals, and plant compounds that beans or oats bring with theirs. Whole foods first; supplements only when a clinician advises them.</p>"
