      "heading": "Simple vs. Complex — and Why Speed Matters",
      "html": "<p>Carbohydrates are often described as <strong>simple</strong> or <strong>complex</strong>. Simple carbohydrates are sugars: one or two molecules, broken down and absorbed quickly. Complex carbohydrates are starches and fiber: long chains that take longer to break down. As a rule, simple carbohydrates raise blood sugar fast, and complex carbohydrates raise it more slowly — but the rule has exceptions, and the whole food matters more than the label. White bread is a starch, but it is refined and low in fiber, so it raises blood sugar almost as fast as sugar. Whole-grain bread is also a starch, but its fiber slows digestion, so blood sugar rises more gently.</p>\n<p>Two ideas help you judge a carbohydrate food. The <strong>glycemic index (GI)</strong> ranks foods by how fast they raise blood sugar compared with pure glucose. High-GI foods (white bread, sugary drinks, white rice) spike blood sugar quickly; low-GI foods (beans, lentils, whole grains, most vegetables) raise it slowly. The <strong>glycemic load</strong> adds portion size: a small serving of a high-GI food may raise blood sugar less than a huge serving of a low-GI food. For everyday eating, you do not need to memorize GI tables — you need the pattern: whole, fiber-rich, minimally processed carbohydrate foods are steadier fuel than refined, sugary ones.</p>\n<p>After eating carbohydrate, blood sugar rises and the pancreas releases <strong>insulin</strong>, a hormone that moves glucose from the blood into cells and tells the liver to store the extra as glycogen. When blood sugar falls, another hormone, <strong>glucagon</strong>, releases stored glucose back into the blood. In a healthy person this system keeps blood sugar in a narrow range all day. In type 2 diabetes, the system breaks down — cells respond poorly to insulin, or the pancreas cannot make enough — and blood sugar stays high. That is the subject of Module 6 in the next course.</p>"
