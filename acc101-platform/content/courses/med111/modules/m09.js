      "html": "<p>Good diet planning rests on six principles. <strong>Adequacy</strong> means the diet provides enough of every nutrient and enough energy. <strong>Balance</strong> means the right proportions — enough of each food group, and not too much of any one thing. <strong>Calorie control</strong> means matching intake to need so weight stays steady. <strong>Nutrient density</strong> means choosing foods that pack the most nutrition per calorie. <strong>Moderation</strong> means limiting the foods that are high in added sugars, saturated fat, and sodium — not banning them, but keeping them occasional. <strong>Variety</strong> means eating different foods within each group, because no single food covers everything.</p>\n<p>These six principles work together. A diet can be adequate but not balanced (enough calories but no vegetables). It can be balanced but not moderate (the right groups but too much sugar). It can be nutrient-dense but not varied (the same three healthy foods every day, missing nutrients the others would provide). Planning is the act of checking all six at once — and the simplest check is the plate itself, which is the subject of the next section.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The six principles — adequacy, balance, calorie control, nutrient density, moderation, variety — are the checklist for any diet plan. If a plan fails one of them, it is not a good plan, however fashionable it is.</div>"
