      "heading": "Planning a Day of Meals",
      "html": "<p>Meal planning starts with the day, not the meal. First, decide the calorie level — for many adults, about 2,000 calories is a useful starting point, adjusted up or down by size, age, and activity. Second, divide the day into meals and snacks: breakfast, lunch, dinner, and one or two snacks. Third, fill each meal following the inverted pyramid, and check the six principles at the end of the day: did the day include vegetables, fruits, whole grains, protein foods, and dairy? Did it stay within the limits for added sugars, saturated fat, and sodium? Did it include enough fiber and water?</p>\n<p>Here is an example day at about 2,000 calories. Breakfast: oatmeal with berries and walnuts, plus low-fat milk. Lunch: a whole-wheat wrap with beans, peppers, and avocado, plus an apple. Snack: yogurt with a handful of almonds. Dinner: baked salmon, brown rice, and steamed broccoli with a drizzle of olive oil. Water through the day. That day covers all five food groups, provides fiber and protein at every meal, keeps saturated fat low, and stays well within the added-sugar limit — and it uses ordinary foods, not special products.</p>\n<p>Planning also means planning for real life. Cook once, eat twice: make a big pot of beans or a tray of roasted vegetables and use them in two or three meals. Keep a stocked pantry: whole grains, canned beans, canned tomatoes, frozen vegetables, oils, spices. Keep healthy snacks visible and less-healthy snacks out of sight — environment beats willpower. And plan for the days that go wrong: a frozen vegetable stir-fry and a can of beans is a real dinner, and it beats skipping the meal and eating everything in sight at 10 p.m.</p>"
