      "html": "<p><strong>Keynesian theory</strong> blames demand: animal spirits swing investment, the multiplier amplifies the swing, and sticky wages and prices stop the economy self-correcting quickly. Policy can and should stabilize demand. <strong>Monetarist theory</strong> (Milton Friedman) blames money: the central bank lets the money supply swing, and those swings become output swings after a lag. Its prescription is a steady money-growth rule, not fine-tuning. <strong>Real business cycle (RBC) theory</strong> blames supply: random shocks to technology and productivity move potential output itself, and the economy's ups and downs are efficient responses — booms are times when working more is worthwhile, recessions times when it is not. In RBC, stabilizing demand is pointless or harmful, because the cycle is the economy doing its best.</p><p>These theories disagree about the cause, and therefore about the cure — but they agree on the facts to explain: output, jobs, and investment move together; consumption moves less; and prices move sluggishly. Modern macroeconomics blends them: demand shocks matter in the short run (Keynes), money matters through interest rates (monetarist), and supply shocks matter always (RBC). The exam will ask you to match a shock to a theory, not to pick a winner.</p><div class=\"callout\"><strong>Key idea:</strong> Same cycle, three diagnoses: demand (Keynes), money (Friedman), technology (RBC). The diagnosis you believe decides the policy you prescribe.</div>"
