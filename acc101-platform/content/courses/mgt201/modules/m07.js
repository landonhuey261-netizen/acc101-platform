      "html": "\n<p>Goods move by five modes, each with its own trade-off. <strong>Road</strong> (truck) is flexible and door-to-door, the workhorse of short and medium distances. <strong>Rail</strong> is cheap for heavy, long-distance loads but slow and inflexible. <strong>Air</strong> is the fastest and the most expensive, used for urgent or high-value goods. <strong>Water</strong> (ship) is the cheapest per unit for large, heavy, international loads but the slowest. <strong>Pipeline</strong> moves liquids and gases continuously at low cost.</p>\n<p>The choice follows the product: heavy and cheap goes by water or rail; urgent and valuable goes by air; everything else goes by road, often in combination. <strong>Intermodal</strong> transport combines modes — a container that travels by ship, then rail, then truck — keeping the goods in the same container so handling is fast and damage is low.</p>\n<p>Reliability matters as much as speed. A mode that is usually fast but sometimes three days late forces the receiver to hold safety stock, and that stock costs money. The true cost of a transport choice includes the inventory it forces the business to hold.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Choose the mode by the product: heavy and cheap by water or rail, urgent and valuable by air, the rest by road — and count the safety stock an unreliable mode forces you to hold.</div>"
