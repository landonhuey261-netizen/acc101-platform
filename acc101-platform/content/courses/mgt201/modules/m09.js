      "html": "\n<p>A <strong>project</strong> is a temporary effort to create a unique result: opening a new shop, launching a website, or moving a warehouse. It has a beginning and an end, a defined scope, and a team that disbands when the work is done. <strong>Operations</strong>, by contrast, is the ongoing, repeating work of running the business — the daily production, the weekly deliveries — which has no end date and produces the same result again and again.</p>\n<p>Every project is judged against the <strong>triple constraint</strong>: <strong>scope</strong> (what must be delivered), <strong>time</strong> (when it must be finished), and <strong>cost</strong> (what it may spend). The three are linked: widen the scope and the project takes longer or costs more; cut the budget and something must give — scope or time. Quality sits in the middle of the triangle, affected by all three. A project manager's job is to hold the balance the customer agreed to, and to make the trade-off explicit when it breaks.</p>\n<p>Projects fail in predictable ways: a scope nobody wrote down, so it grows without control; a deadline set before the work was estimated; a budget that ignores the cost of the people doing the work. The tools in this module exist to stop exactly those failures.</p>\n<div class=\"callout\"><strong>Key idea:</strong> A project is temporary and unique; operations is ongoing and repeating. Scope, time, and cost are linked — change one and at least one other must move.</div>"
