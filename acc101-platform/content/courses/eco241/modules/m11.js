      "html": "<p>The IMF has about 190 member countries. Its jobs are threefold. <strong>Surveillance:</strong> it monitors members' economies and warns about risks — the annual Article IV check-up on each country. <strong>Lending:</strong> when a country cannot pay for imports or service its debts, the IMF lends foreign currency so it can adjust without collapsing — the firefighter role. <strong>Technical help:</strong> it advises central banks and finance ministries on policy.</p>\n<p>IMF lending comes with <strong>conditionality</strong>: the borrower agrees to policy changes — cutting a deficit, raising interest rates, reforming banks — meant to fix the cause of the crisis. Worked example: a country borrows $200 million to be repaid over 10 years. Ignoring interest, the principal repaid each year is $200 million ÷ 10 = <strong>$20 million a year</strong>. The arithmetic is simple; the politics is not — conditionality is the IMF's most criticized feature, because the conditions bite ordinary people while the crisis was often caused by elites. The IMF's answer is that lending without conditions would fund the same policies that caused the crisis.</p>\n<p>The IMF is funded by members' <strong>quotas</strong> — contributions that decide both how much a country can borrow and how much it can vote. Quotas give large economies more votes, which critics call undemocratic and defenders call realistic: the biggest contributors bear the biggest risk. The IMF also created <strong>Special Drawing Rights (SDRs)</strong>, an international reserve asset that supplements members' reserves in a crisis.</p>"
