      "html": "<p><strong>Insurance</strong> is a deal: you pay a small, known amount — the <strong>premium</strong> — and the insurer agrees to pay a large, unknown amount if something bad happens. You are not buying a profit; you are buying protection against the one event that would wreck your plan. A $1,500 car repair is annoying. A $150,000 house fire without insurance is life-changing.</p>\n<p>The right question is never “is insurance a good deal?” — the insurer expects to collect more than it pays out, on average. The right question is “which losses can I not afford?” Insure the losses you cannot absorb: your home burning, a major illness, a lawsuit after a car crash, your family losing your income. Skip or self-insure the small stuff.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Insurance is for losses you cannot afford, not for annoyances you can. Insure the catastrophe, save for the inconvenience.</div>"
