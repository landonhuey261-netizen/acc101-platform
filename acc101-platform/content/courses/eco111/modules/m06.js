      "html": "<p><strong>Life insurance</strong> replaces your income for the people who depend on it if you die. If nobody depends on your income, you probably do not need it yet. If a partner, a child, or a parent depends on your paycheck, you do.</p>\n<p><strong>Term life</strong> covers you for a set period — 10, 20, or 30 years — and pays only if you die during that term. It is simple and cheap: a healthy young adult can often buy a large term policy for the price of a streaming subscription or two each month. <strong>Whole life</strong> covers you for life and builds a cash value, but it costs many times more for the same death benefit, and the investment part is usually a poor deal compared with investing separately.</p>\n<p>For most beginners, the rule is simple: buy term, buy enough (a common guidepost is 10 to 12 times your annual income — on a $50,000 income that is $500,000 to $600,000 of coverage), and invest the difference yourself. A $50,000 income times 10 is <strong>$500,000</strong>; times 12 is <strong>$600,000</strong>. Your family's needs — debts, a mortgage, children's ages — fine-tune the number.</p>"
