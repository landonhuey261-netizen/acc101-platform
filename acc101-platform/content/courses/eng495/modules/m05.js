      "html": "<p>A fallacy is a shortcut that looks like reasoning but is not. The <strong>straw man</strong> attacks a weak version of the opposing view instead of the real one — \"critics of Sunday hours want to close all libraries\" — when no critic said that. The <strong>false dilemma</strong> pretends there are only two choices — \"either we fund Sunday hours or we fund nothing\" — when a third option exists. <strong>Ad hominem</strong> attacks the person instead of the argument — \"the librarian is biased, so the data is wrong\" — when the data must be judged on its own. <strong>Hasty generalization</strong> draws a broad conclusion from too little evidence — \"one student failed, so the program fails everyone.\"</p><p>Fallacies matter for the capstone because they are the errors a skeptical reader will find in your paper, and because the comprehensive exams will ask you to name them. The defense is simple: state the opposing view fairly, consider more than two options, judge evidence on its own merits, and claim only what your evidence supports. An argument that survives those four tests is an argument worth submitting.</p>"
