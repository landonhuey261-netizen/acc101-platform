      "html": "<p>Every argument has three corners: the <strong>speaker</strong> (who is making the claim, and what qualifies them), the <strong>audience</strong> (who must be persuaded, and what they already believe), and the <strong>message</strong> (what is being claimed, and with what evidence). Change any corner and the argument changes: the same claim, made by a different speaker to a different audience, is a different argument. Your research paper's speaker is you — a student who has done the research — and your audience is a reader who knows the topic and expects evidence, not slogans. Write for that audience, and the paper writes itself more honestly.</p><p>The three appeals are the tools. <strong>Ethos</strong> is credibility: the reader trusts you because you cite good sources, admit what you do not know, and treat opposing views fairly. <strong>Pathos</strong> is emotion: the reader feels the stakes — a working student with nowhere to study on Sunday — and the feeling makes the argument matter. <strong>Logos</strong> is reasoning: the evidence and the logic that connect the evidence to the claim. A strong argument uses all three, but logos carries the weight: emotion without evidence is manipulation, and credibility without evidence is a reputation with nothing behind it.</p>"
