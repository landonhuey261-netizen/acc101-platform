      "html": "<p>The Fed's main tool is <strong>open-market operations</strong>: buying and selling U.S. Treasury bonds. When the Fed <em>buys</em> bonds from banks, it pays with new reserves, banks have more to lend, the money supply grows, and interest rates fall. When the Fed <em>sells</em> bonds, it takes reserves away, the money supply shrinks, and interest rates rise. This is the tool the Fed uses most, because it is precise and reversible.</p><p>The second tool is the <strong>discount rate</strong>: the interest rate the Fed charges banks that borrow directly from it. Lowering it makes borrowing from the Fed cheaper and encourages lending; raising it does the opposite. The third is the <strong>reserve requirement</strong>: raising it forces banks to hold more reserves and lend less, shrinking the money supply; lowering it frees reserves for lending. In practice the Fed rarely changes reserve requirements — it is a blunt instrument — and since 2008 it has also paid <strong>interest on reserves</strong>, which gives it another lever over banks' willingness to lend.</p><p>Worked example: the Fed buys $100 million of bonds and the reserve requirement is 10%. The purchase adds $100 million of reserves, and the money multiplier is 10, so the money supply can rise by up to $100 million × 10 = <strong>$1,000 million</strong>. If instead the Fed sells $50 million of bonds, the money supply can fall by up to $50 million × 10 = <strong>$500 million</strong>. The multiplier works in both directions.</p><div class=\"formula\">Maximum change in money supply = Open-market purchase (or sale) × Money multiplier</div>"
