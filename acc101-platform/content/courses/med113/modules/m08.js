      "html": "<p>Even mild dehydration hurts performance: it raises heart rate, raises body temperature, and makes the same effort feel harder. Athletes should start exercise well hydrated — drinking fluids through the day, not just gulping water at the start line — and drink during exercise, especially in heat. A simple check is urine color: pale yellow usually means good hydration, while dark yellow suggests more fluid is needed.</p>\n<p>Sweat is not just water. It contains electrolytes, mainly sodium, and in long, sweaty sessions those need replacing too. That is why sports drinks contain sodium as well as carbohydrate: the sodium helps the body hold on to fluid and replaces what sweat took away. For sessions under an hour, plain water is usually fine; for longer or very sweaty sessions, a drink with electrolytes makes sense.</p>\n<p>Two mistakes are common. The first is drinking too little and ignoring thirst, heat, and cramping. The second is drinking far too much water in a short time, which can dilute blood sodium — a rare but serious condition. The sensible middle ground is to drink to thirst and to the plan the athlete has practiced in training, and to include electrolytes in long sessions.</p>"
