      "heading": "What the Tests Measure — and What They Cannot Tell You",
      "html": "<p>Once a person is screened and cleared, testing begins. Each test measures one thing, and each has limits. The main families:</p>\n<ul>\n<li><strong>Body composition</strong> — how much of the body is fat and how much is everything else (muscle, bone, water). Common methods include skinfold measurements, bioelectrical impedance (a small, painless electrical current), and waist circumference. No field method is exact: skinfolds depend on the tester's skill, impedance is thrown off by hydration and recent food, and waist circumference tells you about fat distribution, not total fat. All of them are estimates, and the same method repeated the same way is more useful for tracking change than for giving one \"true\" number.</li>\n<li><strong>Muscular strength and endurance</strong> — strength tests (such as a grip test or a one-repetition maximum on a machine) measure the most force a muscle can produce; endurance tests (such as a timed push-up or sit-up test) measure how long a muscle can keep working. A one-repetition maximum needs careful technique and supervision, and it is not suitable for beginners or for people with joint problems.</li>\n<li><strong>Aerobic fitness</strong> — tests such as a step test, a walk test, or a graded treadmill or bike test estimate how well the heart and lungs deliver oxygen. The most accurate measure is a laboratory VO2max test (Module 4), but field tests are cheaper and safer for most people — they estimate rather than measure directly, so their numbers are approximate.</li>\n<li><strong>Movement screens</strong> — structured observations of how a person squats, lunges, reaches, or balances. They show the coach what to watch — a knee collapsing inward, a trunk that cannot stay upright — and they guide exercise choices. They are observations, not diagnoses: a movement screen cannot tell you that a joint is damaged or that a muscle is weak in a medical sense.</li>\n<li><strong>Flexibility</strong> — tests such as the sit-and-reach measure the range of a particular movement. They describe one joint or pattern, not whole-body flexibility.</li>\n</ul>\n<p>Every test needs three things to be useful: the same conditions each time, the same instructions, and a clear reason for testing. Testing without a reason wastes time; testing without standard conditions gives numbers that cannot be compared.</p>"
