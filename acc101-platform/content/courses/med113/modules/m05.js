      "heading": "The PAR-Q+ and Risk Stratification",
      "html": "<p>The most widely used screening tool is the <strong>PAR-Q+</strong> — the Physical Activity Readiness Questionnaire for Everyone. It is a short set of yes-or-no questions about symptoms and health conditions: chest pain, dizziness, joint problems, blood pressure, and similar. It is designed for the general public and is used all over the world in gyms and fitness settings.</p>\n<p>How it works is simple: if a person answers \"no\" to every question, they are generally ready to start becoming more active, beginning at a light-to-moderate level and building up gradually. If they answer \"yes\" to any question, they should talk to a clinician before starting or increasing exercise — or follow the questionnaire's own follow-up questions, which ask for more detail. A \"yes\" is not a ban on exercise. It is a signal to get a clinician's view first, so the exercise that follows is safe and appropriate.</p>\n<p>Coaches also use <strong>risk stratification</strong>: sorting people into broad groups — lower risk, moderate risk, higher risk — based on their health history, symptoms, and risk factors. The point is practical, not medical: a lower-risk person can usually start light activity and build up; a higher-risk person needs medical clearance and supervision before testing or vigorous exercise. The exact boundaries are set by professional guidelines (the ACSM guidelines are the standard reference), and a coach follows them rather than inventing their own. When in doubt, the rule is simple: refer.</p>"
