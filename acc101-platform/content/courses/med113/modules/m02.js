      "heading": "Torque and the Force–Velocity Relationship",
      "html": "<p><strong>Torque</strong> is turning force — the twist a muscle applies around a joint. It depends on two things: how hard the muscle pulls, and how far from the joint it pulls. Torque equals force times the <strong>moment arm</strong> (the perpendicular distance from the joint to the line of the muscle's pull). A longer moment arm means the same muscle force makes more torque.</p>\n<p>You can feel this with a biceps curl. Hold a dumbbell with your elbow bent at a right angle: the weight hangs straight down, far from the elbow, and the curl feels hardest. That is the point of maximum torque — the weight's line of pull is at its farthest from the joint. Straighten the arm fully or curl it all the way up and the same weight feels lighter, because the moment arm has shrunk. This is why a movement feels hard at one point and easier at another, even though the weight never changes.</p>\n<p>The <strong>force–velocity relationship</strong> is the second big rule. A muscle can produce its greatest force when it shortens slowly — or not at all, as in holding a heavy weight still. As the speed of shortening rises, the force it can produce falls. A powerlifter grinding out a heavy squat moves slowly and produces huge force; a sprinter's legs move fast but each step produces far less force. The two ends of the curve are the point of training: heavy, slow work builds maximal force; light, fast work builds speed and power. You cannot maximise both at the same time, which is why programs train different qualities on different days — the idea Module 6 builds into periodisation.</p>\n<p>Two more terms complete the picture. <strong>Concentric</strong> action is the muscle shortening while it produces force (lifting the dumbbell up). <strong>Eccentric</strong> action is the muscle lengthening while it produces force (lowering the dumbbell under control). <strong>Isometric</strong> action is force without any change in length (holding a plank). Eccentric actions can produce the most force of all, and they are also the ones most linked to muscle soreness after a new workout — useful knowledge when a client asks why they ache two days after their first session.</p>"
