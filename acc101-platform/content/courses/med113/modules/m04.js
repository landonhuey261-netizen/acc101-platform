      "html": "<p><strong>VO2</strong> is the volume of oxygen your body uses per minute. At rest it is small; during exercise it rises steeply as muscles demand more oxygen to make ATP through the oxidative system (Module 3). <strong>VO2max</strong> is the highest VO2 you can reach — the maximum rate at which your body can take in, deliver, and use oxygen during hard exercise. It is widely used as the single best measure of cardiorespiratory fitness.</p>\n<p>VO2max depends on a chain of steps, and the chain is only as strong as its weakest link: the lungs must move air in, oxygen must cross into the blood, the heart must pump that blood to the muscles, the blood vessels must deliver it, and the muscles must extract and use it. The heart's pumping capacity is usually the main limit in healthy people — which is why training that strengthens the heart raises VO2max.</p>\n<p>The <strong>Fick equation</strong> puts the chain into one line: VO2 equals <strong>cardiac output</strong> (how much blood the heart pumps per minute) multiplied by the <strong>arteriovenous oxygen difference</strong> (how much oxygen the muscles take out of each litre of blood). Two levers, then: pump more blood, or take more oxygen out of the blood. Training improves both.</p>\n<div class=\"callout\"><strong>Key idea:</strong> VO2max is the ceiling on how fast your body can use oxygen. It depends on the lungs, the heart, the blood, and the muscles — and the heart's pumping power is usually the main limit.</div>"
