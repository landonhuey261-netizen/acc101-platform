      "html": "<p><strong>Cardiac output</strong> is the volume of blood the heart pumps per minute. It is the product of two numbers: <strong>heart rate</strong> (beats per minute) and <strong>stroke volume</strong> (the volume of blood pumped with each beat). Cardiac output = heart rate × stroke volume.</p>\n<p>At rest, a typical adult heart beats around 60–80 times a minute and pumps a modest volume with each beat. During hard exercise, heart rate climbs and stroke volume rises too, so cardiac output can increase several-fold. Stroke volume rises because the heart fills more fully between beats (more blood returns from the working muscles) and because it contracts more forcefully, squeezing out a larger share of what it holds.</p>\n<p>Here is the key training effect: a trained heart pumps more blood per beat. At rest, that means it can beat more slowly and still deliver the same cardiac output — which is why trained people often have a low resting heart rate. During exercise, a bigger stroke volume means the heart does not have to beat as fast to deliver the same blood flow, so the same pace feels easier. Stroke volume is one of the biggest reasons endurance training raises VO2max.</p>"
