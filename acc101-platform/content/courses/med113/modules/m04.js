      "html": "<p>Coaches often divide exercise intensity into <strong>heart-rate zones</strong>, from easy to very hard. In plain words: an easy zone is a pace where you can talk in full sentences; a moderate zone is a pace where you can talk in short sentences; a hard zone is a pace where you can only get out a few words; and a very hard zone is a pace where talking is nearly impossible. The talk test is a practical, free way to judge intensity — and it works because breathing and talking compete for the same air.</p>\n<p>Zones are often written as percentages of maximum heart rate, which brings us to a famous formula: <strong>220 minus age</strong>. A 40-year-old would get an estimated maximum of 180 beats per minute. Here is the part that matters: <strong>220 minus age is an estimate, not an exact number.</strong> It is a rough average across a population, and any one person's true maximum can sit well above or below it. Two people the same age can have maximum heart rates that differ by a large amount. So a zone calculated from 220 minus age is a starting guess, not a measurement — and a coach should never treat it as a diagnosis or a hard limit. If a precise maximum matters, it is measured directly with a graded exercise test run by a qualified professional (Module 5), not calculated from a formula.</p>\n<p>Heart rate also has limits as a training guide. It drifts upward during long exercise in the heat even at the same pace, it is affected by sleep, caffeine, illness, and stress, and some medicines change it. A good coach watches the person — their breathing, their talk, their effort — not just the number on a watch.</p>\n<div class=\"callout\"><strong>Key idea:</strong> 220 minus age estimates maximum heart rate — it does not measure it. Real maximum heart rates vary widely between people of the same age, so treat formula-based zones as a rough guide, not a fact.</div>"
