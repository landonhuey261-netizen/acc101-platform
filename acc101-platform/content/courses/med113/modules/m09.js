      "html": "<p>The <strong>NASM Corrective Exercise Continuum</strong> is a four-phase system for addressing movement compensations and muscle imbalances, and the order matters — each phase prepares the body for the next. The phases are: <strong>inhibit, lengthen, activate, integrate</strong>.</p>\n<p><strong>Inhibit</strong> means calming overactive tissue, usually with self-myofascial release — rolling slowly over a tender spot with a foam roller or ball and holding pressure there for roughly 30 seconds while breathing and relaxing. <strong>Lengthen</strong> means restoring length to that same overactive tissue, usually with static stretching held for about 30 seconds. Inhibit and lengthen work as a pair: rolling calms the tissue, and stretching then addresses its length.</p>\n<p><strong>Activate</strong> means waking up and strengthening the underactive muscles — the ones that have gone quiet and weak — with isolated strengthening exercises, such as glute bridges for sleepy glutes or band pull-aparts for a weak upper back. <strong>Integrate</strong> means putting the corrected pattern back into real movement: squats, hinges, pushes, pulls, and carries that teach the nervous system to use the improved mechanics in the real world.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Inhibit, lengthen, activate, integrate — in that order. Calm the overactive tissue first, then stretch it, then wake up the weak side, then practice the whole movement. Reversing the order does not work as well.</div>\n<p>One line must stay clear through all of this: corrective exercise does <strong>not</strong> diagnose or treat injuries. It addresses movement compensations and muscle imbalances in healthy people. Diagnosing and treating injuries belongs to a clinician — a physician, physical therapist, or athletic trainer.</p>"
