      "heading": "Periodisation: Planning in Cycles",
      "html": "<p><strong>Periodisation</strong> is the practice of organising training into planned cycles so that the body peaks at the right time and does not burn out. It works in three sizes:</p>\n<ul>\n<li><strong>Macrocycle</strong> — the big picture, usually several months to a year. It holds the main goal: for example, \"get fit enough to enjoy a hiking holiday in six months.\"</li>\n<li><strong>Mesocycle</strong> — a block of several weeks inside the macrocycle, each with one focus: a block for building base endurance, then a block for strength, then a block for power, for example.</li>\n<li><strong>Microcycle</strong> — a single week: which days are hard, which are easy, and which are rest. Most people live their training one microcycle at a time.</li>\n</ul>\n<p>Inside the cycles, the load rises and falls in waves rather than climbing in a straight line. A common pattern is three weeks of building load followed by one easier week (a <strong>deload</strong>), which lets the body catch up and adapt. For a general adult who is not competing, periodisation can be simple: a few weeks focused on one quality, then a change of focus, with easy weeks built in. The point is not complexity — it is that the plan is written down in advance, so training is a decision, not an accident.</p>"
