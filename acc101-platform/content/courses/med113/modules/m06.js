      "heading": "The Principles That Make Training Work",
      "html": "<p>Four principles explain why training works — and why it stops working when they are ignored:</p>\n<ul>\n<li><strong>Overload</strong> — to improve, the body must be asked to do a little more than it is used to. A muscle that is never challenged does not grow stronger; a heart that is never asked to work harder does not adapt. The key word is <em>little</em>: the overload must be just enough to trigger adaptation, not so much that it causes injury.</li>\n<li><strong>Specificity</strong> — the body adapts to exactly what it is asked to do. Running improves running, not swimming; heavy squats improve leg strength, not flexibility. If the goal is a faster 5K, the program must include running. This is also called the SAID principle (Specific Adaptation to Imposed Demands).</li>\n<li><strong>Progression</strong> — the overload must grow gradually as the body adapts. What was challenging last month becomes easy; the program must move on. Good progression is small and steady — a little more weight, a few more minutes, one more day — not a sudden jump.</li>\n<li><strong>Reversibility</strong> — use it or lose it. Stop training and the gains fade: fitness drops within weeks, strength more slowly. This is not a punishment; it is how the body works — it keeps only what it is regularly asked to use. It is also the reason a program needs to be something a person can keep doing, not a heroic burst.</li>\n</ul>\n<p>Two more ideas sit beside these. <strong>Individualisation</strong> means the program fits the person — their goals, history, likes, and limits — not a template copied from someone else. And <strong>recovery</strong> means the program includes rest: adaptation happens during recovery (Module 4), so a program without rest days is a program that cannot work.</p>"
