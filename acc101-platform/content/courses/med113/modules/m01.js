      "html": "<p>Sports science leads to many different jobs. Here are the main ones, in plain words:</p>\n<ul>\n<li><strong>Strength and conditioning coach</strong> — designs training programs that build strength, power, speed, and endurance for athletes or teams.</li>\n<li><strong>Exercise physiologist</strong> — uses exercise testing and training to improve fitness and support health, often working with people who have long-term health conditions, alongside clinicians.</li>\n<li><strong>Personal trainer / fitness coach</strong> — works one-to-one with general clients on fitness goals such as strength, weight management, and everyday energy.</li>\n<li><strong>Sport scientist</strong> — tests athletes, tracks their training load, and gives coaches data to guide decisions.</li>\n<li><strong>Athletic trainer</strong> — prevents, recognises, and manages sport injuries on the field and in the clinic, working with clinicians.</li>\n<li><strong>Physical therapist / physiotherapist</strong> — helps people recover movement after injury or illness. This needs a clinical degree and licence — it is a separate profession, not something this course qualifies you for.</li>\n<li><strong>Sport psychologist</strong> — helps athletes with confidence, focus, and handling pressure.</li>\n<li><strong>Researcher or lecturer</strong> — studies how the body responds to exercise and teaches the next generation.</li>\n</ul>\n<p>Many of these jobs need further study, a degree, or a professional credential beyond this course. This course gives you the knowledge base — the science — so that if you go further, you are starting from a solid place.</p>\n<div class=\"callout\"><strong>Key idea:</strong> A strength coach, an exercise physiologist, and a physical therapist all study movement, but they do different jobs with different training. Knowing which job is which is part of knowing the field.</div>"
