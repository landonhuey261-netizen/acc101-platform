      "html": "<p><strong>Sports science</strong> is the study of how the human body moves, performs, and adapts to exercise and sport. <strong>Kinesiology</strong> is the wider science behind it: the study of human movement itself, from a walk to the shops to an Olympic sprint. The word comes from Greek — <em>kinesis</em> means movement, and <em>logia</em> means study. So kinesiology is literally \"the study of movement.\"</p>\n<p>Movement is not one subject. It is many subjects working together. To understand why a runner gets faster, you need anatomy (which muscles do the work), physiology (how the heart and lungs deliver oxygen), biomechanics (how forces move the body), psychology (how the mind handles pressure), and nutrition (how food fuels the work). Sports science pulls all of these together and asks one practical question: how can a person move better, perform better, and stay healthier?</p>\n<p>This course is the sports-science course in your Medical program. The anatomy and physiology you learned in med102 and med103 are the foundation — this course builds on them by asking what happens when the body is put to work, and how a coach or exercise professional uses that knowledge to help real people.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Kinesiology is the study of human movement. Sports science applies that study to exercise and sport — to help people perform better, stay healthy, and recover well.</div>"
