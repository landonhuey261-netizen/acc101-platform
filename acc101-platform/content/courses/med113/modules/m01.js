      "heading": "Scope of Practice: Knowing Where Your Job Ends",
      "html": "<p><strong>Scope of practice</strong> is the line around what a professional is trained and allowed to do. Inside the line: their job. Outside the line: someone else's job, and stepping over it can harm people. A fitness coach, for example, is inside their scope when they design a workout for a healthy adult, teach good lifting form, and motivate a client. They step outside their scope when they diagnose an injury, prescribe a diet for a medical condition, or tell a client to stop taking a medicine.</p>\n<p>Here are the edges that matter most for a coach or exercise professional:</p>\n<ul>\n<li><strong>Diagnosing is for clinicians.</strong> If a client has pain, a new symptom, or a health problem, the coach refers them to a doctor or other clinician — they do not guess the diagnosis themselves.</li>\n<li><strong>Medical advice is for clinicians.</strong> A coach can share general health information, but personal medical decisions belong to the client's clinician.</li>\n<li><strong>Rehabilitation is for licensed professionals.</strong> Helping someone recover from an injury is the job of a physical therapist or clinician, not a fitness coach — though a coach may work with a client after the clinician has cleared them.</li>\n<li><strong>Staying current is part of the job.</strong> Scope grows with training and credentials; a coach who earns a recognised certification can do more than one who has not — but never more than their training supports.</li>\n</ul>\n<p>Scope of practice is not about being unhelpful. It is about being safe and honest. Referring a client to the right professional is good practice, not a failure — it is how a trustworthy coach protects the people they work with.</p>"
