      "heading": "Arousal, Anxiety, and Performance",
      "html": "<p><strong>Arousal</strong> is the body's level of activation — heart rate, alertness, muscle tension. A little arousal helps: it sharpens focus and readies the body. Too much arousal hurts: hands shake, thoughts race, and simple skills fall apart. The <strong>inverted-U hypothesis</strong> pictures this as a curve: performance rises as arousal rises, peaks at a middle level, then falls as arousal keeps climbing. The best level is not the same for everyone or every task — a weightlifter may need more arousal than a golfer putting for a win.</p>\n<p><strong>Performance anxiety</strong> is the worry and tension an athlete feels before or during competition — the fear of failing, of letting the team down, of being judged. Coaches can help with simple tools: slow breathing to lower arousal, a consistent pre-performance routine so the athlete focuses on familiar steps instead of the crowd, and reframing nerves as excitement — \"my body is getting ready\" instead of \"I am falling apart.\"</p>\n<p>Anxiety that is severe, constant, or affecting life outside sport is not a coaching problem. That is a referral: the athlete should be encouraged to talk to a qualified mental health professional or counselor. Coaches support athletes; they do not provide therapy.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Arousal is a dial, not a switch. Some helps, too much hurts, and the right level depends on the athlete and the task. Breathing, routines, and reframing are coaching tools; severe or constant anxiety is a referral.</div>"
