      "heading": "Motivation: Why Athletes Keep Going",
      "html": "<p><strong>Motivation</strong> is the drive to start and keep doing something. Psychologists usually describe two kinds. <strong>Intrinsic motivation</strong> comes from inside — playing because the sport is fun, because mastering a skill feels good, or because the athlete loves the challenge. <strong>Extrinsic motivation</strong> comes from outside — trophies, money, praise, or avoiding punishment. Both can work, but intrinsic motivation tends to last longer: athletes who play for the love of it keep going when the trophies stop coming.</p>\n<p>Two ideas help coaches work with motivation. <strong>Self-determination theory</strong> says people are most motivated when three needs are met: autonomy (having some choice), competence (feeling able to improve), and relatedness (feeling connected to the team). A coach who gives athletes choices, sets tasks they can succeed at, and builds a team that belongs together is feeding all three. <strong>Achievement goal theory</strong> adds that some athletes judge success by beating others, while others judge it by beating their own previous best — and the second group, the mastery-focused athletes, usually handle setbacks better.</p>\n<p>Rewards are not the enemy, but they need care. A reward for effort and improvement supports motivation; a reward that makes the athlete feel controlled or that replaces the fun can quietly kill it. The practical rule is simple: reward the process — effort, improvement, teamwork — more than the outcome.</p>"
