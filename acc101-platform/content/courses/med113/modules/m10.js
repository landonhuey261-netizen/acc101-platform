      "heading": "Motor Learning: How Skills Are Built",
      "html": "<p><strong>Motor learning</strong> is the process of learning a movement so that it becomes reliable and automatic. It happens in stages. In the <strong>cognitive stage</strong>, the learner is thinking hard about every part — the movement is slow, clumsy, and full of errors, and the coach gives frequent, simple instructions. In the <strong>associative stage</strong>, the movement gets smoother, errors get smaller, and the learner starts to feel what is right and correct themselves. In the <strong>autonomous stage</strong>, the skill runs almost automatically — the athlete can do it while thinking about tactics instead of technique.</p>\n<p><strong>Feedback</strong> is information about performance, and the kind that helps changes as the learner advances. Early on, feedback should be frequent, simple, and focused on one thing at a time. Later, it should be less frequent, so the learner practices self-correction — too much feedback creates dependence, and the athlete falls apart without the coach. Good feedback describes what happened and what to change (\"your elbow dropped on that last throw — keep it high\"), not just whether it was good or bad.</p>\n<p>Good <strong>coaching cues</strong> are short, specific, and external: \"push the ground away\" works better than \"extend your knees,\" because it gives the athlete a picture to aim at. One cue at a time, in plain words, at the moment the athlete can use it — that is the craft of coaching.</p>"
