      "heading": "Imagery, Self-Talk, and Goal-Setting",
      "html": "<p><strong>Imagery</strong> — also called visualization — is mentally rehearsing a skill: seeing the perfect free throw, feeling the rhythm of the run-up, hearing the crowd. Good imagery uses more than sight: the best mental rehearsals include the feel of the movement, the sounds around it, and even the emotions. Imagery works best when the athlete already knows the skill physically, and when the mental picture is vivid, positive, and in real time rather than slow motion.</p>\n<p><strong>Self-talk</strong> is the inner voice athletes use during performance. Positive, instructional self-talk — \"knees bent, eyes on the ball\" — helps focus and confidence. Negative self-talk — \"I always mess this up\" — does the opposite. Coaches can teach athletes to notice their self-talk, catch the negative phrases, and replace them with short, specific cues they have practiced.</p>\n<p><strong>Goal-setting</strong> turns motivation into a plan. Good goals are SMART: Specific, Measurable, Achievable, Relevant, and Time-bound. \"Get better at free throws\" is a wish; \"make 70 out of 100 free throws in practice by the end of the month\" is a goal. The best programs mix outcome goals (win the match), performance goals (run a personal best), and process goals (keep my elbow in on every shot) — and process goals are the ones the athlete controls completely.</p>"
