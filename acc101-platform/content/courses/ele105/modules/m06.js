      "html": "<p>The kitchen is the most circuit-dense room in a house, and the Code treats it that way. Two 20-ampere small-appliance branch circuits are required (210.11(C)(1)), and they feed the countertop receptacles where the small appliances live. Countertop receptacles follow 210.52(C): no point along the countertop wall may be more than 24 inches from a receptacle, which puts them no more than 48 inches apart. A receptacle is also required for each wall countertop space 12 inches or wider.</p><p>Island and peninsular countertops have their own rule in the 2023 NEC: at least one receptacle is required when the long dimension is 12 inches or more and the short dimension is 12 inches or more (210.52(C)(2) and (C)(3)). The receptacle may be mounted on the side of the island or in the countertop itself with a listed assembly. The rule exists because islands are where people actually use small appliances — and where an extension cord across a walkway is most likely.</p><p>The range, cooktop, or oven gets its own circuit: a 240-volt circuit sized by Table 220.55 for the range demand, usually 40 or 50 amperes on 8 or 6 AWG copper. The dishwasher and the garbage disposal are each typically on their own 15- or 20-ampere circuit, and the refrigerator may be on its own circuit or on a small-appliance circuit — but if it is on a small-appliance circuit, a tripped GFCI can cost a refrigerator full of food, which is why a dedicated refrigerator circuit is better practice.</p><div class=\"callout\"><strong>Key idea:</strong> Two 20 A small-appliance circuits, countertop receptacles every 48 inches at most, and a receptacle on islands and peninsulas 12 inches or longer.</div>"
