      "html": "<p>Cable runs through framing by bored holes, and Section 300.4 sets the protection rules. A bored hole must be at least 1-1/4 inches from the nearest edge of the wood member; if it is closer, a steel plate at least 1/16 inch thick must protect the cable. The plate covers the cable's path so a drywall screw or a nail cannot reach it. Notches in studs must be protected the same way, and a notch may not be deeper than the building code allows.</p><p>Holes through joists follow the building code as well as the NEC: holes go in the middle third of the joist depth, not near the top or bottom where the joist carries its load, and not too close to a support. A hole drilled through the bottom edge of a joist weakens the joist and is a structural violation, not just an electrical one.</p><p>Where cable runs across the face of framing instead of through holes, it must be protected by a running board or by furring strips, or run through a raceway. Cable stapled to the face of a stud at drywall height will be hit by a drywall screw — the plate and the hole are what keep the cable safe.</p><ul><li>Bored holes: 1-1/4 in. from the edge, or a steel plate (300.4).</li><li>Joist holes: middle third of the depth, not near the top, bottom, or supports.</li><li>Cable on the face of framing needs a running board, furring, or a raceway.</li></ul>"
