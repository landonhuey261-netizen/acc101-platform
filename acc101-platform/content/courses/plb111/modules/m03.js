      "html": "<p>When you \"glue\" PVC or CPVC, you are not sticking two pieces together with an adhesive layer. The primer and cement are solvents: they soften the plastic surfaces, and when you push the pipe into the fitting, the two softened surfaces fuse into one continuous piece of plastic. That is why the joint is called a <strong>solvent weld</strong>, and why a good one is as strong as the pipe itself.</p>\n<p>That also explains why the steps cannot be skipped. A dirty or unsoftened surface will not fuse. The wrong cement will not soften the plastic it is meant for. And once the cement is applied, you have seconds — not minutes — to assemble the joint before the surfaces stop being soft enough to fuse.</p>\n<div class=\"callout\"><strong>Key idea:</strong> A solvent weld fuses pipe and fitting into one piece. There is no glue layer doing the work — the softened plastic itself is the bond.</div>"
