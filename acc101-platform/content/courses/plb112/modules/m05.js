      "html": "<p><strong>CSST</strong> — corrugated stainless steel tubing — is a flexible, semi-rigid stainless steel tube with a yellow (or sometimes black) plastic jacket, made for gas piping inside buildings. It bends like a thick electrical cable, so it snakes through walls and joists with almost no joints: a run that would need a dozen threaded black-steel joints needs only two CSST fittings, one at each end. Fewer joints mean fewer places to leak, and installation can be much faster than threading steel pipe.</p>\n<p>CSST is a gas material, not a water material. It carries natural gas or propane to furnaces, water heaters, stoves, and dryers. It is listed to a standard (such as CSA LC-1 / ANSI LC-1) and must be installed exactly to the manufacturer's instructions — CSST is not a generic product, and each brand has its own fittings, tools, and rules.</p>\n<div class=\"callout\"><strong>Key idea:</strong> CSST is flexible gas tubing: few joints, fast install, gas only. It is installed to the manufacturer's instructions, brand by brand — there is no generic CSST method.</div>"
