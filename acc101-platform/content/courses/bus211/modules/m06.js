      "html": "\n<p>Inside the company, pay must feel fair: jobs that carry more responsibility should pay more. <strong>Job evaluation</strong> ranks jobs by factors such as skill, effort, responsibility, and working conditions — the point-factor method scores each factor and adds the points. Outside the company, pay must compete: <strong>market pricing</strong> compares each job's pay with survey data for the same job in the same labor market, and sets the <strong>midpoint</strong> of the pay range near the market rate.</p>\n<p>The two meet in the <strong>pay structure</strong>: jobs are grouped into <strong>pay grades</strong>, each with a range (minimum, midpoint, maximum). A typical range spread is 40–50%. In this course a 40% spread is built as ±20% around the midpoint: for a $50,000 midpoint, the minimum is $40,000 and the maximum is $60,000 (see the worked example). Employees move through the range with experience and performance; new hires start near the minimum, experts sit near the maximum.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Internal fairness (job evaluation) and external competitiveness (market pricing) must agree. A job that is top-ranked inside but bottom-paid outside will lose its people.</div>\n<p><strong>Worked example.</strong> A pay grade has midpoint $50,000 and a 40% range spread, built as ±20% around the midpoint. Minimum = $50,000 × 0.80 = <strong>$40,000</strong>. Maximum = $50,000 × 1.20 = <strong>$60,000</strong>. An employee paid $45,000 has a <strong>compa-ratio</strong> = $45,000 ÷ $50,000 = <strong>0.90</strong> (90% — paid below midpoint, as expected for someone still developing). An employee paid $55,000 has a compa-ratio of 1.10 (110% — above midpoint, for an expert).</p>"
