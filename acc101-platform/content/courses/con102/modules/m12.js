      "html": "<p>The three main sling types are <strong>wire rope</strong>, <strong>synthetic web</strong>, and <strong>chain</strong>. Wire rope slings are strong and flexible, made of steel wires twisted into strands; they are damaged by kinks, crushed wires, broken strands, and corrosion. Synthetic web slings are light, flexible, and will not scratch a finished load, but they are cut easily by sharp edges and damaged by heat and chemicals \u2014 edge protectors are used wherever a web sling touches a sharp corner. Chain slings are the strongest and most durable, used for hot or rough loads, but a chain with a stretched, cracked, or bent link is retired \u2014 chain does not stretch before it fails, it just fails.</p>\n<p>Every sling is inspected before every lift: the tag is legible and present, the body has no cuts, kinks, broken wires, or stretched links, the fittings are not cracked or bent, and the sling has not been exposed to heat or chemicals beyond its rating. A sling that fails any check is taken out of service and tagged \u2014 never used \"for a light load\" or \"just this once.\" A sling's rating is a maximum, not a suggestion, and the rating on the tag is for a straight vertical pull \u2014 other hitches and angles reduce it.</p>\n<p><strong>Shackles and hooks</strong> are inspected the same way: the pin is present and tight, the body is not cracked or bent, and the hook's safety latch closes. A hook without a working latch can let a sling slip off, and a shackle with a bent pin can fail under load. Hardware is never overloaded, never side-loaded beyond its rating, and never improvised \u2014 a bolt is not a shackle pin, and a piece of wire is not a sling.</p>"
