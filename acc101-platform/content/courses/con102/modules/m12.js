      "heading": "Hitches: Vertical, Choker & Basket",
      "html": "<p>A <strong>hitch</strong> is how a sling is attached to the load. In a <strong>vertical hitch</strong>, a single sling runs straight from the hook to the load \u2014 simple, but it gives no grip on the load and the load can slide. In a <strong>choker hitch</strong>, the sling wraps around the load and passes through its own eye, tightening as the load lifts \u2014 it grips the load, but the sling's capacity drops to about 75% of its vertical rating because the sling bends around itself. In a <strong>basket hitch</strong>, the sling passes under the load and both ends go to the hook, sharing the load between two legs \u2014 it doubles the capacity when the legs are vertical, but the capacity falls as the legs spread apart.</p>\n<p>The choice of hitch depends on the load: a choker grips a bundle of pipe or a log, a basket cradles a pallet or a beam, and a vertical hitch lifts from a lifting eye. Whatever the hitch, the load must be balanced: the hook must be directly above the load's <strong>center of gravity</strong>, or the load will tilt and swing when it lifts. A load that tilts can slip its slings, hit the structure, or swing into a worker. The rigger checks the balance with a trial lift of a few inches before the load is raised fully.</p>\n<p>Tag lines \u2014 ropes attached to the load \u2014 let workers control the load's rotation and swing from a safe distance. Hands are never placed on a suspended load, and nobody stands under it. The load is guided, never wrestled.</p>"
