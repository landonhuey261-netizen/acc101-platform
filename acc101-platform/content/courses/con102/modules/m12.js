      "heading": "Sling Angle, Hand Signals & the Lift",
      "html": "<p><strong>Sling angle</strong> is the angle between the sling leg and the horizontal, and it changes the load on each leg dramatically. When two sling legs are vertical (90 degrees to the horizontal), each leg carries half the load. At 60 degrees, each leg carries about 58% of the load. At 45 degrees, each carries about 71%. At 30 degrees, each carries the full load \u2014 100% \u2014 because the legs are pulling sideways as much as they are lifting. The rule is simple: the shallower the angle, the higher the tension. A two-leg sling at 30 degrees carries twice the tension of the same sling at 90 degrees, and a sling rated for the load at 90 degrees can fail at 30 degrees.</p>\n<p>Worked example: a 1,000-pound load on two sling legs at 60 degrees puts about 577 pounds on each leg (1,000 \u00f7 2 \u00f7 sin 60\u00b0 = 500 \u00f7 0.866 = 577). At 30 degrees, each leg carries 1,000 pounds (500 \u00f7 0.5 = 1,000). That is why riggers keep sling angles at 60 degrees or steeper whenever possible, and why a wide, flat lift needs a spreader bar to keep the angles steep.</p>\n<p><strong>Hand signals</strong> are the standard language between the signal person and the operator: one finger up for hoist, one finger down for lower, a flat palm for stop, a circular motion for swing, and both arms crossed overhead for emergency stop. Only one person signals, the operator follows only that person, and if communication is unclear the operator stops. Voice signals by radio follow the same rules: one direction at a time, confirmed by the operator. When in doubt \u2014 stop. A stopped lift can be restarted; a dropped load cannot be undone.</p>"
