      "html": "<p>Wood moves with moisture. <strong>Green lumber</strong> is freshly sawn with a moisture content of 19% or more; it is heavy, it shrinks as it dries, and it can warp, twist, and crack in the wall. <strong>Kiln-dried (KD)</strong> lumber has been dried in a kiln to 19% moisture or less; it is more stable, lighter, and less likely to move after installation. For interior framing and finish work, kiln-dried is the standard. <strong>Pressure-treated lumber</strong> is lumber forced full of preservative chemicals under pressure, for use where wood touches soil, concrete, or weather \u2014 sill plates, deck posts, and exterior framing. It is heavier, it is corrosive to ordinary fasteners (hot-dipped galvanized or stainless fasteners are required), and its cut ends must be treated with preservative.</p>\n<p>Storing lumber matters as much as buying it. Keep it flat, level, and stickered \u2014 stacked with thin strips between layers so air can circulate \u2014 and covered on top but open on the sides so moisture can escape. Lumber stored on uneven ground dries crooked, and a crooked stud is a wavy wall. Check each board before you use it: sight down its edge for bow, crook, twist, and cup, and set aside the worst boards for blocking and short pieces.</p>\n<p>The four warps have names worth learning: <strong>bow</strong> (a curve along the face), <strong>crook</strong> (a curve along the edge), <strong>twist</strong> (one end rotated relative to the other), and <strong>cup</strong> (a curve across the width). A board with a slight crown (bow) can be installed crown-up in a joist or crown-out in a stud; a board with a twist goes to the cut pile.</p>"
