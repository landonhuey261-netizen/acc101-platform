      "html": "<p>The hook at the end of the blade is loose on purpose, and beginners often think it is broken. It moves by exactly the thickness of the hook \u2014 about 1/16 inch \u2014 so that the measurement is correct whether you hook it over an edge or push it against a surface. When you hook it over the end of a board, the hook slides out and the zero starts at the outside of the hook. When you push it against a wall for an inside measurement, the hook slides in and the zero starts at the inside face. Either way, the reading is right.</p>\n<p>For an <strong>outside measurement</strong>, hook the end over the edge and pull the blade taut \u2014 not so hard that it stretches or bows, just snug. For an <strong>inside measurement</strong>, push the hook flat against one surface and read where the blade meets the other \u2014 or use the case: most tape cases have their length printed on them (often 3 inches), so you can butt the case against the wall, read the blade, and add the case length. The hook must be clean and undamaged: a bent hook gives a wrong zero, and every measurement after that is wrong by the same amount.</p>\n<p>The most common measuring error is not the hook \u2014 it is the sag. A blade held out over a long span sags in the middle and reads long. For long runs, have a second person hold the far end, or measure in shorter sections and add them. And always measure from a square edge: measuring from a crooked cut gives a crooked number.</p>"
