      "heading": "Steel Pipe: The Standard",
      "html": "\n<p><strong>Schedule 40 steel pipe</strong> — black iron pipe — is the traditional gas piping material. It is strong, rigid, and familiar to every inspector. Steel pipe is joined with <strong>threaded joints</strong>: the pipe ends are cut and threaded with a die, and the fittings are screwed on. The threads themselves do not seal the joint — the <strong>thread sealant</strong> does. For gas, use a sealant rated for fuel gas (a yellow gas-rated thread compound or gas-rated PTFE tape); ordinary white PTFE tape and pipe dope not rated for gas are not acceptable.</p>\n<p>Threading has rules. The threads must be clean and sharp, cut to the right depth, and free of burrs. The joint is made up wrench-tight — tight enough to seal, not so tight that the fitting cracks. A joint that is over-torqued can split a fitting, and a joint that is under-torqued will leak. After assembly, every joint is leak-tested (Module 5). Steel pipe must be protected where it passes through walls and where it could be damaged, and it must be supported: the IFGC support table calls for rigid metallic pipe to be supported about every 6 feet, depending on size.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The sealant seals the joint, not the threads. Clean threads, gas-rated sealant, and a wrench-tight makeup — then test every joint, because a threaded joint that looks tight can still leak.</div>\n<p>Steel pipe is used indoors and outdoors, above ground. It is not used underground without a listed protective coating and wrapping, because buried bare steel corrodes. Where steel runs underground, the code requires a listed coating, and the pipe must be protected from damage.</p>"
