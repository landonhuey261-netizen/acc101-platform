      "html": "\n<p><strong>CSST</strong> is flexible, corrugated stainless steel tubing with a yellow (or black, for arc-resistant types) jacket. It bends around obstacles without fittings, so a CSST run needs far fewer joints than a steel run — and every joint not made is a joint that cannot leak. CSST is joined with manufacturer-specific fittings: the tubing is cut square, the jacket is stripped back, and the fitting is assembled per the manufacturer's instructions, with a torque value that must be followed exactly.</p>\n<p>CSST has three rules that steel does not. <strong>First, support:</strong> CSST must be supported about every 4 feet, and protected where it passes through studs or joists with striker plates. <strong>Second, bonding:</strong> CSST must be bonded to the building's electrical grounding system, per the IFGC and the manufacturer's instructions — bonding gives lightning a path to ground that does not go through the thin tubing wall. <strong>Third, training:</strong> CSST may only be installed by a person trained and certified by the manufacturer, and the installation must follow that manufacturer's instructions exactly.</p>\n<p>CSST is used indoors for distribution piping and for appliance runs. It must not be used outdoors unless the manufacturer allows it and it is protected, and it must not be run where it can be damaged — in a garage, for example, it needs protection from vehicle impact and from nails and screws.</p>\n<div class=\"callout\"><strong>Key idea:</strong> CSST's advantage is fewer joints; its risk is lightning. Bond it to the grounding system, support it every 4 feet, protect it from damage, and follow the manufacturer's instructions to the letter.</div>"
