      "heading": "Natural Gas vs. Propane",
      "html": "\n<p>Natural gas arrives through a buried service line from the street main, through a <strong>meter</strong> that measures use, and into the building's piping. Its energy content is about <strong>1,000 Btu per cubic foot</strong> — the number the gas sizing tables use. A cubic foot is the unit the tables work in, and 1,000 Btu per cubic foot is the conversion that turns an appliance's Btu-per-hour rating into cubic feet per hour.</p>\n<p>Propane is stored as a liquid under pressure in a tank and vaporizes as it is used. Its energy content is much higher per unit volume: about <strong>2,500 Btu per cubic foot</strong> of vapor, or about 91,300 Btu per gallon of liquid. A propane system needs a <strong>regulator</strong> at the tank that drops the tank pressure to the low pressure the house piping uses, and often a second-stage regulator at the building. Propane appliances are built or converted for propane — a natural gas appliance will not burn propane correctly, and vice versa.</p>\n<p>The code that governs both is the <strong>International Fuel Gas Code (IFGC)</strong>, adopted in Michigan alongside the plumbing code, with NFPA 54 (the National Fuel Gas Code) as the parallel standard. The IFGC covers piping, sizing, venting, combustion air, testing, and purging. This course cites IFGC section numbers so you can look each rule up.</p>"
