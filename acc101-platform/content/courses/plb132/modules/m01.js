      "heading": "From the Meter to the Appliance",
      "html": "\n<p>Follow the gas through a house. The utility's service line enters to the <strong>meter</strong>, usually outside. From the meter, the <strong>building piping</strong> (the house line) runs to a <strong>manifold or trunk</strong>, then branches to each appliance. At each appliance there is a <strong>manual shutoff valve</strong> in the same room, within 6 feet of the appliance, upstream of the appliance connection. After the shutoff comes a <strong>sediment trap</strong> (drip leg) as close to the appliance inlet as practical, then a short <strong>flexible appliance connector</strong> (maximum 6 feet, one per appliance, staying in the same room) to the appliance itself.</p>\n<p>Gas pressure in a house is low. Residential service is typically delivered at about <strong>7 inches of water column</strong> (about 1/4 psi) at the meter, and the sizing tables are built for an inlet pressure of less than 2 psi with a pressure drop of 0.5 inch of water column across the system. That is why the pipes are large for the energy they carry: a furnace at 100,000 Btu per hour needs about 100 cubic feet of gas per hour, and moving 100 cubic feet per hour at a quarter of a psi takes a 3/4-inch or 1-inch pipe, not a 1/2-inch one.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Gas piping is sized by load and length, not by the appliance's pipe thread. A 1/2-inch inlet on an appliance does not mean a 1/2-inch pipe run will feed it — the table decides, and the table works from the total load and the longest run.</div>"
