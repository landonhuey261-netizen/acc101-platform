      "heading": "What Fuel Gas Is",
      "html": "\n<p><strong>Fuel gas</strong> is a gas burned for heat: in furnaces, boilers, water heaters, ranges, dryers, and fireplaces. The two fuel gases a plumber meets are <strong>natural gas</strong>, delivered by pipeline from the utility, and <strong>propane</strong> (LP gas, liquefied petroleum gas), delivered by truck and stored in a tank on the property. Both are hydrocarbons — molecules of carbon and hydrogen — and both burn cleanly when they get the right amount of air. Both are dangerous when they do not.</p>\n<p>Natural gas is mostly methane. It is lighter than air (specific gravity about 0.60), so a leak rises and disperses upward. Propane is heavier than air (specific gravity about 1.5), so a leak sinks and pools in low places — basements, pits, and floor drains. That single difference changes everything about leak response: a natural gas leak ventilates upward, a propane leak collects where you stand.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Natural gas rises; propane sinks. If you smell gas in a basement with a propane system, the gas may be pooling at your feet — do not switch on a light, do not use a phone, get out and call from outside.</div>\n<p>Both gases are odorless in their natural state, so the utility adds an <strong>odorant</strong> (a mercaptan compound) that smells like rotten eggs. The smell is the alarm system. If you smell it, there is a leak until proven otherwise.</p>"
