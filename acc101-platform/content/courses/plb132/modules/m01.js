      "heading": "Pressure, Measurement, and the First Safety Rules",
      "html": "\n<p>Gas pressure is measured in <strong>inches of water column (in. w.c.)</strong> for low-pressure systems and in <strong>psi</strong> for higher pressures. One psi equals about 27.7 inches of water column. A manometer — a U-tube of water — reads inches of water column directly, which is why the trade still uses the unit. A residential meter delivering 7 inches w.c. is delivering about 1/4 psi.</p>\n<p>The safety rules are absolute. <strong>Never</strong> use a flame to look for a gas leak — use soap solution or an electronic detector. <strong>Never</strong> work on a live gas line with an ignition source nearby. <strong>Always</strong> pressure-test new or altered piping before gas is introduced (Module 5). <strong>Always</strong> purge air from a new line outdoors or by the code's purging rules, never into a room. And <strong>always</strong> treat the smell of gas as an emergency: no switches, no phones, no flames — leave the building and call the utility from outside.</p>\n<p>Gas work also has a licensing boundary. In Michigan, fuel gas piping is part of the plumbing license's scope, and many jurisdictions require the work to be permitted and inspected. Know your local rules before you touch a gas line — and never work on a gas system you are not qualified and authorized to work on.</p>"
