      "heading": "Venting Gas Appliances",
      "html": "\n<p>Burning gas produces combustion gases, including carbon monoxide, that must leave the building. A <strong>Category I</strong> appliance — a standard atmospheric furnace, boiler, or water heater — vents by natural draft: hot gases rise through the appliance's flue, into the draft hood, and out through the vent connector to the chimney or vent. The vent connector must rise continuously toward the chimney, about 1/4 inch per foot, with no dips.</p>\n<p>Vent clearances are the same as for water heaters: a <strong>single-wall metal vent</strong> needs at least 6 inches from combustible materials; a <strong>Type B (double-wall) vent</strong> needs only 1 inch. The vent must terminate above the roof per the manufacturer's instructions and the code, and it must be sized to the appliance — an undersized vent spills combustion gases into the room, and an oversized vent lets them cool and condense inside the vent, which corrodes it.</p>\n<p><strong>Power-vented</strong> appliances use a fan to push exhaust out through a side wall, and <strong>direct-vent</strong> appliances draw combustion air from outdoors and vent outdoors through a sealed pipe. Both follow the manufacturer's instructions exactly — vent length, elbows, and termination clearances are set by the listing. Never mix vent types, and never vent a Category I appliance with a power vent it was not listed for.</p>"
