      "heading": "Combustion Air",
      "html": "\n<p>A burner needs air to burn gas completely. Without enough air, the flame burns yellow and sooty, produces carbon monoxide, and can roll out of the burner compartment. The code's standard method is simple: a space with gas appliances needs <strong>50 cubic feet of volume for every 1,000 Btu per hour</strong> of total appliance input. A 100,000-Btu furnace plus a 50,000-Btu water heater — 150,000 Btu per hour total — needs 7,500 cubic feet of space (150 × 50). A room 10 feet by 15 feet with an 8-foot ceiling is only 1,200 cubic feet — far too small, so that room needs combustion air openings to the outside or to a larger space.</p>\n<p>Combustion air comes from indoors, from outdoors, or both. Indoor air comes through openings to adjacent spaces. Outdoor air comes through ducts or openings to the outside, sized per the code — commonly one square inch of free area per 1,000 Btu per hour for a direct opening, or per the code's tables for ducted air. Direct-vent appliances do not need room combustion air, because they draw it from outdoors through their own pipe.</p>\n<p>Modern tight houses are the problem case. An old, leaky house supplied combustion air through its cracks. A new, air-sealed house does not — and a gas appliance in a tight house without a dedicated combustion air supply will starve, spill, or backdraft. When you install or service a gas appliance, check the combustion air before you check the burner.</p>\n<div class=\"callout\"><strong>Key idea:</strong> 50 cubic feet per 1,000 Btu per hour. If the room is smaller than that, the appliance needs combustion air from somewhere else — an opening, a duct, or a direct vent. A tight house is not a safe house for a gas burner without it.</div>"
