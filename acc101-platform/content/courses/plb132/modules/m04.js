      "heading": "Connecting an Appliance",
      "html": "\n<p>Every gas appliance gets the same connection set. <strong>First, the manual shutoff valve:</strong> in the same room as the appliance, within 6 feet of it, upstream of the appliance connection, and accessible without moving the appliance. <strong>Second, the sediment trap (drip leg):</strong> a capped tee downstream of the shutoff valve and as close to the appliance inlet as practical, catching dirt and moisture before it reaches the gas control. <strong>Third, the flexible appliance connector:</strong> a listed connector, maximum 6 feet long, one per appliance, staying entirely in the same room — never through a wall, floor, or ceiling.</p>\n<p>The connector is the last link, not a substitute for piping. It bridges the small gap between the fixed piping and the appliance so the appliance can be moved for service. It must be the right size for the appliance's load, and it must not be kinked, stretched, or coiled. A connector that is too long sags and stresses its fittings; a connector that is too short pulls on them.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Shutoff, sediment trap, connector — in that order, every appliance, every time. The shutoff lets you stop the gas; the trap protects the control; the connector lets you service the appliance.</div>\n<p>Appliances that move — ranges and dryers — use a connector that allows movement, and the connector must be long enough to pull the appliance out without disconnecting it. Stationary appliances — furnaces, boilers, water heaters — use a short connector or hard piping. Check the local code: some jurisdictions limit connectors on stationary appliances to 3 feet.</p>"
