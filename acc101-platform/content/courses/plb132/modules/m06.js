      "heading": "The Oil Burner",
      "html": "\n<p>The burner is a gun-type assembly with four working parts. The <strong>fuel pump</strong> draws oil from the tank and pressurizes it to about 100 psi. The <strong>nozzle</strong> atomizes the oil into a fine spray — the spray pattern and the flow rate are set by the nozzle's rating, stamped on its side. The <strong>electrodes</strong> make the spark that ignites the spray; the gap between them must be set to the manufacturer's specification, or the spark will be weak or misplaced. The <strong>primary control</strong> (the cad cell relay) watches the flame with a light-sensitive cell: if the flame is not established within a few seconds of the burner starting, the control locks the burner out.</p>\n<p>The burner also has an air adjustment — a shutter or a band that sets how much combustion air enters with the oil spray. Too little air makes a smoky, sooty flame; too much air cools the flame and wastes heat up the chimney. A combustion test (measuring CO2, stack temperature, and smoke) is how a technician sets the air correctly — by instrument, not by eye.</p>\n<p>Oil burners need annual service: a new nozzle, a new filter, cleaned electrodes, and a combustion test. A nozzle wears as oil passes through it — a worn nozzle sprays a different pattern and flow than its rating, and the burner drifts out of tune over a season.</p>"
