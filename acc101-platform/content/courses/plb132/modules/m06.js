      "html": "\n<p>Oil storage is a liability as much as a convenience. An above-ground tank sits in a basement or outside on a pad, with a fill pipe, a vent pipe, and a gauge. A buried tank is out of sight — and out of mind until it leaks. Oil leaks contaminate soil and groundwater, and the cleanup is expensive. The plumber's job is to spot the warning signs: a tank that is rusted, weeping, or sitting on a wet floor; a line that is kinked or corroded; a smell of oil in the basement.</p>\n<p>The <strong>supply line</strong> runs from the tank to the burner, usually in copper or coated steel, with a <strong>filter</strong> (a canister with a felt element) that catches water and dirt before they reach the pump. A two-pipe system returns unused oil to the tank; a one-pipe system does not. The filter is changed at annual service, and the tank is kept as full as practical — a tank that sits near empty condenses water inside, and water in the oil is the most common cause of a burner that will not stay lit.</p>\n<p>Oil lines must be protected from damage and from freezing, and the tank's vent must terminate outdoors where its fumes cannot enter the building. A tank that is overfilled spills oil — the fill pipe's whistle (which sounds while the tank fills and stops when it is full) is the delivery driver's signal to stop.</p>"
