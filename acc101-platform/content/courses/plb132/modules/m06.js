      "heading": "How an Oil System Works",
      "html": "\n<p>A fuel oil heating system burns liquid fuel oil in a burner to heat water (a boiler) or air (a furnace). The oil sits in a <strong>storage tank</strong> — above ground in a basement or outside, or buried underground — and is drawn through a supply line, a filter, and a pump to the <strong>burner</strong>. The burner's pump pressurizes the oil (typically to 100 psi) and pushes it through a <strong>nozzle</strong> that sprays it as a fine mist into the combustion chamber. An ignition spark lights the mist, and the flame heats the boiler water or the furnace air.</p>\n<p>No. 2 fuel oil is the standard residential heating oil. One gallon contains about <strong>140,000 Btu</strong> of heat. A burner nozzle is rated in <strong>gallons per hour (gph)</strong> at 100 psi — a 1.00-gph nozzle delivers 1 gallon per hour, or about 140,000 Btu per hour of input. The nozzle size is matched to the boiler or furnace: too large a nozzle over-fires the unit, too small under-fires it, and either one wastes fuel and soots the heat exchanger.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Oil is measured in gallons, gas in cubic feet — but the heat is the same Btu. A 1.00-gph oil nozzle and a 140,000-Btu gas input are the same size of fire, in different units.</div>\n<p>Oil systems are common in the Northeast and in rural areas without gas service. In Michigan they appear in older homes and in rural properties. The plumber who services them must understand the burner, because the burner is where the heat is made — and where the trouble starts.</p>"
