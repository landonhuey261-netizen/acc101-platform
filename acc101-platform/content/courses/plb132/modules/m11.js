      "html": "\n<p>Corrosive waste usually cannot go straight to the public sewer. Most jurisdictions require it to be <strong>neutralized</strong> first — brought to a pH the sewer can accept — in a <strong>neutralization tank</strong> (also called an acid neutralization tank). The tank holds limestone chips or another neutralizing medium: acid waste flows through the tank, the acid reacts with the limestone, and the waste that leaves the tank is near neutral. The tank is sized to the flow and to the strength of the acid, and its medium is consumed and must be replaced on a schedule.</p>\n<p>The neutralized waste then flows to the building drain and to the sewer, and the discharge must meet the local sewer authority's limits — usually a pH range and limits on specific chemicals. Some wastes can never go to the sewer at any pH: heavy metals, solvents, and some radioactive wastes must be collected and disposed of as hazardous waste. The plumber's duty is to build the system the design calls for and to make sure the discharge point is the one the permit allows.</p>\n<p>Traps and vents on a corrosive-waste system are made of the same resistant material as the pipe. A trap of ordinary cast iron in a polypropylene system is a weak link — the acid will find it. The whole wetted path, from the sink to the neutralization tank to the sewer, must be resistant.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The whole wetted path must be resistant — pipe, traps, vents, and the neutralization tank. One ordinary fitting in a corrosive line is the leak waiting to happen.</div>"
