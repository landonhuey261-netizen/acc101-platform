      "heading": "Joining and Supporting",
      "html": "\n<p>Corrosive-resistant piping is joined by the method its material demands. <strong>Glass</strong> is joined with beaded-end compression couplings — the glass is never threaded or solvent-welded. <strong>Polypropylene</strong> is joined by <strong>heat fusion</strong> (the pipe ends are heated and pressed together, forming one piece) or by mechanical joints with gaskets. <strong>PVDF</strong> is joined the same way. The joints must be made exactly as the manufacturer instructs: the wrong temperature, the wrong time, or a contaminated joint surface makes a weak fusion that will leak chemical waste.</p>\n<p>Support matters more than it does for ordinary DWV, because the materials are different: glass is heavy and fragile, so it is supported closely and cushioned; polypropylene expands and contracts with temperature more than metal does, so its supports must allow movement and its runs need expansion provisions. Hangers must not damage the pipe — no sharp edges, no over-tightened bands, and no contact with a dissimilar material that could corrode.</p>\n<p>Every corrosive-waste system is <strong>tested</strong> before it is put into service, and the test is done with water, not with chemicals. The system is filled, checked for leaks at every joint, and only then is the waste stream introduced. A leak in a corrosive-waste line is not a drip — it is a chemical spill.</p>"
