      "html": "\n<p>Ordinary DWV materials — cast iron, copper, PVC, and ABS — do not survive corrosive waste. The materials that do:</p>\n<p><strong>Borosilicate glass pipe</strong> is the classic laboratory drain material. It resists almost every acid, it is transparent (so a blockage can be seen), and it is joined with beaded ends and compression couplings. It is also fragile — it must be handled carefully, supported closely, and protected from impact.</p>\n<p><strong>Polypropylene (PP)</strong> is the workhorse of modern lab waste. It resists a wide range of acids and alkalis, it is joined by heat fusion or by mechanical (threaded or flanged) joints, and it is tough and light. <strong>PVDF (polyvinylidene fluoride)</strong> resists a wider range of chemicals than polypropylene, including stronger solvents, and is used where polypropylene is not enough — at a higher price.</p>\n<p><strong>Special cast iron and stainless steel</strong> serve in industrial waste where the waste is corrosive but not acidic enough to demand plastic or glass — for example, some high-temperature or abrasive industrial wastes. The choice is always driven by the chemical resistance chart and the temperature of the waste.</p>"
