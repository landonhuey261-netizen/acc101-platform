      "heading": "What Makes Waste Corrosive",
      "html": "\n<p>Most waste is mild: the water from a sink, a shower, or a toilet. <strong>Corrosive waste</strong> is different — it is waste that attacks ordinary pipe. It comes from <strong>laboratories</strong> (acids and chemicals poured down sinks), <strong>photo and print shops</strong> (developer and fixer), <strong>industrial processes</strong> (plating, etching, and metal finishing), and <strong>commercial kitchens</strong> in a milder form (hot grease and detergents, which is why grease interceptors exist — see plb131 Module 11). The chemicals in corrosive waste eat cast iron, dissolve copper, and soften ordinary plastic.</p>\n<p>The plumber's first job is to identify the waste. What chemicals, at what concentration, at what temperature, and how often? The answer comes from the building owner, the lab manager, or the process engineer — not from a guess. The chemical resistance of a pipe material is published by its manufacturer in a <strong>chemical resistance chart</strong>: a table that says, for each chemical and concentration, whether the material is suitable. Never choose a corrosive-waste material without checking the chart for the actual chemicals in the waste stream.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Corrosive waste is a chemistry problem before it is a plumbing problem. Identify the chemicals first, then check the manufacturer's chemical resistance chart — never guess a material.</div>\n<p>Corrosive waste is also a safety problem. Acids burn skin and eyes, and some chemical wastes give off fumes. The plumber works with gloves, eye protection, and ventilation, and never mixes chemicals — an acid and a base, or bleach and an acid, can react violently. The waste system itself must be vented and trapped like any other drainage system, so sewer gas and chemical fumes cannot enter the building.</p>"
