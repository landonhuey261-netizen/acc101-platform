      "html": "<p>A head injury is damage to the scalp, skull, or brain from a blow or a fall. The scalp bleeds a lot because it has many blood vessels — a scalp cut can look dramatic while the brain underneath is fine — but a blow hard enough to break the skull or shake the brain can cause a traumatic brain injury (TBI), where the brain itself is bruised, bleeding, or swelling inside a skull that cannot expand. Because the skull is rigid, bleeding or swelling inside it squeezes the brain, and that pressure can kill. The EMT cannot see inside the skull; the job is to recognise the warning signs, protect the airway and the spine, support breathing, and transport fast.</p>\n<p>Causes are everyday ones: falls (the most common cause in older adults and young children), car crashes, sports, assaults, and workplace accidents. A patient on blood-thinning medication, an older adult, or a young child deserves extra caution after a head injury, because bleeding inside the head can be worse and slower to show in these patients — always mention blood thinners in your handover.</p>"
