      "html": "<p>Shock is not a mood or a feeling — it is a state where the body's tissues are not getting enough blood flow, and therefore not enough oxygen. The heart may be pumping, but if there is too little blood, the pump is too weak, or the blood vessels have opened too wide, the tissues starve. Cells that do not get oxygen cannot do their work, and if shock goes on, organs start to fail. The EMT's job is to recognise shock early, find and treat the cause where possible, support breathing and circulation, and get the patient to hospital fast.</p>\n<p>Textbooks describe several types. Hypovolemic shock comes from too little fluid — most often blood loss, but also severe vomiting, diarrhoea, or burns. Cardiogenic shock comes from a failing pump — the heart cannot pump well after a heart attack or serious heart problem. Distributive shock comes from the vessels opening too wide, so blood pools instead of flowing — this includes septic shock from serious infection, anaphylactic shock from a severe allergic reaction, and neurogenic shock after a spinal cord injury. Obstructive shock comes from something blocking flow, such as a tension pneumothorax or a blood clot in the lungs. At EMT level, the type matters less than recognising the pattern and acting fast.</p>"
