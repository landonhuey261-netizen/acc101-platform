      "html": "<p>A <strong>tort</strong> is a civil wrong — an act that harms another person or their property, for which the law lets the victim sue for damages. Torts come in three families. <strong>Intentional torts</strong> are harms done on purpose: fraud, defamation (a false statement that damages a reputation), trespass, and interference with a contract. <strong>Negligence</strong> is harm caused by carelessness — the failure to use reasonable care. <strong>Strict liability</strong> is liability without fault: in some situations, the law holds a party liable even if they were careful, because the activity or product is so dangerous that the risk belongs to the one who profits from it.</p>\n<p>Businesses meet all three. A company that lies about a competitor's product commits an intentional tort. A store that leaves a spill unmarked for hours is negligent when a customer falls. A manufacturer whose product injures a user can face strict liability even if its quality control was excellent — which is why product liability, the next section, is the tort a product business fears most.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Torts are the law of \"you broke it, you pay for it\" — except strict liability, where the law says \"you made it, you pay for it\" even when you did nothing wrong.</div>"
