      "html": "<p><strong>Agency</strong> is the relationship in which one person, the <strong>agent</strong>, acts on behalf of another, the <strong>principal</strong>, and can bind the principal to contracts with third parties. Every business runs on agency: a store clerk sells the store's goods, a purchasing manager signs supply orders, a real-estate agent signs for a client. The agent's acts are the principal's acts — which is why the limits of an agent's authority are one of the most practical questions in business law.</p>\n<p>Agency is created by agreement, and it ends when the job is done, the agreement ends, or either side ends it. The agent owes the principal <strong>fiduciary duties</strong>: loyalty (act in the principal's interest, not your own), obedience (follow lawful instructions), care (do the job competently), and accounting (keep records of money handled). A purchasing agent who takes a kickback from a supplier breaches the duty of loyalty — and the principal can recover the kickback.</p>\n<div class=\"callout\"><strong>Key idea:</strong> An agent's signature is the principal's signature. Before you let anyone sign for your business, decide exactly what they may sign for — and write it down.</div>"
