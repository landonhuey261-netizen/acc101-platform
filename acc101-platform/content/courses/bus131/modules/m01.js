      "html": "<p>Most business disputes are <strong>civil law</strong>: one private party sues another for money or for an order to do (or stop doing) something. A supplier sues for an unpaid invoice; a customer sues over a defective product. The party who sues must prove their case by a <strong>preponderance of the evidence</strong> — more likely than not, just over 50%. The remedy is usually money, called <strong>damages</strong>.</p>\n<p><strong>Criminal law</strong> is different: the government prosecutes someone for an act the law defines as a crime, such as fraud or embezzlement, and the penalty can be a fine or imprisonment. The standard of proof is far higher — <strong>beyond a reasonable doubt</strong>. The same act can produce both: a bookkeeper who steals from the business can be prosecuted by the state and sued by the business for the money back.</p>\n<p><strong>Worked check:</strong> A customer sues a shop for $5,000 over a broken product. The customer must show it is more likely than not — say, 51% likely — that the shop is responsible. If the same facts were a fraud prosecution, the state would have to prove guilt beyond a reasonable doubt, a much higher bar. The same facts, two different standards, two different cases.</p>"
