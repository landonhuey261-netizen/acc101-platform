      "html": "<p>Contraction works by filaments sliding past each other. The steps are: <strong>1.</strong> A nerve signal reaches the muscle fiber and releases <strong>calcium</strong> inside the cell. <strong>2.</strong> Calcium uncovers the binding sites on the actin filaments. <strong>3.</strong> Myosin heads — tiny arms on the thick filaments — attach to actin, forming <strong>cross-bridges</strong>. <strong>4.</strong> Using energy from <strong>ATP</strong>, the myosin heads pull the actin filaments toward the center of the sarcomere, and the sarcomere shortens. <strong>5.</strong> ATP lets the myosin heads detach and reattach farther along, repeating the cycle — like a team rowing, pulling, releasing, and pulling again.</p>\n<p>When the nerve signal stops, calcium is pumped back into storage, the binding sites are covered again, and the muscle relaxes. Without ATP, myosin cannot detach — which is why, after death, muscles stiffen (rigor mortis) until the proteins break down.</p>\n"
