      "html": "<p>The heart beats because of an electrical signal that starts in the <em>sinoatrial node</em> (SA node), the heart's natural pacemaker, and spreads through the muscle. <em>Bradycardia</em> is a slow heart rate (below 60 beats per minute in an adult at rest); <em>tachycardia</em> is a fast heart rate (above 100 beats per minute at rest). <em>Arrhythmia</em> is any abnormal rhythm. <em>Atrial fibrillation</em> is a common arrhythmia in which the atria quiver instead of beating in an organized way, so the heartbeat becomes irregular.</p><p><em>Fibrillation</em> of the ventricles — <em>ventricular fibrillation</em> — is a life-threatening emergency: the ventricles quiver and pump no blood, so the person collapses and needs CPR and a defibrillator immediately. <em>Asystole</em> means no electrical activity at all — a flat line. <em>Palpitations</em> are the feeling of a racing, pounding, or skipping heartbeat. A <em>pacemaker</em> is a small device implanted to keep the heart beating at a steady rate when the natural pacemaker fails.</p><div class=\"callout\"><strong>Key idea:</strong> Brady- means slow, tachy- means fast. Bradycardia and tachycardia are the same word with opposite prefixes — and the same trap as hyper- and hypo-.</div>"
