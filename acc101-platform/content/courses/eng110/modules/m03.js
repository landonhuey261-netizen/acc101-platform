      "html": "<p>A metaphor says one thing is another: 'Hope is the thing with feathers.' A simile says one thing is like another: 'My love is like a red, red rose.' The difference is small — a single word, 'like' or 'as' — and it matters. A simile announces the comparison and keeps the two things apart; a metaphor collapses them, and for a moment the reader believes the identity. When Dickinson says hope is a bird, she does not say it is like a bird; she says it is one, and the poem's world becomes a world in which hope has feathers and sings. That is the metaphor's power: it does not compare, it transforms.</p>\n<p>Both devices have the same parts: the tenor, the thing being described, and the vehicle, the thing it is described as. In 'hope is a bird,' hope is the tenor and the bird is the vehicle. A good metaphor chooses a vehicle that gives the tenor something it did not have: the bird gives hope wings, song, and fragility. A bad metaphor chooses a vehicle that gives nothing: 'love is a rose' is tired because the rose has given love everything it can, a thousand times. When you write a metaphor, ask what the vehicle gives the tenor — and whether it gives something new.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Metaphor says one thing is another; simile says it is like another. The metaphor collapses the two — and transforms the world.</div>"
