      "html": "<p>Imagery can be literal or figurative. Literal imagery describes what is actually there: 'the red door,' 'the wet street,' 'the smell of bread.' Figurative imagery describes one thing in terms of another: 'the door is a mouth,' 'the street is a river,' 'the smell of bread is a memory.' Both are imagery, and both do the same job — they make you sense something — but figurative imagery does a second job: it makes you think. When a poet calls a street a river, you see the street and you think about flow, about being carried, about drowning.</p>\n<p>The test of an image is not whether it is pretty but whether it is true to the experience. A bad image is one that sounds poetic but does not fit: 'the moon was a silver coin' is a cliché because it has been used a thousand times and no longer makes you see the moon. A good image surprises you and then seems inevitable: 'the moon was a thumbnail, bitten to the quick' makes you see the moon's shape and feel a small, human anxiety. Perrine's rule is simple: an image should appeal to the senses and it should be fresh — it should make you see the thing as if for the first time.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Literal imagery describes what is there; figurative imagery describes one thing as another — and a good image surprises, then seems inevitable.</div>"
