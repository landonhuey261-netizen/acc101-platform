      "html": "<p><strong>Blood pressure</strong> is the force of blood against the walls of the arteries, measured in millimeters of mercury (mmHg) and written as a fraction: systolic over diastolic. The <strong>systolic</strong> pressure (the top number) is the pressure when the heart squeezes and pushes blood out. The <strong>diastolic</strong> pressure (the bottom number) is the pressure when the heart relaxes between beats. A reading of 120/80 means a systolic pressure of 120 mmHg and a diastolic pressure of 80 mmHg.</p><p>The categories used in the United States (from the American College of Cardiology and American Heart Association, 2017) are: <strong>normal</strong> — below 120/80; <strong>elevated</strong> — systolic 120–129 and diastolic below 80; <strong>stage 1 hypertension</strong> — systolic 130–139 or diastolic 80–89; <strong>stage 2 hypertension</strong> — systolic 140 or higher or diastolic 90 or higher. A single high reading does not diagnose hypertension — the diagnosis needs repeated readings over time — but a very high reading, or a high reading with symptoms such as chest pain, severe headache, or trouble breathing, must be reported immediately.</p>"
