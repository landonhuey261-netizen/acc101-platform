      "html": "<p>Two heart emergencies are often confused, and the difference matters. A <strong>heart attack</strong> happens when blood flow to part of the heart muscle is blocked; the person is usually awake, in pain, and breathing. <strong>Cardiac arrest</strong> happens when the heart stops pumping blood: the person collapses, does not respond, and stops breathing normally. A heart attack can lead to cardiac arrest, but they are not the same thing — and only cardiac arrest needs CPR.</p><p>Cardiac arrest is a race against time. When the heart stops, blood stops moving, and the brain begins to die within minutes. Survival falls by about 7–10% for every minute without CPR and defibrillation, which is why the first few minutes — before the ambulance arrives — are the minutes that decide the outcome. CPR does not restart the heart on its own; it keeps blood moving to the brain and heart until a defibrillator or professionals can restore a normal rhythm.</p>"
