      "html": "<p><strong>Hands-only CPR</strong> is CPR without rescue breaths, and it is what the American Heart Association recommends for bystanders who are not trained in rescue breathing. The steps: <strong>Call 911</strong> and send someone for the AED — if you are alone with an unresponsive adult, call 911 and get the AED first, then start compressions. Place the person on their back on a firm, flat surface. Kneel beside them, put the heel of one hand on the center of the chest, on the lower half of the breastbone, put your other hand on top, interlock your fingers, and keep your arms straight with your shoulders over your hands.</p><p>Push hard and fast: <strong>100 to 120 compressions per minute</strong>, at least <strong>2 inches (5 cm) deep</strong> for an adult — the full AHA range is 2 to 2.4 inches (5–6 cm) — and let the chest come fully back up between compressions (<strong>full recoil</strong>), because the heart refills while the chest rises. Keep going until the AED arrives, the person starts breathing normally or moving, or professionals take over. If you get tired, switch with another trained person about every 2 minutes, keeping the pause under 10 seconds.</p><div class=\"callout\"><strong>Key idea:</strong> Push hard (2–2.4 inches) and fast (100–120 per minute), in the center of the chest, and let the chest come fully back up. Keep interruptions under 10 seconds.</div>"
