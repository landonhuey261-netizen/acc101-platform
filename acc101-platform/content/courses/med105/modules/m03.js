      "html": "<p>Before you can give a breath, the airway must be open. In an unconscious person, the tongue falls back and blocks the throat — the most common cause of a blocked airway. The <strong>head-tilt, chin-lift</strong> fixes this: place one hand on the forehead and gently tilt the head back, then lift the chin with the fingertips of your other hand. This lifts the tongue away from the back of the throat and opens the airway. Use this whenever there is no suspected spine injury.</p><p>If a spine injury is suspected — for example after a fall from a height or a car crash — use the <strong>jaw thrust</strong> instead: kneel at the top of the person's head, place your fingers behind the angles of the jaw, and lift the jaw forward without moving the neck. The jaw thrust opens the airway without tilting the head, so it is the safer choice when the spine may be injured. In either case, look inside the mouth only if you can see an object — never do a blind finger sweep, because you can push an object deeper or injure the mouth.</p>"
