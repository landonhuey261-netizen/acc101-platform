      "html": "<p>Trained rescuers add <strong>rescue breaths</strong> to compressions. The cycle for an adult is <strong>30 compressions to 2 breaths</strong>, repeated. After 30 compressions, open the airway with the head-tilt, chin-lift, pinch the nose closed, seal your mouth over the person's mouth (or use a pocket mask or face shield), and give a breath that lasts about <strong>1 second</strong> — just enough to make the chest visibly rise. Then give a second breath the same way, and go straight back to compressions. The whole pause for two breaths should be under 10 seconds.</p><p>Give only enough air to make the chest rise. Too much air, or breaths given too forcefully, push air into the stomach, which can cause vomiting — and a vomiting patient can choke. If the chest does not rise, reposition the head and try again; if it still does not rise, there may be an obstruction, and you should return to compressions. If you are not trained in rescue breaths, or you do not have a barrier device and do not want to give mouth-to-mouth, hands-only CPR is still the right thing to do — compressions alone are far better than nothing.</p><div class=\"callout\"><strong>Key idea:</strong> 30 compressions, then 2 breaths of about 1 second each — just enough to make the chest rise. The pause for breaths stays under 10 seconds.</div>"
