      "html": "<p>Two numbers decide whether a business's customer strategy works. <strong>Customer acquisition cost (CAC)</strong> is what it costs to win one new customer — advertising, discounts, sales time. <strong>Customer lifetime value (LTV)</strong> is the total profit a customer brings over the whole relationship. A healthy business earns far more from a customer than it spent to win them; a common rule is that LTV should be at least three times CAC.</p>\n<p><strong>Worked example:</strong> A subscription box spends $40 to acquire each customer (CAC = $40). Each customer stays an average of 12 months, paying $20 a month with $10 of cost per month, for a profit of $10 a month — so LTV = 12 × $10 = <strong>$120</strong>. The LTV-to-CAC ratio is $120 ÷ $40 = <strong>3 to 1</strong> — exactly at the healthy threshold. If customers left after 6 months, LTV would be $60 and the ratio would be 1.5 to 1, and the business would be spending too much to win customers who leave too soon.</p>\n<p>The fix for a weak ratio is rarely more advertising. It is keeping customers longer — better service, a better product, a reason to return — because every extra month of a customer's life is pure LTV with no new CAC.</p>"
