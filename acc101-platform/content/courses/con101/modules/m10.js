      "html": "<p>Back injuries are the most common construction injury, and they come from lifting wrong, lifting too much, and lifting alone. The safe lift has four steps: <strong>size up the load</strong> before touching it \u2014 how heavy is it, where is its center, is the path clear; <strong>get help or equipment</strong> if it is too heavy, too big, or awkward; <strong>lift with your legs</strong>, keeping your back straight, the load close to your body, and your feet positioned for balance; and <strong>move smoothly</strong>, never twisting while carrying \u2014 turn with your feet, not your waist.</p>\n<p>Two people carry long material \u2014 pipe, lumber, rebar \u2014 one at each end, walking in step and calling out obstacles. A dolly, a hand truck, or a cart beats a carry whenever the load is heavy or the distance is long. Team lifts are planned: both lifters agree on the count, the path, and where the load goes down before anyone lifts. And the golden rule: if it feels too heavy, it is too heavy. Nobody is impressed by a hernia.</p>\n<p>Repetitive strain matters too. A lift done badly once can injure you; a lift done badly a hundred times a day will injure you. Vary the task, stretch, take the help offered, and report a sore back early \u2014 a strain reported on day one is a week off; a strain hidden for a month can be a career-ending injury.</p>"
