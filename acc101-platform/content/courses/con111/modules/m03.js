      "html": "<p>Oxyfuel cutting does not melt steel the way a weld does — it burns it. The torch's flame preheats the steel to its ignition temperature, about 1,650°F, until the spot glows red. Then a jet of pure oxygen is pressed through the torch, and the oxygen reacts with the hot iron in a rapid exothermic reaction — the iron itself burns, and the burning iron blows out of the cut as slag. The torch moves along, and the cut follows.</p>\n<p>That is why oxyfuel cutting works on carbon and low-alloy steels but not on aluminum or stainless steel. Iron oxide melts below the melting point of steel, so the burning iron flows out of the kerf. Aluminum and stainless form oxides that melt far above the base metal, so the oxide seals the cut shut instead of flowing out. The chemistry decides what can be cut, not the operator's skill.</p>\n<p>The cut quality depends on the preheat, the oxygen pressure, the tip size, and the travel speed. Too slow and the cut is wide and rough with a heavy slag coating; too fast and the cut does not go through, leaving an uncut edge. A good cut is narrow, straight, and nearly slag-free on the bottom — and it comes from the right settings, not from force.</p>\n"
