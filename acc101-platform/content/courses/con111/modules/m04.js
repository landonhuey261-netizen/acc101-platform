      "html": "<p>SMAW — shielded metal arc welding, or stick welding — uses a flux-coated rod and an electric arc. The welder holds the rod in an electrode holder, strikes an arc between the rod tip and the work, and the arc melts the rod and the base metal together into a weld pool. The rod is consumed as it welds: it gets shorter as the metal is deposited, and the welder feeds it forward to keep the arc length steady.</p>\n<p>The flux coating does three jobs at once. As it burns, it makes a shielding gas that keeps oxygen and nitrogen out of the molten pool, it forms a slag blanket over the cooling weld that protects it and shapes it, and it adds alloying elements to the weld metal. When the weld cools, the slag is chipped off — and a weld with its slag still on it has not been inspected, because the slag hides the bead underneath.</p>\n<p>Stick welding is the rugged process. It works outdoors in wind, on dirty or rusty steel, in all positions, with a simple machine and no gas bottle. That is why it is the construction site's process: the machine is portable, the setup is simple, and the welds hold up in the field.</p>\n"
