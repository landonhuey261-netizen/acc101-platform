      "html": "<p>FCAW — flux-cored arc welding — looks like MIG: a wire feeds through a gun, an arc melts it, and a weld pool forms. The difference is inside the wire. A flux-core wire is hollow, filled with flux — the same kind of flux that coats a stick electrode. As the wire melts, the flux makes shielding gas and a slag blanket, just like stick welding. The wire is stick welding's flux, delivered like MIG's wire.</p>\n<p>Because the flux makes its own shielding, flux core can work without a gas bottle. That is the <strong>self-shielded</strong> type, FCAW-S — also called gasless flux core or by the trade name Innershield. It is the outdoor process: wind cannot blow away shielding that is made inside the arc itself. The <strong>gas-shielded</strong> type, FCAW-G — also called Dual Shield — adds an external shielding gas as well, for cleaner, stronger welds on thicker steel in the shop and in the field.</p>\n<p>Flux core is the bridge between stick and MIG. It has stick's tolerance for wind and dirty steel and MIG's speed and continuous wire. On a construction site, it is the process for structural steel outdoors, for thicker plate, and for work where MIG's gas would blow away and stick would be too slow.</p>\n"
