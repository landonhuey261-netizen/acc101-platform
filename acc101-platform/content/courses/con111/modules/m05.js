      "heading": "The Three Controls",
      "html": "<p>Every stick weld is controlled by three things, and only three: <strong>arc length</strong>, <strong>travel speed</strong>, and <strong>electrode angle</strong>. Arc length is the gap between the rod tip and the work — about one rod diameter. Travel speed is how fast the rod moves along the joint. Electrode angle is how the rod is tilted — the work angle across the joint and the travel angle along it. Change any one of them and the bead changes.</p>\n<p>Arc length is the most sensitive of the three. A long arc makes a wide, flat bead with spatter and poor shielding; the arc wanders and the puddle cools. A short arc that drags makes a narrow, high bead that can trap slag. The right arc is short and steady, with the rod tip just above the puddle, and the welder holds it by feeding the rod forward as it burns down.</p>\n<p>Travel speed sets the bead size. Too fast and the bead is narrow and ropy, with poor fusion at the toes — the weld sits on the surface instead of melting into it. Too slow and the bead is wide and high, with a risk of overlap and slag trapping. The right speed keeps the puddle about twice as wide as the rod, moving steadily forward.</p>\n"
