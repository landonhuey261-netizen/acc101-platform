      "html": "<p>The <strong>work angle</strong> is the rod's tilt across the joint — for a fillet weld, 45 degrees between the two plates, so the arc heats both sides equally. Tilt too far to one side and that side melts while the other stays cold, giving a bead that fuses to one plate and not the other. The <strong>travel angle</strong> is the rod's tilt along the direction of travel — for stick welding, the rod is dragged at about 15 to 20 degrees behind the direction of travel, pulling the puddle along.</p>\n<p>Stick welding is a drag process: the rod points back toward the finished bead, and the arc pushes the puddle forward. Pushing a stick rod — pointing it ahead of the puddle — makes a shallow, wide bead with slag running ahead of the arc, which traps slag in the weld. The rule is drag, do not push, for stick and flux core; MIG is the process that can push.</p>\n<p>The angles change with the joint. A butt joint wants the rod centered. A fillet wants 45 degrees. A lap joint wants the angle biased toward the bottom plate. The welder sets the angle by looking at the puddle: if one toe is not fusing, the angle is wrong on that side.</p>\n"
