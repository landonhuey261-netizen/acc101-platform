      "html": "\n<p><strong>Compression faucets</strong> are the oldest type: two handles, each turning a threaded stem that presses a rubber <strong>washer</strong> down onto a metal <strong>seat</strong>. Tighten the handle and the washer seals; loosen it and water flows. The washer wears out, so compression faucets drip from the spout — the fix is a new washer, and sometimes a reseated or replaced seat.</p>\n<p><strong>Ball faucets</strong> are single-handle, common in kitchens. A slotted metal or plastic <strong>ball</strong> sits over spring-loaded rubber seats; moving the handle rotates the ball to align its slots with the hot and cold inlets. Leaks come from worn springs, seats, or the ball itself, and from the O-rings around the cap. Repair kits with new springs, seats, and O-rings fix most of them.</p>\n<p><strong>Cartridge faucets</strong> are single- or two-handle and use a movable <strong>cartridge</strong> — a cylinder with ports that align as you turn or lift the handle. A worn cartridge leaks or gets stiff; the fix is to pull the cartridge out and replace it with an exact match. Cartridges are brand- and model-specific, so take the old one to the supply house.</p>\n<p><strong>Ceramic disc faucets</strong> are the modern standard: two hard ceramic discs slide over each other, and their aligned holes meter the water. The discs almost never wear out; leaks usually come from the neoprene inlet seals under the disc cartridge. They are smooth, durable, and the most expensive to buy — and the cheapest to own over time.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Compression = washer on a seat. Ball = slotted ball on spring seats. Cartridge = replaceable cylinder. Ceramic disc = two sliding discs. Name the mechanism and you know the repair.</div>"
