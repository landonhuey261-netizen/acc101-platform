      "html": "\n<p>Accessible design means a person using a wheelchair, a walker, or with limited strength or reach can use a restroom safely and independently. The plumber's part is the heights, the clearances, and the controls: where the fixture sits, how high it is, how much room is around it, and whether its controls can be worked with one hand without tight grasping, pinching, or twisting.</p>\n<p>Two documents carry the numbers. <strong>ICC A117.1, Accessible and Usable Buildings and Facilities</strong>, is the technical standard the plumbing and building codes reference. The <strong>ADA Standards for Accessible Design</strong> carry the same numbers for buildings covered by the Americans with Disabilities Act. On most jobs the numbers match; where they differ, the local code and the designer's drawings govern — and the plumber installs what the drawings and the adopted code require.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Only the fixtures a building designates as accessible must meet these numbers — but the plumber must know which ones those are before rough-in, because moving a drain after the floor is poured is a different job entirely.</div>\n<p>Accessible fixtures are not special fixtures. They are ordinary fixtures — water closets, lavatories, showers — installed at accessible heights with accessible clearances and controls. The skill is in the rough-in, not in a different catalog.</p>"
