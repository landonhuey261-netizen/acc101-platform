      "html": "\n<p>An accessible water closet seat must sit <strong>17 to 19 inches above the finished floor</strong> — the \"chair height\" that lets a person transfer from a wheelchair. A standard residential seat is about 15 to 16 inches, so an accessible water closet is a taller fixture (or a standard fixture on a raised base), and its drain rough-in must match the taller model.</p>\n<p>The water closet centerline must be <strong>16 to 18 inches from the side wall</strong>, so the grab bar and the transfer space land in the right place. The clear floor space in front is at least <strong>56 inches deep for a wall-hung</strong> water closet and <strong>59 inches for a floor-mounted</strong> one, measured from the rear wall. The wheelchair-accessible compartment must be at least <strong>60 inches wide</strong>.</p>\n<p><strong>Grab bars</strong> mount horizontally on the side wall and the rear wall, <strong>33 to 36 inches above the finished floor</strong> measured to the top of the gripping surface, with 1-1/2 inches of clearance between the bar and the wall. The side-wall bar must be at least 42 inches long; the rear-wall bar at least 36 inches long. Flush controls must be on the open side of the water closet and operable with one hand without tight grasping — a lever, not a knob.</p>\n<div class=\"callout\"><strong>Key idea:</strong> 17–19-inch seat, 16–18-inch centerline, 33–36-inch grab bars, 60-inch compartment. Those four numbers are the accessible water closet in one breath.</div>"
