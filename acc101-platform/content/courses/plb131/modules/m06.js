      "html": "\n<p>An accessible lavatory rim or counter surface must be no higher than <strong>34 inches above the finished floor</strong>. Below it, knee and toe clearance must be provided: the knee space must be at least <strong>27 inches high</strong>, 30 inches wide, and 8 inches deep at the minimum, so a wheelchair user can roll forward under the basin. The drain and supply pipes under the basin must be insulated or guarded so they cannot burn or cut the user's legs.</p>\n<p>Faucets on accessible lavatories must be operable with one hand without tight grasping, pinching, or twisting, and without more than 5 pounds of force. Lever handles, push buttons, and sensor faucets meet this; round knobs that must be gripped and twisted do not. The faucet must also be reachable — no more than 48 inches above the floor for a forward reach over an obstruction, and the reach depth is limited by the obstruction's depth.</p>\n<p>Mirrors above accessible lavatories must have their bottom edge no more than <strong>40 inches above the floor</strong>. Dispensers, dryers, and other accessories must be within reach range — generally no higher than 48 inches — and must not protrude into the clear floor space.</p>"
