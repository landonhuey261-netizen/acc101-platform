      "heading": "Reading a Fixture Schedule",
      "html": "\n<p>A <strong>fixture schedule</strong> is a table on the plumbing drawings. Each row is one fixture type, identified by a <strong>mark</strong> — WC-1, LAV-1, SH-1, and so on — and each row gives the manufacturer and model, the mounting, the rough-in, the supply sizes, the drain and trap sizes, and any accessories. The plan shows where each mark goes; the schedule says what it is. You cannot install from the plan alone, and you cannot order from the schedule alone — the two documents work together.</p>\n<p>Read a schedule row the way you read a recipe: left to right, one column at a time. <strong>Mark</strong> tells you which fixture on the plan. <strong>Description</strong> tells you the type. <strong>Manufacturer and model</strong> tell you what to order. <strong>Mounting</strong> tells you floor, wall, or counter. <strong>Rough-in</strong> tells you the drain and supply locations. <strong>Connections</strong> tell you the pipe sizes. <strong>Notes</strong> tell you the exceptions — accessible, high-efficiency, or a special finish.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The schedule is the contract. If the schedule and the plan disagree, stop and ask the designer — never guess which one is right, and never install from memory.</div>\n<p>Common schedule marks: WC for water closet, LAV for lavatory, SK for sink, BT for bathtub, SH for shower, UR for urinal, DF for drinking fountain, WH for water heater, FD for floor drain. A mark with a number (WC-1, WC-2) means more than one type of that fixture is on the job — read the number, not just the letters.</p>"
