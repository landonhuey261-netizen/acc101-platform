      "html": "\n<p>Three documents run every fixture job. The <strong>rough-in dimension</strong> is the measurement from a fixed reference — usually the finished wall or finished floor — to the center of the drain or supply connection. The standard water closet rough-in is 12 inches from the finished wall to the center of the closet flange; 10-inch and 14-inch models exist for tight or old spaces. Measure rough-in from the <em>finished</em> wall, never from bare studs, and never include baseboard in the measurement.</p>\n<p>The <strong>fixture unit</strong> is the code's way of rating how much load a fixture puts on the water or drainage system. On the drainage side these are <strong>drainage fixture units (DFU)</strong>: in IPC Table 702.1 a private 1.6-gpf water closet is 3 DFU, a lavatory is 1 DFU, a bathtub or shower is 2 DFU, a kitchen sink is 2 DFU, a dishwasher is 2 DFU, and a clothes washer is 3 DFU. Water supply uses a different set of <strong>water supply fixture units (WSFU)</strong>. Never mix the two tables.</p>\n<p>The <strong>fixture schedule</strong> is the table on the drawings that lists every fixture by mark (WC-1, LAV-2, and so on), with its manufacturer, model, mounting, rough-in, supply sizes, and drain sizes. Module 12 walks a real schedule line by line. Until then, remember: the schedule is the contract. If the schedule says a 12-inch rough-in and the wall moved, you stop and ask — you do not guess.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Rough-in is measured to the finished surface. A wall that gains tile or a floor that gains tile changes the number. Confirm finished surfaces before you set a flange or a carrier.</div>"
