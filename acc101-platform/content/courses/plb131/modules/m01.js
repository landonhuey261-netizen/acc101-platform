      "html": "\n<p>A <strong>plumbing fixture</strong> is any device that is connected to the water supply, the drainage system, or both, and that delivers water or receives waste. A lavatory faucet delivers water. A water closet receives waste. A bathtub does both. Pipes, fittings, and valves are not fixtures — they serve fixtures. If a customer can see it, touch it, and use it, it is almost certainly a fixture.</p>\n<p>Every fixture sits at the meeting point of two systems you studied in earlier courses. Clean water arrives through the <strong>water distribution system</strong> at pressure. Used water leaves through the <strong>drainage system</strong> by gravity. The fixture is the controlled opening between those two worlds, and its job is to let water in and waste out without letting the two mix — and without letting sewer gas come back into the room.</p>\n<div class=\"callout\"><strong>Key idea:</strong> A fixture is the only part of the plumbing system most customers ever see. They judge your whole trade by how fixtures look, feel, and work — which is why fixture work is both the most visible and the most fussed-over part of the job.</div>\n<p>Fixtures also carry a health job. A drinking fountain, a hand-washing lavatory, and a flushing water closet all protect public health when they are installed to code. A badly installed fixture can cross-connect clean water with waste, splash, leak inside a wall, or leave a trap dry. This course teaches the install so the health job holds.</p>"
