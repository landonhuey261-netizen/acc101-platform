      "html": "\n<p>Fixtures fall into families by what they do. <strong>Water closets</strong> (toilets) flush waste to the drain. <strong>Lavatories</strong> are bathroom hand-washing basins. <strong>Sinks</strong> are kitchen, laundry, and service basins, usually deeper and built for work. <strong>Bathtubs and showers</strong> are bathing fixtures. <strong>Urinals</strong> serve commercial restrooms. <strong>Drinking fountains and water coolers</strong> deliver drinking water. <strong>Bidets</strong> wash with water. Each family has its own rough-in dimensions, trap sizes, and fixture-unit values, so learning the families is learning the map of this course.</p>\n<p>Beyond the families, fixtures split by <strong>mounting</strong>: floor-mounted (most water closets), wall-hung (many commercial water closets and urinals, carried by a steel carrier inside the wall), and countertop or deck-mounted (lavatories and sinks). Mounting decides the rough-in: a floor-mounted water closet needs a closet flange in the floor, while a wall-hung one needs a carrier set in the framing before the wall is closed.</p>\n<p>Fixtures also split by <strong>material</strong>: vitreous china is the standard for water closets, lavatories, and urinals because it is smooth, hard, and easy to clean; cast iron and steel with enamel coatings appear in tubs and sinks; acrylic and fiberglass are light and common in tubs and shower bases; stainless steel rules commercial kitchens. Material matters because it decides weight, handling, and how the fixture is sealed and supported.</p>\n<div class=\"callout\"><strong>Key idea:</strong> When you meet a new fixture, ask three questions: what family is it, how is it mounted, and what is it made of? Those three answers tell you the rough-in, the support, and the seal.</div>"
