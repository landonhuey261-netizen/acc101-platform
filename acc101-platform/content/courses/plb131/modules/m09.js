      "html": "\n<p><strong>Running toilet.</strong> The fill valve runs constantly or cycles on and off (the \"phantom flush\"). First check the flapper: drop food coloring in the tank and wait 15 minutes without flushing — color in the bowl means the flapper leaks. Check the chain: too short and it holds the flapper open; too long and it tangles. Check the water level: it should sit about 1 inch below the overflow tube; a level above the overflow sends water straight down the drain. Check the fill valve: a valve that will not shut off needs cleaning or replacement.</p>\n<p><strong>Weak flush.</strong> Check the tank water level first — a low level means a weak flush. Then check the rim wash holes and the siphon jet for mineral buildup; clean them with a wire or a descaling solution. Check the flapper's lift: a flapper that drops too fast releases water too slowly to start the siphon. Check the vent: a blocked vent can slow the drain and weaken the flush.</p>\n<p><strong>Leak at the base.</strong> Water at the base means the wax ring has failed, the flange is below the floor, or the closet bolts are loose. Tightening the bolts is a temporary patch at best — and overtightening cracks the base. The real fix is to pull the fixture, inspect the flange, and set a new wax ring. Water at the tank-to-bowl joint means the tank bolts or the tank-to-bowl gasket need attention.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The dye test is the fastest diagnosis in plumbing. Fifteen minutes and a few drops of food coloring will tell you whether a flapper leaks — no tools, no disassembly, no guessing.</div>"
