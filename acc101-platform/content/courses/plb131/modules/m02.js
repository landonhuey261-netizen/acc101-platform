      "html": "\n<p>A water closet does two things in about three seconds: it washes the bowl and it moves waste through the trap and into the drain. The tank holds the flush water. When you push the handle, the <strong>flapper</strong> (or canister seal) lifts and water rushes into the bowl through two paths: the <strong>rim wash</strong>, which rinses the bowl surface through holes under the rim, and the <strong>siphon jet</strong>, a hole at the front bottom of the bowl that pushes water into the trapway and starts the siphon.</p>\n<p>The bowl's built-in <strong>trapway</strong> is a curved passage cast into the fixture. As water rises in the bowl, it spills over the trapway's high point — the <strong>weir</strong> — and the falling water pulls the bowl contents behind it by siphon action. The trapway holds a standing water seal afterward, usually about 2 inches deep, which blocks sewer gas. That seal is the same idea as a P-trap under a sink, built into the fixture itself.</p>\n<div class=\"callout\"><strong>Key idea:</strong> A flush is a controlled flood. The tank must deliver enough water fast enough to start the siphon; a slow trickle into the bowl will never flush, no matter how much water eventually arrives.</div>\n<p>Modern water closets use <strong>1.28 gallons per flush (gpf)</strong> or 1.6 gpf. Federal law caps new water closets at 1.6 gpf. A 1.28-gpf model is a high-efficiency toilet (HET). The lower the water use, the more the bowl design matters — glazed trapways and tuned jets are what let 1.28 gallons do the work that once took 3.5 or more.</p>"
