      "html": "\n<p>The <strong>rough-in</strong> is the distance from the finished wall to the center of the closet flange: 12 inches is standard, with 10-inch and 14-inch models for nonstandard spaces. Measure from the <em>finished</em> wall — tile and baseboard count. The supply stub-out typically sits about 8 inches above the finished floor and about 6 inches to the left of the centerline (viewed facing the fixture), though you should always check the manufacturer's drawing for the model on the schedule.</p>\n<p>IPC 405.3.1 sets the clearances. A water closet must sit at least <strong>15 inches from its centerline to any side wall, partition, vanity, or other obstruction</strong>, and at least <strong>30 inches center to center</strong> between adjacent fixtures. There must be at least <strong>21 inches of clear space in front</strong> of the water closet to any wall, fixture, or door. A floor-mounted water closet compartment must be at least 30 inches wide and 60 inches deep; a wall-hung compartment at least 30 inches wide and 56 inches deep.</p>\n<p>The drain for a water closet is 3 inches minimum (IPC Table 702.1 gives a 3-inch minimum trap and trap arm). The closet flange must sit on top of the finished floor — the flange should be about 1/4 inch above the finished floor surface so the wax ring compresses fully. A flange set below the floor is the classic cause of a leak that rots the subfloor.</p>\n<div class=\"callout\"><strong>Key idea:</strong> 12-inch rough-in, 15-inch side clearance, 21-inch front clearance, 3-inch drain, flange 1/4 inch above the finished floor. Those five numbers settle most water closet layout arguments.</div>"
