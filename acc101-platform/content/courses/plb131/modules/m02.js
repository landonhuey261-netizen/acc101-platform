      "html": "\n<p><strong>Gravity tank water closets</strong> are the residential standard: a tank above the bowl, gravity does the work, quiet and simple to repair. <strong>Pressure-assisted</strong> models add a sealed air vessel inside the tank; compressed air drives the flush harder, which helps in commercial settings and in homes with chronic weak flushes — at the cost of noise and pricier parts.</p>\n<p><strong>Flushometer-valve water closets</strong> have no tank. A flushometer valve connected to a large water supply line meters a fixed volume of water directly into the bowl. They are the commercial standard because they flush fast, recover instantly, and have no tank to refill — but they need a 1-inch (or larger) supply line and adequate pressure, so they are rare in houses. <strong>Wall-hung</strong> water closets mount on a carrier in the wall with the tank or flushometer concealed; they make floor cleaning easy and set the bowl at the accessible height.</p>\n<p>Bowls come in two shapes: <strong>round front</strong> (shorter, fits small rooms) and <strong>elongated</strong> (longer, more comfortable, and the standard for accessible fixtures). Seats follow the bowl shape — a round seat on an elongated bowl will not fit, and vice versa.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Match the type to the job: gravity tank for most houses, pressure-assisted or flushometer where the flush must be strong and fast, wall-hung where cleaning and accessibility drive the design.</div>"
