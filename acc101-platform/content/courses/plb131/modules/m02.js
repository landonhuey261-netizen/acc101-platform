      "html": "\n<p><strong>Step 1 — Prepare.</strong> Shut off the water, drain the old fixture if replacing one, and inspect the closet flange: it must be solid, level, and anchored to the floor. Clean off old wax completely. Set the <strong>closet bolts</strong> in the flange slots, parallel to the wall, and hold them upright with a dab of putty or a bolt cap.</p>\n<p><strong>Step 2 — Set the wax ring.</strong> Place a new wax ring (or wax-free seal) on the flange — or on the horn of the bowl, per the product's instructions — never reuse an old one. The wax ring is the seal between the bowl outlet and the drain; it works by compression, and once compressed it cannot be reset.</p>\n<p><strong>Step 3 — Set the bowl.</strong> Lower the bowl straight down over the bolts, using the bolts as guides. Press down evenly with your body weight to compress the wax. Do not rock or twist the bowl after it touches the wax — moving it breaks the seal, and the only fix is a new ring and another try.</p>\n<p><strong>Step 4 — Secure and connect.</strong> Add the washers and nuts and tighten by hand, then snug with a wrench in small alternating turns. Do not overtighten — a cracked base is a ruined fixture and a flooded floor. Trim the bolts, cap them, connect the supply line to the fill valve, set the tank (on a two-piece model), fill, and flush several times while watching the base and every connection for leaks.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The wax ring gets one chance. If the bowl moves after setting, pull it, scrape the wax, and start over with a new ring. A reused or disturbed ring is a leak waiting for the first flush.</div>"
