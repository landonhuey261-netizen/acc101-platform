      "heading": "The Trap: A Water Seal Against Sewer Gas",
      "html": "\n<p>Every fixture must be separately trapped by a liquid-seal trap — IPC 1002.1 — except as the code otherwise permits. A <strong>trap</strong> is a U-shaped (or S-shaped) fitting that holds a standing body of water, the <strong>trap seal</strong>, in its bend. Drainage flows through the seal; sewer gas cannot flow back through it, because gas cannot pass a wall of water. The trap is the only thing between a bathroom and the sewer, and it works silently for years — until it loses its seal.</p>\n<p>IPC 1002.4 sets the seal depth: not less than <strong>2 inches</strong> and not more than <strong>4 inches</strong>, except for deeper seals in special designs for accessible fixtures. A seal shallower than 2 inches is too easily lost; a seal deeper than 4 inches drains sluggishly and can clog. The fixture outlet must sit close to the trap: the vertical distance from the fixture outlet to the trap weir must not exceed 24 inches, and the horizontal distance must not exceed 30 inches, measured from the fixture outlet centerline to the trap inlet centerline.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The trap seal is a wall of water. Anything that removes the water — evaporation, siphonage, or a blast of pressure — removes the wall, and sewer gas walks straight into the room.</div>\n<p>Traps lose their seal four ways. <strong>Evaporation:</strong> a floor drain in an unused room dries out over weeks. <strong>Siphonage:</strong> a fixture draining nearby pulls the seal out through the vent — the reason vents exist. <strong>Backpressure:</strong> a surge in the drain pushes the seal out the other way. <strong>Capillary action and leaks:</strong> a rag or a hair in the trap wicks water out, or a cracked trap leaks it away. IPC 1002.4.1 requires trap seal protection — a primer valve, a deeper seal, or another approved method — for emergency floor drains and traps subject to evaporation.</p>"
