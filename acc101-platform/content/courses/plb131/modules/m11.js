      "html": "\n<p>A <strong>grease interceptor</strong> (grease trap) is a box that separates fats, oils, and grease (FOG) from wastewater before the water enters the drain. Kitchen wastewater flows into the interceptor, slows down, and the grease — which is lighter than water — floats to the top while food solids sink to the bottom. The clarified water in the middle flows out to the drain. The interceptor is cleaned on a schedule: the floating grease and the settled solids are removed before they reach the outlet.</p>\n<p>IPC 1003 requires a grease interceptor wherever food is prepared and grease could enter the drainage system — restaurants, cafeterias, commercial kitchens, and food-processing areas. A home kitchen does not need one. Interceptors come in two forms: a small <strong>hydromechanical grease interceptor</strong> (a grease trap) under or near a sink, rated by flow in gallons per minute, and a large <strong>gravity grease interceptor</strong> (a grease trap tank) buried outside, rated by capacity in gallons and by retention time.</p>\n<p>Sizing follows the fixture load and the code's tables: the interceptor must be large enough to hold the wastewater long enough for the grease to separate. An undersized interceptor passes grease into the drain, where it cools, hardens, and blocks the pipe — and a blocked grease line is one of the most expensive drain calls in commercial plumbing. The interceptor must also be accessible for cleaning: a buried tank with no access is a tank that never gets cleaned.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Grease is a drain's worst enemy because it is liquid in the sink and solid in the pipe. The interceptor's whole job is to catch it while it is still warm and floating.</div>"
