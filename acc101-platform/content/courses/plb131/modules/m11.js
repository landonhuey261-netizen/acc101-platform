      "html": "\n<p>The standard trap is the <strong>P-trap</strong>: a U-bend with a horizontal outlet arm to the vented drain. It is self-scouring, easy to clean, and the default for every fixture. An <strong>S-trap</strong> has a vertical outlet that drops straight into the floor; it is prone to self-siphonage and is prohibited in new work under the IPC — if you find one, it is a candidate for replacement. A <strong>drum trap</strong> is a can-shaped trap found in old tubs; it holds a large volume of water, clogs easily, and is also prohibited in new work. A <strong>bottle trap</strong> is a compact, decorative trap used on exposed lavatories; it is allowed where listed, but it holds a small seal and clogs more easily than a P-trap.</p>\n<p>IPC 1002.3 prohibits traps that depend on moving parts to maintain the seal, bell traps, crown-vented traps, and traps with interior partitions (except listed corrosion-resistant ones). The rule behind the list is simple: a trap must be a simple water seal with no moving parts to fail and no hidden chamber to clog.</p>\n<p>Each fixture gets its own trap. The code allows limited exceptions — a combination sink with compartments no more than 6 inches different in depth and waste outlets no more than 30 inches apart may share a trap, and a grease interceptor may serve as the trap for a single fixture — but the default is one fixture, one trap.</p>"
