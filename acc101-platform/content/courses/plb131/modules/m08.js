      "heading": "Thermal Expansion and the Expansion Tank",
      "html": "\n<p>Water expands as it heats. In an open system, the expanded water pushes back into the street main. But most modern systems are <strong>closed</strong>: a pressure-reducing valve, a check valve, or a backflow preventer stops water from flowing backward. In a closed system, the expanding water has nowhere to go, so the pressure climbs — sometimes high enough to drip the T&P valve, damage fixtures, or shorten the heater's life.</p>\n<p>The code's answer is a <strong>thermal expansion tank</strong> (IPC 607.3): a small tank with a rubber bladder and a cushion of air, installed on the cold-water line near the heater. When water heats and expands, it compresses the air cushion instead of raising the system pressure. The tank must be sized to the system and its air charge set to match the house water pressure — a tank charged to 40 psi on a 60-psi system does half its job.</p>\n<p>Signs of an expansion problem: the T&P valve drips after every heating cycle, the pressure gauge climbs well above the static pressure when the heater fires, or fixtures drip at night. The fix is an expansion tank (or a replacement tank if the bladder has failed), not a higher-pressure T&P valve — the relief valve is a safety device, never a pressure regulator.</p>\n<div class=\"callout\"><strong>Key idea:</strong> A dripping T&P valve usually means the system has no place for expansion to go — not that the valve is bad. Check for a closed system and a working expansion tank before you replace the valve.</div>"
