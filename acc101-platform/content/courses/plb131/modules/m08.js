      "heading": "Venting a Gas Water Heater",
      "html": "\n<p>A gas water heater's burner produces combustion gases — including carbon monoxide — that must leave the building. A standard atmospheric (Category I) gas heater vents by natural draft: hot gases rise through the center flue, into the <strong>draft hood</strong> on top, and out through the <strong>vent connector</strong> to the chimney or vent. The vent connector must rise continuously toward the chimney — a common rule is at least 1/4 inch of rise per foot of horizontal run — with no dips where gases could stall.</p>\n<p>Vent clearances matter. A <strong>single-wall metal vent</strong> must be at least 6 inches from combustible materials; a <strong>Type B (double-wall) vent</strong> needs only 1 inch, because its outer wall stays cooler. The vent must terminate above the roof per the manufacturer's instructions and the code, with the right height above the roofline so wind does not push exhaust back down. Never vent a gas appliance into a room, an attic, or a crawl space, and never share a vent with an appliance it was not sized for.</p>\n<p>Power-vented and direct-vent heaters are different: a power vent uses a fan to push exhaust out through a side wall, and a direct vent draws combustion air from outdoors and vents outdoors through a sealed pipe. Both follow the manufacturer's instructions exactly — vent length, elbows, and termination clearances are set by the listing, not by habit.</p>\n<div class=\"callout\"><strong>Key idea:</strong> Venting is a life-safety system. A blocked, undersized, or wrongly sloped vent can spill carbon monoxide into the house. If the vent is wrong, the heater does not run — fix the vent first.</div>"
