      "html": "<p>Lifting is the most common cause of injury in EMS, and the power lift is the technique that prevents it. The power lift is simple: stand close to the load, feet shoulder-width apart, one foot slightly forward, back straight, knees bent, and lift with the legs, keeping the load close to the body. Tighten the stomach muscles, keep the back straight, and lift smoothly — no twisting, no jerking, and no lifting while bent over. If the load is too heavy, too awkward, or the patient is on the floor in a tight space, do not lift alone: call for more help, use a slide sheet or a scoop stretcher, or move the patient in stages.</p>\n<p>Before any lift, plan it: agree who lifts which end, count together, and lift on the same count. Check the route is clear, the stretcher is at the right height and locked, and the wheels are locked before you load. Keep the patient covered and secure with straps, and tell the patient what is happening — a patient who is lifted without warning tenses up and makes the lift harder. And look after your own back: a crew member who is injured cannot help the next patient.</p>"
