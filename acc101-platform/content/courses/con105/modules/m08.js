      "html": "<p>Curing is keeping fresh concrete moist and at the right temperature so hydration can continue. Concrete gains most of its strength in the first week, and hydration needs water — if the concrete dries out, hydration stops and the strength stops with it. A slab that is cured well is stronger, less permeable, and far less likely to crack than a slab left to dry in the sun.</p>\n<p>The standard is to keep concrete moist for at least 7 days. That does not mean soaking it forever; it means not letting the surface dry out while the reaction is running. The first 24 to 48 hours matter most, because that is when the surface is forming, and a surface that dries in the first day never recovers its strength.</p>\n<p>Curing is not optional and it is not expensive. Water, a cover, or a sprayed compound costs almost nothing compared with the concrete itself, and it is the difference between a slab that lasts decades and one that dusts and cracks in its first year. The pour is not finished when the finishing is done — it is finished when the curing is done.</p>"
