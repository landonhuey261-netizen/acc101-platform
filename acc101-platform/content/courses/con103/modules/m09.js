      "html": "<p>Every spec section follows the same three-part format: <strong>Part 1 \u2014 General</strong>, <strong>Part 2 \u2014 Products</strong>, and <strong>Part 3 \u2014 Execution</strong>. Part 1 covers the scope, the referenced standards, the submittals required, and the quality assurance (who tests what, and to what standard). Part 2 names the products: the manufacturer, the model, the material, and the performance requirements. Part 3 says how the work is done: the preparation, the installation, the tolerances, and the protection of the finished work.</p>\n<p>Read a spec the way you read a recipe: Part 1 is the introduction, Part 2 is the ingredients, and Part 3 is the method. A concrete spec's Part 2 will name the mix \u2014 the compressive strength (3,000 psi, 4,000 psi), the slump, the air content \u2014 and Part 3 will say how it is placed, finished, and cured. A door spec's Part 2 will name the door and the hardware; Part 3 will say how the door is hung and adjusted. The spec is where the quality standard lives: a drawing shows a concrete slab, but the spec says the slab is 4,000 psi concrete, cured for 7 days, with a flatness tolerance of 1/8 inch in 10 feet.</p>\n<p>Two kinds of spec language matter: <strong>prescriptive</strong> specs say exactly what to use (\"provide a 3'-0\" x 6'-8\" solid-core wood door by Manufacturer X\"), and <strong>performance</strong> specs say what the result must be (\"provide a door with a sound rating of STC 35\"). A prescriptive spec is easy to follow and hard to substitute; a performance spec lets the contractor propose an equal product, and the designer decides whether it is equal. The spec will say which kind it is, and whether substitutions are allowed.</p>"
