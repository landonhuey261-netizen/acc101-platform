      "html": "<p>The most important tool of a structural ironworker is the <strong>spud wrench</strong>. It is a wrench with two jobs: one end is a wrench that turns bolts, and the other end tapers to a point — the spud — that slides into a bolt hole to pull two steel members into alignment so the holes line up. A beam arriving from the crane is almost never perfectly lined up; the spud end levers the holes together, and then the wrench end tightens the bolt. One tool does both halves of the connection.</p>\n<p>When a spud is not enough, the ironworker reaches for pins. A <strong>bull pin</strong> is a tapered steel pin, thick in the middle and pointed at both ends, driven into a bolt hole to pull the members into line. A <strong>drift pin</strong> is a similar tapered pin used the same way. The pins go in first to align the holes, the bolts follow, and the pins come out as the bolts go in. The <strong>beater</strong> is the mallet used to drive the pins: a forged steel head on a hickory handle, swung to tap a pin home — never to strike a wrench, a bolt, or a hardened tool, because striking the wrong thing chips steel and sends fragments flying.</p>\n<p>The <strong>sleever bar</strong>, also called a connecting bar, is a long steel alloy bar used to pry. When a beam needs to move a little more than a spud can manage, the sleever bar gives the leverage to shift it. It is a prying tool, not a hammer and not a cheater bar: never use a pipe or bar as an extension on a wrench handle to force a bolt, because the extra leverage can snap the wrench or the bolt and throw you off balance at height.</p>\n"
