      "heading": "Weld Defects — What Goes Wrong and Why",
      "html": "<p>A good weld is smooth, even, and fused to both sides of the joint. The defects are the ways it fails to be that. <strong>Porosity</strong> is gas holes in the bead, from a damp rod, dirty steel, or wind blowing the shield away. <strong>Undercut</strong> is a groove eaten into the base metal at the toe of the weld, from too much amperage or too long an arc. <strong>Overlap</strong> is weld metal rolling over the toe without fusing, from traveling too slowly. <strong>Slag inclusion</strong> is slag trapped inside the weld, from welding over a pass that was not cleaned. <strong>Lack of fusion</strong> is the weld metal not melting into the base metal or the previous pass, from too little heat or a bad angle. And a <strong>crack</strong> is a break in the weld or the metal beside it — the worst defect of all, because a crack grows under load.</p>\n<p>Every defect has a cause, and the cause is the fix. Porosity means dry the rods and clean the steel. Undercut means turn the heat down and shorten the arc. Overlap means speed up. Slag inclusion means stop and clean between passes. Lack of fusion means check the heat and the angle. A crack means stop welding, tell the foreman, and let the inspector and the engineer decide what happens next — a cracked weld is never welded over and forgotten.</p>\n<p>Two more habits prevent defects before they start. First, clean the joint: mill scale, rust, paint, and oil all make bad welds. Second, never strike the arc on the base metal away from the joint — an <strong>arc strike</strong> leaves a small hard, brittle spot that can start a crack. Strike the arc in the joint, where the weld will cover the mark.</p>\n"
