      "html": "<p>Lighting a torch has one safe order. Open the fuel valve slightly, light the gas with a <strong>striker</strong> — never a lighter or a match in the hand — then add oxygen until the flame turns neutral. A <strong>backfire</strong> is a loud pop when the flame snaps back into the torch; a <strong>flashback</strong> is worse, the flame burning back into the torch and hoses, and it can reach the regulators. Flashback arrestors — devices fitted at the torch and the regulators — stop a flashback from traveling further, and they are checked and replaced on schedule, not removed when they get in the way.</p>\n<p>Acetylene has a hard limit: never run it above 15 PSI working pressure, because above that pressure acetylene can decompose and explode inside the hose without any oxygen at all. That number is not a suggestion — it is the rule every torch hand learns first. The other hard rule is the fire watch: hot work needs combustibles cleared from the area, a fire watch posted, and the watch kept for at least 30 minutes after the cutting stops, because sparks can smolder hidden in a crack before flaming up.</p>\n<p>To cut, preheat the edge of the steel until it glows, press the oxygen lever, and move at a steady speed. Too slow, and the cut goes wide and rough with heavy slag on the bottom. Too fast, and the cut does not go through. To stop, release the oxygen lever, then shut down in order: close the oxygen cylinder valve first, then the fuel cylinder valve, bleed the lines, and back off the regulators. The same order every time — no shortcuts, because the shortcut is where the accident hides.</p>\n"
