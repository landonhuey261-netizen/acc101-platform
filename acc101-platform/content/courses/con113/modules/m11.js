      "heading": "How Oxyfuel Cutting Works",
      "html": "<p>An oxyfuel torch does not melt steel the way a welder does. It burns it. First the <strong>preheat flame</strong> — fuel gas and oxygen burning together — heats a spot on carbon steel until it reaches its kindling temperature, the point where steel will burn in pure oxygen. Then the cutter presses the oxygen lever, and a jet of pure oxygen hits the hot spot. The steel burns, turning to iron oxide, and the oxygen jet blows the molten slag out of the cut. The torch moves along, and the cut follows.</p>\n<p>That is why oxyfuel cutting works on carbon steel and not on stainless steel or aluminum: those metals form a crust of oxide that blocks the burning, so the cut stalls. It is also why the cut is called a <strong>kerf</strong> — the slot the burning removes — and why the underside of a good cut has thin, straight drag lines of slag, while a bad cut has heavy slag stuck to the bottom edge.</p>\n<p>The preheat flame must be <strong>neutral</strong>: one crisp inner cone, neither feathery with extra fuel nor short and hissing with extra oxygen. A carburizing flame (feathery, too much fuel) adds carbon to the steel; an oxidizing flame (short and hissing, too much oxygen) burns the edge. Set the flame neutral, hold the tip at the right distance, and move at a steady speed, and the cut is clean.</p>\n"
