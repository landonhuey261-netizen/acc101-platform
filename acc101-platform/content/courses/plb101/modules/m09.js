      "html": "<p>A <strong>work order</strong> is the job in writing: who the customer is, where the job is, what the problem is, what has been promised, and any parts or notes from the office. Read it fully before you drive to the job — the difference between a good day and a wasted trip is usually one line you skipped: the gate code, the \"dog in the yard,\" the \"water must be off before arrival,\" or the part that is already on the truck.</p>\n<p>Pull out four things from every work order: <strong>(1) the customer</strong> — name, phone, and how to reach them; <strong>(2) the problem in the customer's words</strong> — what they see and hear, not your diagnosis yet; <strong>(3) the location and access</strong> — address, where the fixture or equipment is, how to get in; <strong>(4) the scope</strong> — what was promised, what was not, and what parts or permits are involved. If anything is unclear, call the office or the customer before you leave — a two-minute call beats a one-hour round trip.</p>\n<p>On arrival, confirm the problem yourself. Customers describe symptoms, not causes: \"the toilet runs\" could be a flapper, a fill valve, or a cracked overflow tube. Your job is to verify, diagnose, and then explain — in that order.</p>\n<div class=\"callout\"><strong>Key idea:</strong> The work order is the job's contract. Read it, confirm it on site, and never promise more than it says without checking.</div>"
